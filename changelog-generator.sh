#!/usr/bin/env bash
# changelog-generator.sh
# Bounty #1: Generate structured CHANGELOG.md from git history
# Usage: bash changelog-generator.sh [output_file]

set -e

OUTPUT="${1:-CHANGELOG.md}"
REPO_DIR="${2:-.}"

cd "$REPO_DIR"

# Get latest tag, fallback to first commit
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || git rev-list --max-parents=0 HEAD)
echo "[*] Last tag / base: $LAST_TAG"

# Detect categories from commits
CAT_ADDED=""
CAT_FIXED=""
CAT_CHANGED=""
CAT_REMOVED=""
CAT_OTHER=""

while IFS= read -r line; do
    commit_hash=$(echo "$line" | cut -d' ' -f1)
    commit_msg=$(echo "$line" | cut -d' ' -f2-)
    commit_msg_lower=$(echo "$commit_msg" | tr '[:upper:]' '[:lower:]')

    if echo "$commit_msg_lower" | grep -qE '^(feat|add|new|feature|implement|create|introduce)'; then
        CAT_ADDED="$CAT_ADDED\n- $commit_msg"
    elif echo "$commit_msg_lower" | grep -qE '^(fix|bug|hotfix|patch|correct|resolve|repair)'; then
        CAT_FIXED="$CAT_FIXED\n- $commit_msg"
    elif echo "$commit_msg_lower" | grep -qE '^(refactor|update|change|modify|improve|optimize|migrate)'; then
        CAT_CHANGED="$CAT_CHANGED\n- $commit_msg"
    elif echo "$commit_msg_lower" | grep -qE '^(remove|delete|drop|deprecate|revert)'; then
        CAT_REMOVED="$CAT_REMOVED\n- $commit_msg"
    else
        CAT_OTHER="$CAT_OTHER\n- $commit_msg"
    fi
done < <(git log "$LAST_TAG..HEAD" --oneline --no-merges 2>/dev/null || echo "")

# Version and date
VERSION=$(git describe --tags --abbrev=0 2>/dev/null || echo "0.1.0")
DATE=$(date +%Y-%m-%d)

# Generate CHANGELOG
cat > "$OUTPUT" << EOF
# Changelog

## [$VERSION] - $DATE

### Added
$(echo -e "$CAT_ADDED" | grep -v '^$' || echo "  (none)")

### Fixed
$(echo -e "$CAT_FIXED" | grep -v '^$' || echo "  (none)")

### Changed
$(echo -e "$CAT_CHANGED" | grep -v '^$' || echo "  (none)")

### Removed
$(echo -e "$CAT_REMOVED" | grep -v '^$' || echo "  (none)")

### Other
$(echo -e "$CAT_OTHER" | grep -v '^$' || echo "  (none)")

---
*Generated by changelog-generator.sh — Bounty #1*
EOF

echo "[OK] CHANGELOG generated at $OUTPUT ($(wc -l < "$OUTPUT") lines)"
echo ""
echo "Sample output:"
head -20 "$OUTPUT"
