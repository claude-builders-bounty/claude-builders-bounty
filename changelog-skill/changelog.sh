#!/usr/bin/env bash
# changelog.sh — generates a structured CHANGELOG.md from git history.
#
# Collects commits since the last git tag, auto-categorizes them into
# Added / Fixed / Changed / Removed, and writes a Keep-a-Changelog style file.
#
# Usage:
#   bash changelog.sh                     # auto: since last tag, version = Unreleased
#   bash changelog.sh --version v1.2.0    # name the section explicitly
#   bash changelog.sh --since v1.0.0      # explicit range start
#   bash changelog.sh --out docs/CHANGELOG.md
#   bash changelog.sh --repo /path/to/repo
#   bash changelog.sh --dry-run           # print to stdout, write nothing
#   bash changelog.sh --help
#
# Exit codes: 0 OK, 1 usage/environment error, 2 not a git repository.

set -uo pipefail

VERSION="Unreleased"
SINCE=""
OUT="CHANGELOG.md"
REPO="."
DRY_RUN=0
DATE="$(date -u +%Y-%m-%d)"

usage() {
	sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
	case "$1" in
		--version) VERSION="${2:-}"; shift 2 ;;
		--since) SINCE="${2:-}"; shift 2 ;;
		--out) OUT="${2:-}"; shift 2 ;;
		--repo) REPO="${2:-}"; shift 2 ;;
		--dry-run) DRY_RUN=1; shift ;;
		--help|-h) usage; exit 0 ;;
		*) echo "changelog.sh: unknown option '$1' (try --help)" >&2; exit 1 ;;
	esac
done

if [ ! -d "$REPO/.git" ] && ! git -C "$REPO" rev-parse --git-dir >/dev/null 2>&1; then
	echo "changelog.sh: '$REPO' is not a git repository" >&2
	exit 2
fi

# Range start: explicit --since, else the most recent tag, else the first commit.
if [ -z "$SINCE" ]; then
	SINCE="$(git -C "$REPO" describe --tags --abbrev=0 2>/dev/null || true)"
fi
if [ -n "$SINCE" ]; then
	RANGE="$SINCE..HEAD"
	RANGE_NOTE="since $SINCE"
else
	RANGE="HEAD"
	RANGE_NOTE="entire history (no tags found)"
fi

# One commit per line: "<short sha>\t<subject>"; merge commits skipped.
COMMITS="$(git -C "$REPO" log "$RANGE" --no-merges --pretty=format:%h%x09%s 2>/dev/null || true)"

if [ -z "$COMMITS" ]; then
	echo "changelog.sh: no commits found ($RANGE_NOTE)" >&2
fi

# Categorization: conventional-commit type first (scope and ! allowed, e.g.
# "feat(api)!: drop v1"), keyword heuristics second. Each commit lands in
# exactly one section; unmatched commits go to Changed.
categorize() {
	local subject="$1"
	local lower ctype
	lower="$(printf '%s' "$subject" | tr '[:upper:]' '[:lower:]')"
	# type(scope)!: description  ->  type     (scope and bang are optional)
	ctype="$(printf '%s' "$lower" | sed -n 's/^\([a-z][a-z0-9_-]*\)\(([^)]*)\)\{0,1\}!\{0,1\}:.*/\1/p')"
	case "$ctype" in
		feat|feature|add|added) echo "Added"; return ;;
		fix|bugfix|hotfix) echo "Fixed"; return ;;
		remove|removed|revert|drop|delete|deprecate) echo "Removed"; return ;;
		refactor|perf|docs|chore|style|test|build|ci|change|changed|update|bump|rename|move) echo "Changed"; return ;;
	esac
	# Keyword heuristics for free-form subjects.
	case "$lower" in
		*fix*|*bug*|*"napraw"*|*"popraw"*) echo "Fixed"; return ;;
		*add*|*new*|*"dodaj"*|*"dodal"*|*"nowy"*|*"nowe"*) echo "Added"; return ;;
		*remove*|*delete*|*drop*|*"usun"*) echo "Removed"; return ;;
	esac
	echo "Changed"
}

ADDED=""; FIXED=""; CHANGED=""; REMOVED=""
while IFS=$'\t' read -r sha subject; do
	[ -z "$subject" ] && continue
	section="$(categorize "$subject")"
	line="- ${subject} (${sha})"
	case "$section" in
		Added) ADDED="${ADDED}${line}"$'\n' ;;
		Fixed) FIXED="${FIXED}${line}"$'\n' ;;
		Changed) CHANGED="${CHANGED}${line}"$'\n' ;;
		Removed) REMOVED="${REMOVED}${line}"$'\n' ;;
	esac
done <<EOF
$COMMITS
EOF

count_total=0
count_total=$((count_total + $(printf '%s' "$ADDED" | grep -c '^- ' || true)))
count_total=$((count_total + $(printf '%s' "$FIXED" | grep -c '^- ' || true)))
count_total=$((count_total + $(printf '%s' "$CHANGED" | grep -c '^- ' || true)))
count_total=$((count_total + $(printf '%s' "$REMOVED" | grep -c '^- ' || true)))

render() {
	printf '# Changelog\n\n'
	printf 'All notable changes to this project are documented in this file.\n\n'
	printf 'Generated by `changelog.sh` from git history (%s).\n\n' "$RANGE_NOTE"
	printf '## [%s] - %s\n\n' "$VERSION" "$DATE"
	if [ -n "$ADDED" ]; then printf '### Added\n\n%s\n' "$ADDED"; fi
	if [ -n "$FIXED" ]; then printf '### Fixed\n\n%s\n' "$FIXED"; fi
	if [ -n "$CHANGED" ]; then printf '### Changed\n\n%s\n' "$CHANGED"; fi
	if [ -n "$REMOVED" ]; then printf '### Removed\n\n%s\n' "$REMOVED"; fi
	if [ "$count_total" -eq 0 ]; then printf '_No commits found in this range._\n\n'; fi
}

if [ "$DRY_RUN" -eq 1 ]; then
	render
else
	render > "$OUT"
	printf 'changelog.sh: wrote %s (%d commits, %s)\n' "$OUT" "$count_total" "$RANGE_NOTE"
fi
exit 0
