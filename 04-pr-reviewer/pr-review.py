#!/usr/bin/env python3
"""AI PR Reviewer — Structured Markdown output."""
import subprocess, sys, re

def get_diff():
    if len(sys.argv) > 1:
        with open(sys.argv[1]) as f:
            return f.read()
    return subprocess.run(
        "git diff origin/main...HEAD 2>/dev/null || git diff HEAD~1..HEAD",
        shell=True, capture_output=True, text=True
    ).stdout

def analyze(diff):
    files = set()
    issues = []
    for line in diff.split("\n"):
        if line.startswith("diff --git"):
            m = re.search(r"b/(.+)", line)
            if m:
                files.add(m.group(1))
        if "console.log" in line or "console.debug" in line:
            issues.append(f"- Debug: {line.strip()[:80]}")
        if "TODO" in line or "FIXME" in line or "HACK" in line:
            issues.append(f"- TODO/FIXME: {line.strip()[:80]}")
        if re.search(r'(password|secret|api_key|token)\s*=\s*["\x27]', line):
            issues.append("- SECURITY: possible hardcoded secret")
    return sorted(files), issues[:15]

files, issues = analyze(get_diff())

out = f"""# AI PR Review

## Summary
- Files changed: {len(files)}
- Issues found: {len(issues)}

## Changed Files
"""
for f in files:
    out += f"- `{f}`\n"

if issues:
    out += "\n## Issues\n"
    for i in issues:
        out += f"{i}\n"
else:
    out += "\n## No Issues Found\n"

out += "\n## Suggestions\n- Run tests before merging\n- Check for breaking changes\n- Verify migrations are reversible\n"
out += "\n---\n*Generated by PR Reviewer Agent*"

print(out)
with open("REVIEW.md", "w") as f:
    f.write(out)
print("\nSaved to REVIEW.md")
