#!/usr/bin/env python3
"""Auto-generate a structured CHANGELOG.md from git history.

Usage:
    python changelog.py [--repo /path/to/repo] [--output CHANGELOG.md]
    Or symlink: ln -s changelog.py /usr/local/bin/generate-changelog
"""

import subprocess
import sys
import re
from datetime import datetime
from pathlib import Path

CATEGORIES = {
    "Added": [r"^add", r"^new", r"^feat", r"^create", r"^introduce", r"^implement"],
    "Fixed": [r"^fix", r"^bug", r"^patch", r"^resolv", r"^correct", r"^repair"],
    "Changed": [r"^updat", r"^chang", r"^modif", r"^refactor", r"^improv", r"^enhanc",
                r"^migrat", r"^upgrad", r"^tweak", r"^adjust", r"^revis", r"^optimiz"],
    "Removed": [r"^remov", r"^delet", r"^deprecat", r"^drop", r"^clean", r"^purge"],
}


def get_last_tag(repo_path: Path) -> str | None:
    try:
        result = subprocess.run(
            ["git", "tag", "--sort=-creatordate"],
            cwd=repo_path, capture_output=True, text=True, timeout=10,
        )
        tags = [t.strip() for t in result.stdout.splitlines() if t.strip()]
        return tags[0] if tags else None
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return None


def get_commits_since_tag(repo_path: Path, tag: str | None) -> list[dict]:
    range_spec = f"{tag}..HEAD" if tag else "HEAD"
    cmd = ["git", "log", range_spec, "--pretty=format:%H||%s||%an||%ad", "--date=short"]
    try:
        result = subprocess.run(cmd, cwd=repo_path, capture_output=True, text=True, timeout=15)
        commits = []
        for line in result.stdout.splitlines():
            if not line.strip():
                continue
            parts = line.split("||", 3)
            if len(parts) >= 4:
                commits.append({
                    "hash": parts[0][:8],
                    "message": parts[1].strip(),
                    "author": parts[2].strip(),
                    "date": parts[3].strip(),
                })
        return commits
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return []


def categorize_commit(message: str) -> str:
    msg_lower = message.lower()
    for category, patterns in CATEGORIES.items():
        for pattern in patterns:
            if re.search(pattern, msg_lower):
                return category
    return "Changed"


def generate_changelog(repo_path: Path) -> str:
    last_tag = get_last_tag(repo_path)
    commits = get_commits_since_tag(repo_path, last_tag)

    if not commits:
        return "# Changelog\n\nNo commits found.\n"

    version = last_tag if last_tag else "Unreleased"
    today = datetime.now().strftime("%Y-%m-%d")

    lines = [
        "# Changelog",
        "",
        f"## [{version}] - {today}",
        "",
    ]

    categorized: dict[str, list[dict]] = {"Added": [], "Fixed": [], "Changed": [], "Removed": []}
    for commit in commits:
        cat = categorize_commit(commit["message"])
        categorized[cat].append(commit)

    for category in ("Added", "Fixed", "Changed", "Removed"):
        entries = categorized[category]
        if not entries:
            continue
        lines.append(f"### {category}")
        lines.append("")
        for c in entries:
            lines.append(f"- {c['message']} ({c['hash']})")
        lines.append("")

    lines.append(f"*Generated by changelog.py on {today}*")
    lines.append("")
    return "\n".join(lines)


def main():
    import argparse

    parser = argparse.ArgumentParser(description="Generate structured CHANGELOG.md from git history")
    parser.add_argument("--repo", default=".", help="Path to git repository (default: current dir)")
    parser.add_argument("--output", default="CHANGELOG.md", help="Output file (default: CHANGELOG.md)")
    args = parser.parse_args()

    repo_path = Path(args.repo).resolve()
    if not (repo_path / ".git").exists():
        print(f"Error: {repo_path} is not a git repository", file=sys.stderr)
        sys.exit(1)

    changelog = generate_changelog(repo_path)
    output_path = Path(args.output)
    output_path.write_text(changelog, encoding="utf-8")
    print(f"Generated {output_path.resolve()} ({len(changelog.splitlines())} lines)")


if __name__ == "__main__":
    main()