#!/usr/bin/env bash
# changelog.sh — Generate a structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--tag TAG] [--output FILE]
#   --tag TAG     Start from specific tag (default: last tag)
#   --output FILE Output file (default: CHANGELOG.md)

set -euo pipefail

# ── Config ──────────────────────────────────────────────
OUTPUT="CHANGELOG.md"
FROM_TAG=""

while [[ $# -gt 0 ]]; do
  case $1 in
    --tag) FROM_TAG="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    *) echo "Unknown option: $1"; exit 1 ;;
  esac
done

# ── Detect last tag ────────────────────────────────────
if [ -z "$FROM_TAG" ]; then
  FROM_TAG=$(git describe --tags --abbrev=0 2>/dev/null || true)
fi

# ── Get commits ────────────────────────────────────────
if [ -n "$FROM_TAG" ]; then
  COMMITS=$(git log "$FROM_TAG..HEAD" --format="%s%n%b---END-BODY---" --no-merges 2>/dev/null || true)
  HEADER="## [$FROM_TAG..HEAD]"
  TIMESTAMP=$(git log -1 --format="%ad" --date=short "$FROM_TAG..HEAD" 2>/dev/null || date +%Y-%m-%d)
else
  COMMITS=$(git log --format="%s%n%b---END-BODY---" --no-merges 2>/dev/null || true)
  HEADER="## [Initial commits]"
  TIMESTAMP=$(date +%Y-%m-%d)
fi

# ── Categorize commits ─────────────────────────────────
ADDED=()
FIXED=()
CHANGED=()
REMOVED=()

while IFS= read -r line; do
  body_start=false
  title=""
  body=""
  while IFS= read -r cline; do
    if [ "$cline" = "---END-BODY---" ]; then
      body_start=true
      continue
    fi
    if [ "$body_start" = false ]; then
      title="$cline"
    else
      body="$cline"
    fi
  done <<< "$line"
  
  [ -z "$title" ] && continue
  
  # Normalize
  title_lower=$(echo "$title" | tr '[:upper:]' '[:lower:]')
  
  if echo "$title_lower" | grep -qE '^(feat|feature|add|new|implement|create|support)'; then
    ADDED+=("$title")
  elif echo "$title_lower" | grep -qE '^(fix|bugfix|hotfix|patch|correct|resolve)'; then
    FIXED+=("$title")
  elif echo "$title_lower" | grep -qE '^(remove|delete|deprecate|drop)'; then
    REMOVED+=("$title")
  else
    CHANGED+=("$title")
  fi
done <<< "$COMMITS"

# ── Write CHANGELOG ────────────────────────────────────
{
  echo "# Changelog"
  echo
  echo "All notable changes to this project will be documented in this file."
  echo
  echo "$HEADER — $TIMESTAMP"
  echo

  if [ ${#ADDED[@]} -gt 0 ]; then
    echo "### Added"
    for c in "${ADDED[@]}"; do
      echo "- $c"
    done
    echo
  fi

  if [ ${#FIXED[@]} -gt 0 ]; then
    echo "### Fixed"
    for c in "${FIXED[@]}"; do
      echo "- $c"
    done
    echo
  fi

  if [ ${#CHANGED[@]} -gt 0 ]; then
    echo "### Changed"
    for c in "${CHANGED[@]}"; do
      echo "- $c"
    done
    echo
  fi

  if [ ${#REMOVED[@]} -gt 0 ]; then
    echo "### Removed"
    for c in "${REMOVED[@]}"; do
      echo "- $c"
    done
    echo
  fi

  echo "---"
  echo "_Generated by [changelog.sh](skills/changelog.sh)_"
} > "$OUTPUT"

echo "✅ CHANGELOG generated → $OUTPUT"
