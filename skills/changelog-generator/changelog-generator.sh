#!/bin/bash
# changelog-generator.sh
# Generates a structured CHANGELOG.md from git history
# Usage: ./changelog-generator.sh [output_file] [since_tag]

set -e

# Default values
OUTPUT_FILE="${1:-CHANGELOG.md}"
SINCE_TAG="${2:-$(git describe --tags --abbrev=0 2>/dev/null || echo '')}"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Function to print colored output
log_info() { echo -e "${BLUE}[INFO]${NC} $1"; }
log_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
log_warning() { echo -e "${YELLOW}[WARNING]${NC} $1"; }
log_error() { echo -e "${RED}[ERROR]${NC} $1"; }

# Function to categorize commit messages
categorize_commit() {
    local msg="$1"
    local msg_lower="$(echo "$msg" | tr '[:upper:]' '[:lower:]')"
    
    # Patterns for categorization
    case "$msg_lower" in
        *add*|*feat*|*new*|*implement*|*create*)
            echo "Added" ;;
        *fix*|*bug*|*patch*|*resolve*|*correct*)
            echo "Fixed" ;;
        *change*|*update*|*modif*|*refactor*|*improve*|*optimize*)
            echo "Changed" ;;
        *remove*|*delete*|*drop*|*deprecate*)
            echo "Removed" ;;
        *docs*|*documentation*|*readme*)
            echo "Documentation" ;;
        *test*|*testing*)
            echo "Tests" ;;
        *style*|*format*|*lint*)
            echo "Style" ;;
        *chore*|*ci*|*build*|*deps*)
            echo "Chore" ;;
        *)
            echo "Other" ;;
    esac
}

# Function to extract commit data
extract_commits() {
    local since_tag="$1"
    
    if [ -z "$since_tag" ]; then
        # Get all commits if no tag specified
        git log --pretty=format:"%H|%an|%ad|%s" --date=short
    else
        # Get commits since the specified tag
        git log --pretty=format:"%H|%an|%ad|%s" --date=short "$since_tag"..HEAD
    fi
}

# Function to generate changelog
generate_changelog() {
    local since_tag="$1"
    local output_file="$2"
    
    log_info "Generating changelog..."
    log_info "Output file: $output_file"
    if [ -z "$since_tag" ]; then
        log_warning "No tag specified, generating changelog from all commits"
    else
        log_info "Since tag: $since_tag"
    fi
    
    # Initialize categories
    declare -A categories
    categories["Added"]=""
    categories["Fixed"]=""
    categories["Changed"]=""
    categories["Removed"]=""
    categories["Documentation"]=""
    categories["Tests"]=""
    categories["Style"]=""
    categories["Chore"]=""
    categories["Other"]=""
    
    # Extract and process commits
    local commit_count=0
    while IFS='|' read -r hash author date subject; do
        [ -z "$hash" ] && continue
        
        commit_count=$((commit_count + 1))
        category=$(categorize_commit "$subject")
        
        # Format commit entry
        entry="- **$subject** (${hash:0:7}) - $author, $date"
        
        # Append to category
        categories["$category"]="${categories[$category]}$entry"$'\n'
        
    done < <(extract_commits "$since_tag")
    
    log_info "Processed $commit_count commits"
    
    # Generate changelog content
    {
        echo "# Changelog"
        echo ""
        echo "All notable changes to this project will be documented in this file."
        echo ""
        
        if [ -z "$since_tag" ]; then
            echo "## [Unreleased]"
        else
            echo "## [Unreleased]"
            echo ""
            echo "### Changes since $since_tag"
        fi
        echo ""
        
        # Output categorized commits
        local has_content=false
        for category in "Added" "Fixed" "Changed" "Removed" "Documentation" "Tests" "Style" "Chore" "Other"; do
            if [ -n "${categories[$category]}" ]; then
                has_content=true
                echo "### $category"
                echo ""
                echo "${categories[$category]}"
            fi
        done
        
        if [ "$has_content" = false ]; then
            echo "No changes detected."
            echo ""
        fi
        
        # Add previous releases section if since_tag is specified
        if [ -n "$since_tag" ]; then
            echo "---"
            echo ""
            echo "## Previous Releases"
            echo ""
            echo "For changes before $since_tag, please check the git history."
        fi
        
        echo ""
        echo "---"
        echo ""
        echo "*Generated by changelog-generator.sh*"
        echo "*Last updated: $(date -u +'%Y-%m-%d %H:%M:%S UTC')*"
        
    } > "$output_file"
    
    log_success "Changelog generated successfully: $output_file"
}

# Function to show usage
show_usage() {
    echo "Usage: $0 [output_file] [since_tag]"
    echo ""
    echo "Arguments:"
    echo "  output_file  Path to output file (default: CHANGELOG.md)"
    echo "  since_tag    Git tag to start from (default: latest tag)"
    echo ""
    echo "Examples:"
    echo "  $0                         # Generate CHANGELOG.md from latest tag"
    echo "  $0 CHANGELOG.md            # Same as above"
    echo "  $0 CHANGELOG.md v1.0.0     # Generate since v1.0.0 tag"
    echo "  $0 docs/CHANGES.md         # Custom output file"
}

# Main execution
main() {
    # Check if we're in a git repository
    if ! git rev-parse --git-dir > /dev/null 2>&1; then
        log_error "Not a git repository. Please run this script from a git repository."
        exit 1
    fi
    
    # Show usage if help requested
    if [[ "$1" == "-h" ]] || [[ "$1" == "--help" ]]; then
        show_usage
        exit 0
    fi
    
    # Generate changelog
    generate_changelog "$SINCE_TAG" "$OUTPUT_FILE"
    
    # Show summary
    echo ""
    echo "=== Summary ==="
    echo "Output file: $(realpath "$OUTPUT_FILE")"
    echo "Total lines: $(wc -l < "$OUTPUT_FILE")"
    echo "File size: $(du -h "$OUTPUT_FILE" | cut -f1)"
    
    # Show preview
    echo ""
    echo "=== Preview (first 20 lines) ==="
    head -20 "$OUTPUT_FILE"
}

# Run main function
main "$@"