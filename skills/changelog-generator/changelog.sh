#!/usr/bin/env bash
# changelog.sh — Generate a structured CHANGELOG.md from git history
# Usage: ./changelog.sh [--since TAG] [--output FILE]
#
# Fetches commits since the last git tag (or specified tag) and
# auto-categorizes them into Added / Fixed / Changed / Removed sections.

set -euo pipefail

# --- Config ---
SINCE_TAG=""
OUTPUT="CHANGELOG.md"
REPO_NAME=$(basename "$(git rev-parse --show-toplevel 2>/dev/null)" 2>/dev/null || echo "project")
DATE=$(date +%Y-%m-%d)

# --- Parse args ---
while [[ $# -gt 0 ]]; do
  case $1 in
    --since) SINCE_TAG="$2"; shift 2 ;;
    --output|-o) OUTPUT="$2"; shift 2 ;;
    -h|--help)
      echo "Usage: changelog.sh [--since TAG] [--output FILE]"
      echo "  --since TAG   Generate changelog since this tag (default: last tag)"
      echo "  --output FILE Output file (default: CHANGELOG.md)"
      exit 0
      ;;
    *) echo "Unknown option: $1"; exit 1 ;;
  esac
done

# --- Find the last tag if not specified ---
if [[ -z "$SINCE_TAG" ]]; then
  SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
fi

# --- Determine version ---
NEXT_VERSION=$(git describe --tags 2>/dev/null || echo "Unreleased")
if [[ "$NEXT_VERSION" == *-* ]]; then
  NEXT_VERSION="Unreleased"
fi

# --- Build commit range ---
if [[ -n "$SINCE_TAG" ]]; then
  RANGE="${SINCE_TAG}..HEAD"
  echo "Generating changelog since tag: $SINCE_TAG"
else
  RANGE=""
  echo "No tags found — generating changelog from all commits"
fi

# --- Collect commits ---
if [[ -n "$RANGE" ]]; then
  COMMITS=$(git log "$RANGE" --pretty=format:"%s|%h|%an" --no-merges 2>/dev/null || echo "")
else
  COMMITS=$(git log --pretty=format:"%s|%h|%an" --no-merges 2>/dev/null || echo "")
fi

if [[ -z "$COMMITS" ]]; then
  echo "No commits found. Nothing to generate."
  exit 0
fi

# --- Categorize commits ---
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""
OTHER=""

while IFS='|' read -r msg hash author; do
  # Normalize to lowercase for matching
  lower=$(echo "$msg" | tr '[:upper:]' '[:lower:]')
  entry="- ${msg} (\`${hash}\`) — *${author}*"

  if echo "$lower" | grep -qE "^(add|feat|new|create|implement|introduce|support)"; then
    ADDED="${ADDED}\n${entry}"
  elif echo "$lower" | grep -qE "^(fix|bug|patch|resolve|repair|correct|hotfix)"; then
    FIXED="${FIXED}\n${entry}"
  elif echo "$lower" | grep -qE "^(remove|delete|drop|deprecate|strip|clean.?up)"; then
    REMOVED="${REMOVED}\n${entry}"
  elif echo "$lower" | grep -qE "^(change|update|refactor|improve|optimize|rename|move|migrate|bump|upgrade|adjust|rework)"; then
    CHANGED="${CHANGED}\n${entry}"
  else
    # Try body keywords as fallback
    if echo "$lower" | grep -qE "(add|feature|new|support|introduce|implement)"; then
      ADDED="${ADDED}\n${entry}"
    elif echo "$lower" | grep -qE "(fix|bug|patch|resolve|repair)"; then
      FIXED="${FIXED}\n${entry}"
    elif echo "$lower" | grep -qE "(remove|delete|drop|deprecate)"; then
      REMOVED="${REMOVED}\n${entry}"
    elif echo "$lower" | grep -qE "(change|update|refactor|improve|optimize|rename)"; then
      CHANGED="${CHANGED}\n${entry}"
    else
      OTHER="${OTHER}\n${entry}"
    fi
  fi
done <<< "$COMMITS"

# --- Write CHANGELOG ---
{
  echo "# Changelog"
  echo ""
  echo "## [${NEXT_VERSION}] — ${DATE}"
  echo ""

  if [[ -n "$ADDED" ]]; then
    echo "### Added"
    echo -e "$ADDED"
    echo ""
  fi

  if [[ -n "$FIXED" ]]; then
    echo "### Fixed"
    echo -e "$FIXED"
    echo ""
  fi

  if [[ -n "$CHANGED" ]]; then
    echo "### Changed"
    echo -e "$CHANGED"
    echo ""
  fi

  if [[ -n "$REMOVED" ]]; then
    echo "### Removed"
    echo -e "$REMOVED"
    echo ""
  fi

  if [[ -n "$OTHER" ]]; then
    echo "### Other"
    echo -e "$OTHER"
    echo ""
  fi

  echo "---"
  echo "*Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty/tree/main/skills/changelog-generator) on ${DATE}*"
} > "$OUTPUT"

echo "✅ Changelog written to ${OUTPUT}"
echo "   $(echo -e "${ADDED}${FIXED}${CHANGED}${REMOVED}${OTHER}" | grep -c "^-") commits categorized"
