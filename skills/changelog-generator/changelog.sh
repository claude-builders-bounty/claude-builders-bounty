#!/usr/bin/env bash
# changelog.sh — Auto-generate structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--since TAG] [--output CHANGELOG.md]
# Bounty: $50 — claude-builders-bounty#1

set -euo pipefail

SINCE=""
OUTPUT="CHANGELOG.md"
REPO_NAME=""

# Parse args
while [[ $# -gt 0 ]]; do
    case $1 in
        --since) SINCE="$2"; shift 2 ;;
        --output|-o) OUTPUT="$2"; shift 2 ;;
        --repo) REPO_NAME="$2"; shift 2 ;;
        *) echo "Usage: $0 [--since TAG] [--output FILE] [--repo NAME]"; exit 1 ;;
    esac
done

# If no --since, find last tag
if [[ -z "$SINCE" ]]; then
    SINCE=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
    if [[ -z "$SINCE" ]]; then
        SINCE=$(git rev-list --max-parents=0 HEAD 2>/dev/null || echo "HEAD~100")
    fi
fi

# Get repo name
if [[ -z "$REPO_NAME" ]]; then
    REMOTE=$(git remote get-url origin 2>/dev/null || echo "")
    REPO_NAME=$(basename "$(git rev-parse --show-toplevel 2>/dev/null || echo ".")" .git)
fi

echo "📝 Generating CHANGELOG for $REPO_NAME..."
echo "   Since: $SINCE"

# Fetch commits and categorize
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""
OTHER=""

while IFS='|' read -r hash subject body; do
    lower_subject=$(echo "$subject" | tr '[:upper:]' '[:lower:]')
    entry="- $subject ([${hash:0:7}](https://github.com/$REPO_NAME/commit/${hash}))"

    if echo "$lower_subject" | grep -qE '^feat|^add|^feature|^new'; then
        ADDED="$ADDED\n$entry"
    elif echo "$lower_subject" | grep -qE '^fix|^bug|^hotfix|^patch'; then
        FIXED="$FIXED\n$entry"
    elif echo "$lower_subject" | grep -qE '^refactor|^update|^change|^improve|^perf|^optimize'; then
        CHANGED="$CHANGED\n$entry"
    elif echo "$lower_subject" | grep -qE '^remove|^drop|^delete|^deprecat'; then
        REMOVED="$REMOVED\n$entry"
    else
        OTHER="$OTHER\n$entry"
    fi
done < <(git log "${SINCE}..HEAD" --format="%H|%s|%b" 2>/dev/null || true)

# Get version info
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "v0.1.0")
NEW_VERSION=$(echo "$LAST_TAG" | awk -F. '{
    major=$1; sub(/^v/,"",major);
    if ($3+0 > 0) printf "v%d.%d.%d", major, $2, $3+1;
    else if ($2+0 > 0) printf "v%d.%d.0", major, $2+1;
    else printf "v%d.1.0", major+1;
}' 2>/dev/null || echo "v0.1.0")
DATE=$(date +%Y-%m-%d)

# Generate CHANGELOG
cat > "$OUTPUT" << CHANGELOG
# Changelog

## [${NEW_VERSION}] - ${DATE}

### Added
$(echo -e "$ADDED" | grep -v '^$' || echo "  (none)")

### Fixed
$(echo -e "$FIXED" | grep -v '^$' || echo "  (none)")

### Changed
$(echo -e "$CHANGED" | grep -v '^$' || echo "  (none)")

### Removed
$(echo -e "$REMOVED" | grep -v '^$' || echo "  (none)")

### Other
$(echo -e "$OTHER" | grep -v '^$' || echo "  (none)")

---

*Generated by changelog.sh on ${DATE}*
*Commits since ${SINCE}*
CHANGELOG

echo "✅ CHANGELOG generated: ${OUTPUT}"
echo "   Version: ${NEW_VERSION}"
echo "   Total commits: $(git log "${SINCE}..HEAD" --oneline 2>/dev/null | wc -l | tr -d ' ')"
