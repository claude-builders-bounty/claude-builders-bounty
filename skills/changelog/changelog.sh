#!/usr/bin/env bash
# changelog.sh — Generate structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--repo /path/to/repo] [--output CHANGELOG.md]

set -euo pipefail

REPO="${PWD}"
OUTPUT="CHANGELOG.md"
HEADER=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --repo) REPO="$2"; shift 2 ;;
        --output) OUTPUT="$2"; shift 2 ;;
        --header) HEADER="$2"; shift 2 ;;
        *) echo "Usage: $0 [--repo PATH] [--output FILE] [--header TEXT]"; exit 1 ;;
    esac
done

cd "$REPO"

# Get the last tag, or use initial commit
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
if [[ -z "$LAST_TAG" ]]; then
    RANGE="HEAD"
    TAG_INFO="Initial release"
else
    RANGE="${LAST_TAG}..HEAD"
    TAG_INFO="Since ${LAST_TAG}"
fi

# Categorize commits using Conventional Commits
declare -A SECTIONS
SECTIONS["Added"]=""
SECTIONS["Fixed"]=""
SECTIONS["Changed"]=""
SECTIONS["Removed"]=""
SECTIONS["Deprecated"]=""
SECTIONS["Security"]=""
SECTIONS["Documentation"]=""
SECTIONS="其他"

# Map of conventional commit types to sections
declare -A TYPE_MAP
TYPE_MAP["feat"]="Added"
TYPE_MAP["feature"]="Added"
TYPE_MAP["add"]="Added"
TYPE_MAP["fix"]="Fixed"
TYPE_MAP["bugfix"]="Fixed"
TYPE_MAP["hotfix"]="Fixed"
TYPE_MAP["patch"]="Fixed"
TYPE_MAP["refactor"]="Changed"
TYPE_MAP["refact"]="Changed"
TYPE_MAP["perf"]="Changed"
TYPE_MAP["performance"]="Changed"
TYPE_MAP["improve"]="Changed"
TYPE_MAP["style"]="Changed"
TYPE_MAP["chore"]="Changed"
TYPE_MAP["build"]="Changed"
TYPE_MAP["ci"]="Changed"
TYPE_MAP["remove"]="Removed"
TYPE_MAP["delete"]="Removed"
TYPE_MAP["deprecate"]="Deprecated"
TYPE_MAP["security"]="Security"
TYPE_MAP["audit"]="Security"
TYPE_MAP["docs"]="Documentation"
TYPE_MAP["doc"]="Documentation"
TYPE_MAP["readme"]="Documentation"

# Temporary files
TEMP_DIR=$(mktemp -d)
trap 'rm -rf "$TEMP_DIR"' EXIT

# Process each commit
git log --oneline --format="%H|%s" "$RANGE" 2>/dev/null > "$TEMP_DIR/commits.txt" || {
    echo "No commits found in range: $RANGE"
    echo "# Changelog" > "$OUTPUT"
    echo "" >> "$OUTPUT"
    echo "No changes yet." >> "$OUTPUT"
    exit 0
}

declare -A COUNTS
for section in "${!SECTIONS[@]}"; do
    COUNTS["$section"]=0
    > "$TEMP_DIR/${section}.txt"
done
> "$TEMP_DIR/其他.txt"
OTHER_COUNT=0

while IFS='|' read -r HASH MESSAGE; do
    [[ -z "$MESSAGE" ]] && continue
    
    # Determine section from commit type
    SECTION="其他"
    for prefix in "${!TYPE_MAP[@]}"; do
        if [[ "$MESSAGE" =~ ^${prefix}[\(\!\)] ]] || [[ "$MESSAGE" =~ ^${prefix}: ]] || [[ "$MESSAGE" =~ ^${prefix}\( ]]; then
            SECTION="${TYPE_MAP[$prefix]}"
            break
        fi
    done
    
    # Extract description (remove conventional commit prefix)
    CLEAN_MSG=$(echo "$MESSAGE" | sed -E 's/^[a-z]+(\([^)]*\))?!?: //' | sed -E 's/^[a-z]+: //')
    SHORT_HASH=$(echo "$HASH" | cut -c1-7)
    
    echo "- ${CLEAN_MSG} (${SHORT_HASH})" >> "$TEMP_DIR/${SECTION}.txt"
    COUNTS["$SECTION"]=$((COUNTS["$SECTION"] + 1))
done < "$TEMP_DIR/commits.txt"

TOTAL_COMMITS=$(wc -l < "$TEMP_DIR/commits.txt" | tr -d ' ')

# Get date range
FIRST_DATE=$(git log --format="%as" "$RANGE" 2>/dev/null | tail -1 || echo "")
LAST_DATE=$(git log --format="%as" "$RANGE" 2>/dev/null | head -1 || echo "")
DATE_RANGE=""
if [[ -n "$FIRST_DATE" ]] && [[ -n "$LAST_DATE" ]]; then
    DATE_RANGE="${FIRST_DATE} to ${LAST_DATE}"
fi

# Generate CHANGELOG
{
    if [[ -n "$HEADER" ]]; then
        echo "$HEADER"
    else
        echo "# Changelog"
    fi
    echo ""
    
    # Version title
    VERSION=$(git describe --tags --abbrev=0 2>/dev/null || echo "Unreleased")
    echo "## [${VERSION}]"
    if [[ -n "$DATE_RANGE" ]]; then
        echo ""
        echo "*${DATE_RANGE}*"
    fi
    echo ""
    echo "${TOTAL_COMMITS} commits ${TAG_INFO}"
    echo ""
    
    # Print sections that have commits
    for section in "Added" "Fixed" "Changed" "Removed" "Deprecated" "Security" "Documentation" "其他"; do
        if [[ -s "$TEMP_DIR/${section}.txt" ]]; then
            count=${COUNTS["$section"]:-0}
            echo "### ${section}"
            echo ""
            cat "$TEMP_DIR/${section}.txt"
            echo ""
        fi
    done
    
    echo "---"
    echo ""
    echo "_Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty)_"
} > "$OUTPUT"

echo "✅ Changelog generated: $(pwd)/${OUTPUT}"
echo "   ${TOTAL_COMMITS} commits across $(ls -1 $TEMP_DIR/*.txt 2>/dev/null | wc -l | tr -d ' ') categories"
