#!/usr/bin/env bash
set -euo pipefail

# changelog.sh — Generate CHANGELOG.md from git history
# Usage: bash changelog.sh [target-directory]
#   If no directory is given, uses the current working directory.

TARGET_DIR="${1:-$(pwd)}"
cd "$TARGET_DIR"

if ! git rev-parse --git-dir > /dev/null 2>&1; then
  echo "❌ Error: '$TARGET_DIR' is not a git repository."
  exit 1
fi

# ── Determine commit range ──────────────────────────────────────────
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || true)
if [ -n "$LAST_TAG" ]; then
  RANGE="${LAST_TAG}..HEAD"
  echo "✓ Using range: $RANGE"
else
  RANGE="HEAD"
  echo "✓ No tags found — using all commits since the beginning."
fi

# ── Categorize commits by conventional-commit type ──────────────────
get_commits() {
  local prefix="$1"
  git log "$RANGE" --pretty=format:"- %s" --grep="^${prefix}" 2>/dev/null || true
}

get_commits_scope() {
  local prefix="$1"
  git log "$RANGE" --pretty=format:"- %s" --grep="^${prefix}(" 2>/dev/null || true
}

# ── Build CHANGELOG ────────────────────────────────────────────────
OUTPUT="CHANGELOG.md"
{
  echo "# Changelog"
  echo ""
  echo "## [Unreleased] — $(date +%Y-%m-%d)"
  echo ""

  for section in "Added|feat" "Fixed|fix" "Changed|chore|refactor|perf" "Removed|remove|deprecat"; do
    label="${section%%|*}"
    patterns="${section#*|}"
    
    lines=""
    IFS='|' read -ra PATS <<< "$patterns"
    for pat in "${PATS[@]}"; do
      chunk=$(get_commits "$pat")
      if [ -n "$chunk" ]; then
        lines+="$chunk"$'\n'
      fi
    done
    
    lines=$(echo -e "$lines" | sort -u | sed '/^$/d')
    if [ -n "$lines" ]; then
      echo "### $label"
      echo "$lines" | while IFS= read -r line; do
        # Strip conventional-commit prefix (e.g. "feat: add login" → "- add login")
        clean=$(echo "$line" | sed -E 's/^- (feat|fix|chore|refactor|perf|docs|style|test|ci|build|revert)(\([^)]*\))?: /- /')
        echo "$clean"
      done
      echo ""
    fi
  done

  # Uncategorized leftovers
  ALL=$(git log "$RANGE" --pretty=format:"- %s" 2>/dev/null)
  CATEGORIZED=""
  for section in "Added|feat" "Fixed|fix" "Changed|chore|refactor|perf" "Removed|remove|deprecat"; do
    patterns="${section#*|}"
    IFS='|' read -ra PATS <<< "$patterns"
    for pat in "${PATS[@]}"; do
      chunk=$(echo "$ALL" | grep -i "^ *- *${pat}" || true)
      if [ -n "$chunk" ]; then
        CATEGORIZED+="$chunk"$'\n'
      fi
    done
  done
  
  LEFTOVERS=$(echo "$ALL" | grep -v -i -E "^\s*-\s*(feat|fix|chore|refactor|perf|docs|style|test|ci|build|revert)" || true)
  LEFTOVERS=$(echo "$LEFTOVERS" | sed '/^$/d')
  if [ -n "$LEFTOVERS" ]; then
    echo "### Uncategorized"
    echo "$LEFTOVERS"
    echo ""
  fi

  # Footer
  ALL_COUNT=$(git log "$RANGE" --oneline 2>/dev/null | wc -l)
  echo "---"
  echo "_Generated by [changelog.sh](${BASH_SOURCE[0]:-changelog.sh}) — ${ALL_COUNT} commit(s) since ${LAST_TAG:-the beginning}._"

} > "$OUTPUT"

echo "✅ CHANGELOG.md generated ($(wc -l < "$OUTPUT") lines)"
