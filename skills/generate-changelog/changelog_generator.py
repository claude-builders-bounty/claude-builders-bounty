#!/usr/bin/env python3
"""Auto CHANGELOG Generator — for claude-builders-bounty $50 task"""
import subprocess, os, sys, re
from datetime import datetime

def get_git_log():
    try:
        last_tag = subprocess.run(
            ["git", "describe", "--tags", "--abbrev=0"],
            capture_output=True, text=True, timeout=10
        ).stdout.strip()
        range_spec = f"{last_tag}..HEAD" if last_tag else "HEAD"
    except:
        range_spec = "HEAD"

    result = subprocess.run(
        ["git", "log", range_spec, "--format=%H|%ai|%s|%b"],
        capture_output=True, text=True, timeout=30
    )
    if result.returncode != 0:
        print("Not a git repository")
        return []
    return [l for l in result.stdout.strip().split("\n") if l.strip()]

def categorize_commit(msg):
    ml = msg.lower()
    if any(ml.startswith(p) for p in ["breaking", "!"]):
        return "Changed"
    if any(ml.startswith(p) for p in ["feat", "add", "feature", "new", "create"]):
        return "Added"
    if re.match(r"^(fix|bug|hotfix|correct|resolve|repair|patch)", ml):
        return "Fixed"
    if any(ml.startswith(p) for p in ["change", "update", "refactor", "upgrade"]):
        return "Changed"
    if any(ml.startswith(p) for p in ["remove", "delete", "deprecate", "drop"]):
        return "Removed"
    if ml.startswith("doc"):
        return "Documentation"
    return "Changed"

def parse_commits(raw):
    commits = []
    for line in raw:
        parts = line.split("|", 3)
        if len(parts) < 3: continue
        h, d, t = parts[0][:7], parts[1][:10], parts[2]
        b = parts[3] if len(parts) > 3 else ""
        commits.append({"hash": h, "date": d, "title": t, "body": b[:200], "cat": categorize_commit(t)})
    return commits

def generate_changelog(commits):
    cats = ["Added", "Fixed", "Changed", "Removed", "Documentation"]
    grouped = {c: [] for c in cats}
    for c in commits:
        grouped[c["cat"]].append(c)
    
    ver = datetime.now().strftime("%Y.%m.%d")
    md = f"# Changelog\n\n## [{ver}] - {datetime.now().strftime('%Y-%m-%d')}\n\n"
    
    emojis = {"Added": "🚀", "Fixed": "🐛", "Changed": "🔄", "Removed": "🗑️", "Documentation": "📝"}
    for cat in cats:
        items = grouped[cat]
        if not items: continue
        md += f"### {emojis[cat]} {cat}\n\n"
        for c in items:
            md += f"- **{c['title'][:80]}** (`{c['hash']}`)\n"
            if c["body"]: md += f"  - {c['body'][:120]}\n"
        md += "\n"
    md += "---\n*Generated by changelog-generator (claude-builders-bounty)*\n"
    return md

def main():
    print("Generating CHANGELOG from git history...")
    raw = get_git_log()
    if not raw:
        raw = subprocess.run(["git", "log", "--format=%H|%ai|%s|%b", "-30"],
            capture_output=True, text=True, timeout=10).stdout.strip().split("\n")
        raw = [l for l in raw if l.strip()]
    
    commits = parse_commits(raw)
    if not commits:
        print("No commits found. Run this in a git repository.")
        return
    
    md = generate_changelog(commits)
    with open("CHANGELOG.md", "w", encoding="utf-8") as f:
        f.write(md)
    
    print(f"CHANGELOG.md generated: {len(commits)} commits")
    for cat in ["Added", "Fixed", "Changed", "Removed", "Documentation"]:
        n = sum(1 for c in commits if c["cat"] == cat)
        if n: print(f"  {cat}: {n}")

if __name__ == "__main__":
    main()