#!/usr/bin/env bash
# changelog.sh — generate a categorized CHANGELOG.md from git history.
#
# Fetches the commits since the last git tag (or a ref you pass with --from),
# sorts them into Added / Fixed / Changed / Removed, and writes a Keep a
# Changelog style file. Conventional Commit prefixes are used when present;
# plain-language commit messages are classified by keyword.
#
# Usage: bash changelog.sh [--repo PATH] [--from REF] [--out FILE]

set -euo pipefail

REPO="."
FROM=""
OUT="CHANGELOG.md"

usage() {
  cat <<'EOF'
Usage: changelog.sh [--repo PATH] [--from REF] [--out FILE]

  --repo PATH   Path to the git repository (default: current directory)
  --from REF    Start reference (default: the most recent tag;
                use "" explicitly to include the full history)
  --out FILE    Output file (default: CHANGELOG.md)

Examples:
  changelog.sh                                  # commits since the last tag
  changelog.sh --from v1.2.0                    # commits since v1.2.0
  changelog.sh --from v1.0.0 --out docs/CHANGELOG.md
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --repo) REPO="${2:-}"; shift 2 ;;
    --from) FROM="${2:-}"; shift 2 ;;
    --out) OUT="${2:-}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "changelog.sh: unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [ -z "$FROM" ]; then
  # default: the most recent tag reachable from HEAD; empty when there are none
  FROM="$(git -C "$REPO" describe --tags --abbrev=0 2>/dev/null || true)"
  AUTO_FROM=1
else
  AUTO_FROM=0
fi

if [ -n "$FROM" ]; then
  RANGE="${FROM}..HEAD"
  if [ "$AUTO_FROM" -eq 1 ]; then
    TITLE="Unreleased"                 # whatever follows the last tag is unreleased
  else
    TITLE="Unreleased (since ${FROM})" # explicit range — say which one
  fi
else
  RANGE="HEAD"
  TITLE="Unreleased"
fi

# hash<TAB>subject, newest first, merge commits excluded
mapfile -t COMMITS < <(git -C "$REPO" log "$RANGE" --no-merges \
  --pretty=format:'%H%x09%s' 2>/dev/null || true)

if [ ${#COMMITS[@]} -eq 0 ]; then
  echo "changelog.sh: no commits found in range '${RANGE}'" >&2
  exit 1
fi

# classify a commit subject into Added / Fixed / Changed / Removed
classify() {
  local subject="$1" base

  # Conventional Commit form: type, optional scope, optional "!", ": subject"
  if [[ "$subject" =~ ^([a-z]+)(\([a-z0-9_-]+\))?!?:[[:space:]]*(.*)$ ]]; then
    base="${BASH_REMATCH[1]}"
    case "$base" in
      feat) echo "Added" ;;
      fix) echo "Fixed" ;;
      revert) echo "Removed" ;;
      perf|refactor|style|docs|build|ci|test|chore) echo "Changed" ;;
      *) echo "Changed" ;;
    esac
    return
  fi

  # Plain messages: keyword heuristics
  local lower="${subject,,}"
  case "$lower" in
    add\ *|added\ *|adds\ *|support\ *|introduce\ *|new\ *) echo "Added" ;;
    fix\ *|fixed\ *|fixes\ *|bugfix\ *|resolve\ *|resolves\ *|patch\ *) echo "Fixed" ;;
    remove\ *|removed\ *|removes\ *|drop\ *|dropped\ *|drops\ *|delete\ *|deleted\ *) echo "Removed" ;;
    *) echo "Changed" ;;
  esac
}

# clean a commit subject into an entry line
clean_subject() {
  local subject="$1" breaking=""
  # strip a Conventional Commit prefix, keep the descriptive sentence
  if [[ "$subject" =~ ^([a-z]+)(\([a-z0-9_-]+\))?(!)?:[[:space:]]*(.*)$ ]]; then
    [ -n "${BASH_REMATCH[3]}" ] && breaking=" (breaking change)"
    subject="${BASH_REMATCH[4]}"
  fi
  # trim surrounding spaces, capitalise the first character, drop a trailing period
  subject="${subject#"${subject%%[![:space:]]*}"}"
  subject="${subject%"${subject##*[![:space:]]}"}"
  subject="${subject%.}"
  [ -n "$subject" ] || return 1
  printf '%s%s\n' "${subject^}" "$breaking"
}

declare -a added=() fixed=() changed=() removed=()
declare -A seen=()

for line in "${COMMITS[@]}"; do
  hash="${line%%$'\t'*}"
  subject="${line#*$'\t'}"
  [ -n "$hash" ] && [ -n "$subject" ] || continue
  # identical subjects (often bumps or repeated chores) appear once
  key="${subject,,}"
  [ -n "${seen[$key]:-}" ] && continue
  seen["$key"]=1
  entry="$(clean_subject "$subject")" || continue
  case "$(classify "$subject")" in
    Added) added+=("- ${entry} (\`${hash:0:7}\`)") ;;
    Fixed) fixed+=("- ${entry} (\`${hash:0:7}\`)") ;;
    Removed) removed+=("- ${entry} (\`${hash:0:7}\`)") ;;
    *) changed+=("- ${entry} (\`${hash:0:7}\`)") ;;
  esac
done

emit() {  # emit <array name> <heading>
  local -n arr="$1"
  [ ${#arr[@]} -gt 0 ] || return 0
  printf '### %s\n\n' "$2"
  printf '%s\n\n' "${arr[@]}"
}

{
  printf '# Changelog\n\n'
  printf 'All notable changes to this project are documented in this file.\n\n'
  printf '## [%s]\n\n' "$TITLE"
  emit added "Added"
  emit fixed "Fixed"
  emit changed "Changed"
  emit removed "Removed"
  printf '<!-- Generated by skills/generate-changelog/changelog.sh from %s on %s -->\n' \
    "${RANGE}" "$(date -u +%Y-%m-%d)"
} > "$OUT"

printf 'Wrote %d commits in %s to %s\n' "${#COMMITS[@]}" "${RANGE}" "$OUT" >&2
