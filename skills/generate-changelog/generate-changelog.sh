#!/usr/bin/env bash
# generate-changelog.sh
# Generates a structured CHANGELOG.md from git history since the last tag.
#
# Usage: bash generate-changelog.sh [--output CHANGELOG.md] [--since <tag|date>]

set -euo pipefail

OUTPUT="CHANGELOG.md"
SINCE=""

# Parse args
while [[ $# -gt 0 ]]; do
  case "$1" in
    --output) OUTPUT="$2"; shift 2 ;;
    --since) SINCE="$2"; shift 2 ;;
    *) echo "Unknown flag: $1"; exit 1 ;;
  esac
done

# Find baseline
if [ -z "$SINCE" ]; then
  SINCE=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
fi
if [ -z "$SINCE" ]; then
  SINCE=$(git rev-list --max-parents=0 HEAD)
  echo "⚠️  No git tags found. Using first commit as baseline."
fi

TODAY=$(date +%Y-%m-%d)
VERSION=$(git describe --tags --abbrev=0 2>/dev/null || echo "v0.1.0")

# Collect commits
COMMITS=$(git log "${SINCE}..HEAD" --pretty=format:"- %s" --no-merges 2>/dev/null || git log --pretty=format:"- %s" --no-merges)
COMMIT_COUNT=$(echo "$COMMITS" | grep -c "." || echo 0)

# Categorize using temp files
ADDED=$(mktemp)
FIXED=$(mktemp)
CHANGED=$(mktemp)
REMOVED=$(mktemp)
trap "rm -f $ADDED $FIXED $CHANGED $REMOVED" EXIT

# Read commits line by line
while IFS= read -r line; do
  [ -z "$line" ] && continue
  msg=$(echo "${line#- }" | tr '[:upper:]' '[:lower:]')
  
  case "$msg" in
    feat:*|add:*|new:*|introduce:*|implement:*)
      echo "$line" >> "$ADDED" ;;
    fix:*|bug:*|patch:*|resolve:*|hotfix:*)
      echo "$line" >> "$FIXED" ;;
    remove:*|drop:*|delete:*|deprecate:*|revert:*)
      echo "$line" >> "$REMOVED" ;;
    *)
      echo "$line" >> "$CHANGED" ;;
  esac
done <<< "$COMMITS"

# Write output
mkdir -p "$(dirname "$OUTPUT")"
cat > "$OUTPUT" << EOF
# Changelog

## [Unreleased] - ${TODAY}

### Added
EOF
[ -s "$ADDED" ] && cat "$ADDED" >> "$OUTPUT" || echo "- _(none)_" >> "$OUTPUT"

cat >> "$OUTPUT" << EOF

### Fixed
EOF
[ -s "$FIXED" ] && cat "$FIXED" >> "$OUTPUT" || echo "- _(none)_" >> "$OUTPUT"

cat >> "$OUTPUT" << EOF

### Changed
EOF
[ -s "$CHANGED" ] && cat "$CHANGED" >> "$OUTPUT" || echo "- _(none)_" >> "$OUTPUT"

cat >> "$OUTPUT" << EOF

### Removed
EOF
[ -s "$REMOVED" ] && cat "$REMOVED" >> "$OUTPUT" || echo "- _(none)_" >> "$OUTPUT"

cat >> "$OUTPUT" << EOF

---
Generated by [generate-changelog](https://github.com/claude-builders-bounty/claude-builders-bounty) | ${COMMIT_COUNT} commits processed
EOF

echo "✅ $OUTPUT — $COMMIT_COUNT commits from ${SINCE:0:7}..HEAD"
