#!/bin/bash
# generate-changelog — Structured CHANGELOG.md from git history
# Usage: ./generate-changelog.sh [since_tag]

set -euo pipefail

SINCE="${1:-$(git describe --tags --abbrev=0 2>/dev/null || echo '')}"
OUTPUT="${OUTPUT:-CHANGELOG.md}"

# ── Collect commits ──
if [ -n "$SINCE" ]; then
    echo "→ Scanning commits since tag: $SINCE" >&2
    COMMITS=$(git log "${SINCE}..HEAD" --pretty=format:"%s" 2>/dev/null || git log --pretty=format:"%s")
else
    echo "→ No tag found, scanning all commits" >&2
    COMMITS=$(git log --pretty=format:"%s")
fi

if [ -z "$COMMITS" ]; then
    echo "No commits found since $SINCE"
    exit 0
fi

# ── Classify commits ──
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""

while IFS= read -r line; do
    [ -z "$line" ] && continue
    msg_lower=$(echo "$line" | tr '[:upper:]' '[:lower:]')
    
    if echo "$msg_lower" | grep -qE '^(add|feat|new|introduce)'; then
        ADDED+="  - ${line}"$'\n'
    elif echo "$msg_lower" | grep -qE '^(fix|bug|patch|resolve|hotfix)'; then
        FIXED+="  - ${line}"$'\n'
    elif echo "$msg_lower" | grep -qE '^(remove|drop|delete|deprecate)'; then
        REMOVED+="  - ${line}"$'\n'
    else
        CHANGED+="  - ${line}"$'\n'
    fi
done <<< "$COMMITS"

# ── Generate CHANGELOG.md ──
VERSION="${SINCE:-HEAD}"
DATE=$(date +%Y-%m-%d)
REPO=$(git remote get-url origin 2>/dev/null | sed 's/.*github.com[:/]//' | sed 's/\.git$//' || echo "unknown")

cat > "$OUTPUT" << EOF
# Changelog

## [${VERSION}] — ${DATE}

### Added
$( [ -n "$ADDED" ] && echo "$ADDED" || echo "  - No new features in this release" )

### Fixed
$( [ -n "$FIXED" ] && echo "$FIXED" || echo "  - No bug fixes in this release" )

### Changed
$( [ -n "$CHANGED" ] && echo "$CHANGED" || echo "  - No changes in this release" )

### Removed
$( [ -n "$REMOVED" ] && echo "$REMOVED" || echo "  - No removals in this release" )

---

*Generated by [changelog.sh](https://github.com/yolopsx) on ${DATE} for ${REPO}*
EOF

wc_count=$(echo "$COMMITS" | wc -l | tr -d ' ')
echo "✅ Generated $OUTPUT"
echo "   ${wc_count} commits classified"
echo "   Added:   $(echo "$ADDED" | grep -c '^-' || echo 0)"
echo "   Fixed:   $(echo "$FIXED" | grep -c '^-' || echo 0)"
echo "   Changed: $(echo "$CHANGED" | grep -c '^-' || echo 0)"
echo "   Removed: $(echo "$REMOVED" | grep -c '^-' || echo 0)"
