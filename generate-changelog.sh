#!/usr/bin/env bash
# generate-changelog.sh
# Bounty: $50 — Claude Builders Bounty Issue #1
# Generates a structured CHANGELOG.md from git history
# Usage: bash generate-changelog.sh [output-file]

set -euo pipefail

CHANGELOG_FILE="${1:-CHANGELOG.md}"

# Get the latest tag or initial commit
LATEST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || git rev-list --max-parents=0 HEAD)
NOW=$(date +"%Y-%m-%d")

cat > "$CHANGELOG_FILE" << 'HEADER'
# Changelog

All notable changes to this project will be documented in this file.

The format is based on [Keep a Changelog](https://keepachangelog.com/en/1.1.0/),
and this project adheres to [Semantic Versioning](https://semver.org/spec/v2.0.0.html).

HEADER

echo "## [Unreleased] - $NOW" >> "$CHANGELOG_FILE"
echo "" >> "$CHANGELOG_FILE"

# Collect commits into categorized groups
ADDED=$(git log "$LATEST_TAG..HEAD" --pretty=format:"%s" 2>/dev/null | grep -iE "^feat|^add|^new|^introduce" || true)
FIXED=$(git log "$LATEST_TAG..HEAD" --pretty=format:"%s" 2>/dev/null | grep -iE "^fix|^bug|^hotfix|^patch" || true)
CHANGED=$(git log "$LATEST_TAG..HEAD" --pretty=format:"%s" 2>/dev/null | grep -iE "^change|^refactor|^update|^modify|^perf" || true)
REMOVED=$(git log "$LATEST_TAG..HEAD" --pretty=format:"%s" 2>/dev/null | grep -iE "^remove|^delete|^drop|^deprecat" || true)
DOCS=$(git log "$LATEST_TAG..HEAD" --pretty=format:"%s" 2>/dev/null | grep -iE "^doc|^readme|^changelog" || true)
OTHER=$(git log "$LATEST_TAG..HEAD" --pretty=format:"%s" 2>/dev/null | grep -viE "^(feat|fix|bug|hotfix|patch|change|refactor|update|modify|perf|remove|delete|drop|deprecat|doc|readme|changelog)" || true)

write_section() {
  local heading="$1"
  local content="$2"
  if [ -n "$content" ]; then
    echo "### $heading" >> "$CHANGELOG_FILE"
    echo "$content" | while IFS= read -r line; do
      echo "- $line" >> "$CHANGELOG_FILE"
    done
    echo "" >> "$CHANGELOG_FILE"
  fi
}

write_section "Added" "$ADDED"
write_section "Fixed" "$FIXED"
write_section "Changed" "$CHANGED"
write_section "Removed" "$REMOVED"
write_section "Documentation" "$DOCS"
write_section "Other" "$OTHER"

echo "---" >> "$CHANGELOG_FILE"
echo "_Generated by generate-changelog.sh_" >> "$CHANGELOG_FILE"

echo "CHANGELOG generated at $CHANGELOG_FILE"
