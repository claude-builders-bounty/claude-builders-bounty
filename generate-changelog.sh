#!/usr/bin/env bash
set -euo pipefail
OUTPUT="CHANGELOG.md"
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
if [ -z "$LAST_TAG" ]; then
    COMMITS=$(git log --pretty=format:"%h %s" --reverse)
else
    COMMITS=$(git log "$LAST_TAG..HEAD" --pretty=format:"%h %s" --reverse)
fi
ADDED=""; FIXED=""; CHANGED=""; REMOVED=""
while IFS= read -r line; do
    h=$(echo "$line" | cut -d' ' -f1); m=$(echo "$line" | cut -d' ' -f2-)
    lm=$(echo "$m" | tr '[:upper:]' '[:lower:]')
    case "$lm" in
        feat:*|add*|new*|implement*|create*) ADDED="$ADDED\n  - $m ($h)" ;;
        fix*|bug*|patch*) FIXED="$FIXED\n  - $m ($h)" ;;
        chore*|refactor*|update*|bump*) CHANGED="$CHANGED\n  - $m ($h)" ;;
        remove*|delete*|deprecate*) REMOVED="$REMOVED\n  - $m ($h)" ;;
        *) CHANGED="$CHANGED\n  - $m ($h)" ;;
    esac
done <<< "$COMMITS"
{ echo "# Changelog"; echo ""; echo "## [Unreleased]"; echo ""
  [ -n "$ADDED" ] && { echo "### Added"; echo -e "$ADDED"; echo ""; }
  [ -n "$FIXED" ] && { echo "### Fixed"; echo -e "$FIXED"; echo ""; }
  [ -n "$CHANGED" ] && { echo "### Changed"; echo -e "$CHANGED"; echo ""; }
  [ -n "$REMOVED" ] && { echo "### Removed"; echo -e "$REMOVED"; echo ""; }
  echo "---"; echo "_Generated by generate-changelog.sh_"; } > "$OUTPUT"
echo "Changelog generated: $OUTPUT"
