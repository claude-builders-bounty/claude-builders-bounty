#!/usr/bin/env python3
"""changelog-generator.py — Generate structured CHANGELOG.md from git history"""
import subprocess, sys, os, re
from datetime import date

def run(cmd):
    try:
        r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=sys.argv[2] if len(sys.argv)>2 else ".")
        return r.stdout.strip()
    except: return ""

def main():
    repo_dir = sys.argv[2] if len(sys.argv) > 2 else "."
    output = sys.argv[1] if len(sys.argv) > 1 else "CHANGELOG.md"

    last_tag = run("git describe --tags --abbrev=0 2>/dev/null || git rev-list --max-parents=0 HEAD")
    log = run(f"git log {last_tag}..HEAD --oneline --no-merges 2>/dev/null")

    cats = {"Added": [], "Fixed": [], "Changed": [], "Removed": [], "Other": []}
    patterns = {
        "Added": r"^(feat|add|new|feature|implement|create|introduce)",
        "Fixed": r"^(fix|bug|hotfix|patch|correct|resolve|repair)",
        "Changed": r"^(refactor|update|change|modify|improve|optimize|migrate)",
        "Removed": r"^(remove|delete|drop|deprecate|revert)",
    }

    for line in log.split("\n"):
        if not line.strip(): continue
        matched = False
        for cat, pat in patterns.items():
            if re.search(pat, line.lower()):
                cats[cat].append(line)
                matched = True; break
        if not matched:
            cats["Other"].append(line)

    version = run("git describe --tags --abbrev=0 2>/dev/null") or "0.1.0"
    today = date.today().isoformat()

    lines = [f"# Changelog\n", f"## [{version}] - {today}\n"]
    for cat in ["Added", "Fixed", "Changed", "Removed", "Other"]:
        items = cats[cat]
        lines.append(f"\n### {cat}\n")
        if items:
            for item in items: lines.append(f"- {item}\n")
        else:
            lines.append("  (none)\n")

    lines.append("\n---\n*Generated by changelog-generator.py — Bounty #1*\n")
    
    with open(os.path.join(repo_dir, output), "w", encoding="utf-8") as f:
        f.writelines(lines)
    print(f"[OK] {output} generated ({len(lines)} lines)")

if __name__ == "__main__":
    main()
