#!/usr/bin/env python3
"""
PR Review Agent - Analyzes GitHub PRs and generates structured review comments.
Usage: python pr_reviewer.py --pr https://github.com/owner/repo/pull/123
"""

import argparse
import json
import os
import re
import sys
from urllib.request import Request, urlopen
from urllib.error import HTTPError

# Configuration
GITHUB_TOKEN = os.getenv('GH_TOKEN', '')
CLAUDE_API_KEY = os.getenv('ANTHROPIC_API_KEY', os.getenv('CLAUDE_API_KEY', ''))

def fetch_pr_diff(pr_url: str) -> tuple[str, str, str]:
    """Fetch PR details and diff from GitHub API."""
    # Parse URL: https://github.com/owner/repo/pull/123
    match = re.search(r'github\.com/([^/]+)/([^/]+)/pull/(\d+)', pr_url)
    if not match:
        raise ValueError(f"Invalid PR URL: {pr_url}")
    
    owner, repo, pr_number = match.groups()
    
    # Fetch PR details
    api_url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr_number}"
    req = Request(api_url)
    req.add_header('Authorization', f'token {GITHUB_TOKEN}')
    req.add_header('Accept', 'application/vnd.github.v3+json')
    
    with urlopen(req) as response:
        pr_data = json.loads(response.read().decode())
    
    title = pr_data.get('title', '')
    body = pr_data.get('body', '') or ''
    
    # Fetch diff
    diff_url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr_number}.diff"
    req = Request(diff_url)
    req.add_header('Authorization', f'token {GITHUB_TOKEN}')
    req.add_header('Accept', 'application/vnd.github.v3.diff')
    
    with urlopen(req) as response:
        diff = response.read().decode()
    
    return title, body, diff

def analyze_pr(title: str, body: str, diff: str) -> dict:
    """Send PR to Claude API for analysis."""
    
    prompt = f"""You are an expert code reviewer. Analyze this pull request and provide a structured review.

## PR Title
{title}

## PR Description
{body if body else '(No description provided)'}

## Code Diff
{diff[:15000]}  # Truncate to avoid token limits

Provide your review in the following format:

### Summary
(2-3 sentences summarizing the changes)

### Identified Risks
- (List any potential issues, bugs, or concerns)
- (If none, write "None identified")

### Improvement Suggestions
- (List specific suggestions for code quality, performance, security, etc.)
- (If none, write "No major improvements suggested")

### Confidence Score
(Low / Medium / High - based on the complexity and your confidence in the review)

Be concise but thorough. Focus on:
1. Code correctness
2. Security issues
3. Performance implications
4. Code style and maintainability
5. Test coverage"""

    headers = {
        'x-api-key': CLAUDE_API_KEY,
        'Content-Type': 'application/json',
        'anthropic-version': '2023-06-01'
    }
    
    payload = {
        'model': 'claude-sonnet-4-20250514',
        'max_tokens': 1024,
        'messages': [
            {'role': 'user', 'content': prompt}
        ]
    }
    
    req = Request('https://api.anthropic.com/v1/messages')
    req.add_header('Content-Type', 'application/json')
    req.add_header('x-api-key', CLAUDE_API_KEY)
    req.add_header('anthropic-version', '2023-06-01')
    
    data = json.dumps(payload).encode('utf-8')
    
    with urlopen(req, data=data) as response:
        result = json.loads(response.read().decode())
    
    return result['content'][0]['text']

def generate_markdown_comment(analysis: str, pr_url: str) -> str:
    """Format the analysis as a GitHub comment."""
    
    return f"""## 🤖 Automated PR Review

{analysis}

---

*Generated by [PR Review Agent](https://github.com/claude-builders-bounty/claude-builders-bounty/tree/main/pr-reviewer)*
*Reviewing: {pr_url}*
"""

def post_github_comment(pr_url: str, comment: str):
    """Post comment to GitHub PR."""
    match = re.search(r'github\.com/([^/]+)/([^/]+)/pull/(\d+)', pr_url)
    if not match:
        raise ValueError(f"Invalid PR URL: {pr_url}")
    
    owner, repo, pr_number = match.groups()
    
    api_url = f"https://api.github.com/repos/{owner}/{repo}/issues/{pr_number}/comments"
    
    req = Request(api_url)
    req.add_header('Authorization', f'token {GITHUB_TOKEN}')
    req.add_header('Accept', 'application/vnd.github.v3+json')
    req.add_header('Content-Type', 'application/json')
    
    data = json.dumps({'body': comment}).encode('utf-8')
    
    try:
        with urlopen(req, data=data) as response:
            result = json.loads(response.read().decode())
            return result['html_url']
    except HTTPError as e:
        print(f"Error posting comment: {e.code} {e.reason}")
        raise

def main():
    parser = argparse.ArgumentParser(description='PR Review Agent for GitHub')
    parser.add_argument('--pr', required=True, help='GitHub PR URL')
    parser.add_argument('--post', action='store_true', help='Post comment to GitHub')
    parser.add_argument('--output', type=str, help='Output file path (optional)')
    
    args = parser.parse_args()
    
    # Check environment
    if not GITHUB_TOKEN:
        print("❌ Error: GH_TOKEN environment variable not set")
        print("Set it with: export GH_TOKEN=your_token")
        sys.exit(1)
    
    if not CLAUDE_API_KEY:
        print("❌ Error: ANTHROPIC_API_KEY or CLAUDE_API_KEY not set")
        print("Set it with: export ANTHROPIC_API_KEY=your_key")
        sys.exit(1)
    
    print(f"🔍 Fetching PR: {args.pr}")
    title, body, diff = fetch_pr_diff(args.pr)
    
    print(f"📄 PR Title: {title}")
    print(f"📊 Diff size: {len(diff)} chars")
    
    print("🤖 Analyzing with Claude...")
    analysis = analyze_pr(title, body, diff)
    
    comment = generate_markdown_comment(analysis, args.pr)
    
    # Output
    if args.output:
        with open(args.output, 'w') as f:
            f.write(comment)
        print(f"✅ Review saved to: {args.output}")
    
    print("\n" + "="*50)
    print(comment)
    print("="*50)
    
    # Post to GitHub if requested
    if args.post:
        print("📤 Posting comment to GitHub...")
        comment_url = post_github_comment(args.pr, comment)
        print(f"✅ Comment posted: {comment_url}")

if __name__ == '__main__':
    main()
