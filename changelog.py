#!/usr/bin/env python3
"""Generate CHANGELOG.md from git history since last tag."""
import argparse
import re
import subprocess
import sys
from datetime import date
from pathlib import Path


def run(cmd, cwd):
    return subprocess.check_output(cmd, cwd=cwd, text=True).strip()


def categorize(msg: str) -> str:
    first = msg.split()[0].lower() if msg.split() else ""
    if first in ("add", "added", "feat", "feature", "create", "implement"):
        return "Added"
    if first in ("fix", "fixed", "bug", "patch", "hotfix", "correct", "revert"):
        return "Fixed"
    if first in ("remove", "removed", "delete", "deleted", "deprecate", "drop"):
        return "Removed"
    return "Changed"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", default=".")
    parser.add_argument("--output", default="CHANGELOG.md")
    args = parser.parse_args()

    repo = Path(args.repo).resolve()
    output = Path(args.output)

    # Determine version range
    try:
        last_tag = run(["git", "describe", "--tags", "--abbrev=0"], repo)
        since = f"{last_tag}..HEAD"
        version = last_tag
        tag_date = run(["git", "log", "-1", "--format=%as", last_tag], repo)
        ver_date = tag_date if tag_date else str(date.today())
    except subprocess.CalledProcessError:
        since = "HEAD"
        commit_count = run(["git", "rev-list", "--count", "HEAD"], repo)
        version = f"{commit_count}-commits"
        ver_date = str(date.today())

    # Categorize commits
    sections = {"Added": [], "Fixed": [], "Changed": [], "Removed": []}
    try:
        log = run(["git", "log", "--oneline", since], repo)
        for line in log.split("\n"):
            msg = re.sub(r"^[0-9a-f]{7,40}\s*", "", line).strip()
            if msg:
                sections[categorize(msg)].append(f"- {msg}")
    except subprocess.CalledProcessError:
        print("Warning: no commits found in range", since, file=sys.stderr)

    # Write
    lines = [f"# Changelog\n", f"\n## [{version}] - {ver_date}\n"]
    for section in ("Added", "Fixed", "Changed", "Removed"):
        if sections[section]:
            lines.append(f"\n### {section}\n")
            lines.extend(f"{item}\n" for item in sections[section])

    lines.append("\n---\n_Generated by changelog.py_\n")
    output.write_text("".join(lines))
    print(f"✓ Wrote {output} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
