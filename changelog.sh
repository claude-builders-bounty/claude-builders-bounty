#!/bin/bash
# CHANGELOG Generator - 从git历史生成结构化CHANGELOG.md
# 用法: ./changelog.sh [--tag <tag>] [--output CHANGELOG.md]

set -euo pipefail

OUTPUT="CHANGELOG.md"
SINCE_TAG=""

while [[ $# -gt 0 ]]; do
  case $1 in
    --tag) SINCE_TAG="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    *) echo "用法: $0 [--tag <tag>] [--output <file>]"; exit 1 ;;
  esac
done

if [ -z "$SINCE_TAG" ]; then
  SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
fi

LOG_CMD="git log --pretty=format:'---%ncommit: %H%nauthor: %an%ndate: %ad%nmsg: %s%nbody: %b' --date=short"
[ -n "$SINCE_TAG" ] && LOG_CMD="$LOG_CMD $SINCE_TAG..HEAD"

echo "📝 Generating CHANGELOG..."
echo "   From: ${SINCE_TAG:-project start} to: HEAD"
echo "   Output: $OUTPUT"

TMPFILE=$(mktemp)
trap "rm -f $TMPFILE" EXIT
eval "$LOG_CMD" > "$TMPFILE"

ADDED=""; FIXED=""; CHANGED=""; REMOVED=""; OTHER=""
REPO_URL=$(git remote get-url origin 2>/dev/null | sed 's/.*@//' | sed 's/\.git$//' | sed 's|https://||' | sed 's|github.com/||')

parse_commit() {
  local hash="$1" author="$2" date="$3" msg="$4"
  local type scope desc
  type=$(echo "$msg" | sed -nE 's/^([a-z]+)[(!(:].*/\1/p')
  desc=$(echo "$msg" | sed -nE 's/^[a-z]+(\([^)]+\))?[!]?:[[:space:]]*(.*)/\2/p')
  [ -z "$desc" ] && desc="$msg"
  
  local link="[$hash](https://github.com/$REPO_URL/commit/$hash)"
  
  case "$type" in
    feat|feature) ADDED="$ADDED
- $desc ($link)";;
    fix|bugfix)   FIXED="$FIXED
- $desc ($link)";;
    change|refactor|perf|update) CHANGED="$CHANGED
- $desc ($link)";;
    remove|deprecate|delete) REMOVED="$REMOVED
- $desc ($link)";;
    *)            OTHER="$OTHER
- $desc ($link)";;
  esac
}

# 解析每个commit
current_hash=""; current_author=""; current_date=""; current_msg=""
while IFS= read -r line; do
  case "$line" in
    "---") 
      [ -n "$current_hash" ] && parse_commit "$current_hash" "$current_author" "$current_date" "$current_msg"
      current_hash=""; current_author=""; current_date=""; current_msg=""
      ;;
    commit:*) current_hash="${line#commit: }" ;;
    author:*) current_author="${line#author: }" ;;
    date:*) current_date="${line#date: }" ;;
    msg:*) current_msg="${line#msg: }" ;;
    body:*) ;;
  esac
done < "$TMPFILE"
[ -n "$current_hash" ] && parse_commit "$current_hash" "$current_author" "$current_date" "$current_msg"

# 生成CHANGELOG.md
{
  echo "# Changelog"
  echo ""
  echo "## [Unreleased]"
  echo ""
  [ -n "$ADDED" ] && echo "### Added" && echo "$ADDED" && echo ""
  [ -n "$FIXED" ] && echo "### Fixed" && echo "$FIXED" && echo ""
  [ -n "$CHANGED" ] && echo "### Changed" && echo "$CHANGED" && echo ""
  [ -n "$REMOVED" ] && echo "### Removed" && echo "$REMOVED" && echo ""
  [ -n "$OTHER" ] && echo "### Other" && echo "$OTHER"
  echo ""
  echo "---"
  echo "_Generated by changelog.sh_"
} > "$OUTPUT"

echo "✅ CHANGELOG.md generated ($(wc -l < "$OUTPUT") lines)"
head -20 "$OUTPUT"
