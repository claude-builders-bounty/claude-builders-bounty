#!/usr/bin/env bash
set -euo pipefail

# changelog.sh — Generate CHANGELOG.md from git history
# Usage: bash changelog.sh [--repo /path/to/repo] [--output CHANGELOG.md]

REPO="${1:-$(pwd)}"
OUTPUT="${2:-CHANGELOG.md}"
TAG="$(git -C "$REPO" describe --tags --abbrev=0 2>/dev/null || echo "")"

if [ -z "$TAG" ]; then
  echo "No git tag found. Generating changelog from all commits."
  RANGE="HEAD"
else
  echo "Using tag: $TAG"
  RANGE="$TAG..HEAD"
fi

cat > "$OUTPUT" << 'HEADER'
# Changelog

All notable changes to this project will be documented in this file.

The format is based on [Keep a Changelog](https://keepachangelog.com/en/1.1.0/).

HEADER

echo "## [Unreleased] - $(date +%Y-%m-%d)" >> "$OUTPUT"
echo "" >> "$OUTPUT"

# Categorize commits
added=$(git -C "$REPO" log "$RANGE" --grep="^feat" --oneline --format="  - %s (%h)" 2>/dev/null || true)
fixed=$(git -C "$REPO" log "$RANGE" --grep="^fix" --oneline --format="  - %s (%h)" 2>/dev/null || true)
changed=$(git -C "$REPO" log "$RANGE" --grep="^(refactor|perf|style)" --oneline --format="  - %s (%h)" 2>/dev/null || true)
removed=$(git -C "$REPO" log "$RANGE" --grep="^chore" --oneline --format="  - %s (%h)" 2>/dev/null || true)
other=$(git -C "$REPO" log "$RANGE" --oneline --format="  - %s (%h)" 2>/dev/null || true)

write_section() {
  local title="$1" content="$2"
  if [ -n "$content" ]; then
    echo "### $title" >> "$OUTPUT"
    echo "$content" >> "$OUTPUT"
    echo "" >> "$OUTPUT"
  fi
}

write_section "Added" "$added"
write_section "Fixed" "$fixed"
write_section "Changed" "$changed"
write_section "Removed" "$removed"

# Other commits (not categorized above)
cat_added=$(echo "$added" | wc -l)
cat_fixed=$(echo "$fixed" | wc -l)
cat_changed=$(echo "$changed" | wc -l)
cat_removed=$(echo "$removed" | wc -l)
total_categorized=$((cat_added + cat_fixed + cat_changed + cat_removed))

if [ -n "$other" ]; then
  # Filter out already categorized
  echo "### Other" >> "$OUTPUT"
  git -C "$REPO" log "$RANGE" --oneline --format="  - %s (%h)" 2>/dev/null | while IFS= read -r line; do
    case "$line" in
      *"feat:"*|*"fix:"*|*"refactor:"*|*"perf:"*|*"style:"*|*"chore:"*) ;;
      *) echo "$line" >> "$OUTPUT" ;;
    esac
  done
  echo "" >> "$OUTPUT"
fi

echo "---" >> "$OUTPUT"
echo "Generated by changelog.sh on $(date)" >> "$OUTPUT"

echo "Wrote $OUTPUT ($(wc -l < "$OUTPUT") lines)"
