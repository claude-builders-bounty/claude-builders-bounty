#!/usr/bin/env bash
#
# changelog.sh — Generate a structured CHANGELOG.md from git history
#
# Usage:
#   ./changelog.sh                    # generates CHANGELOG.md from last tag to HEAD
#   ./changelog.sh --all              # includes all commits (no tag filtering)
#   ./changelog.sh --tag v1.0.0       # from specific tag to HEAD
#   ./changelog.sh v1.0.0..v2.0.0     # range of tags
#
# Requirements: git, bash 4+

set -euo pipefail

OUTPUT_FILE="${OUTPUT_FILE:-CHANGELOG.md}"
VERSION=""

# ── Parse arguments ──────────────────────────────────────────────

RANGE=""
USE_ALL=false

case "${1:-}" in
  --all)
    USE_ALL=true
    ;;
  --tag)
    RANGE="${2:-}..HEAD"
    VERSION="since ${2:-}"
    ;;
  *..*)
    RANGE="$1"
    ;;
  "")
    ;;
  *)
    echo "Usage: $0 [--all | --tag <tag> | <tag1>..<tag2>]"
    exit 1
    ;;
esac

# ── Determine commit range ───────────────────────────────────────

if [ "$USE_ALL" = true ]; then
  COMMITS=$(git log --oneline --no-decorate HEAD)
  VERSION="All Commits"
elif [ -n "$RANGE" ]; then
  COMMITS=$(git log --oneline --no-decorate "$RANGE" 2>/dev/null) || {
    echo "Error: invalid range '$RANGE'"
    exit 1
  }
  VERSION="${RANGE}"
else
  # Get latest tag; fallback to first commit if no tags exist
  LATEST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || true)
  if [ -n "$LATEST_TAG" ]; then
    COMMITS=$(git log --oneline --no-decorate "${LATEST_TAG}..HEAD" 2>/dev/null) || true
    VERSION="${LATEST_TAG} → HEAD"
  else
    COMMITS=$(git log --oneline --no-decorate HEAD)
    VERSION="Initial Release (no tags yet)"
  fi
fi

# ── Categorisation ───────────────────────────────────────────────

declare -a added fixed changed removed other

while IFS= read -r line; do
  [ -z "$line" ] && continue
  commit_hash="${line%% *}"
  # Strip hash and any leading whitespace to get the message
  message="${line#"$commit_hash"}"
  message="${message#"${message%%[![:space:]]*}"}"

  # Skip merge commits
  [[ "$message" =~ ^Merge ]] && continue
  [[ "$message" =~ ^Revert ]] && continue

  prefix_lower=$(echo "$message" | tr '[:upper:]' '[:lower:]')

  # Classify by conventional commit prefix
  if   [[ "$prefix_lower" =~ ^(feat|add|implement|create|introduce|new)(\(|:|\ ) ]] || \
       [[ "$prefix_lower" =~ ^feat(\(.*\))?: ]]; then
    added+=("- ${message}")
  elif [[ "$prefix_lower" =~ ^(fix|resolve|patch|correct|repair|hotfix)(\(|:|\ ) ]] || \
       [[ "$prefix_lower" =~ ^fix(\(.*\))?: ]]; then
    fixed+=("- ${message}")
  elif [[ "$prefix_lower" =~ ^(change|update|modify|tweak|adjust|refactor|perf|style|improve|enhance|upgrade|rename|move|rewrite)(\(|:|\ ) ]] || \
       [[ "$prefix_lower" =~ ^(refactor|perf|chore|style)(\(.*\))?: ]]; then
    changed+=("- ${message}")
  elif [[ "$prefix_lower" =~ ^(remove|delete|drop|deprecate|retire|obsolete)(\(|:|\ ) ]] || \
       [[ "$prefix_lower" =~ ^revert(\(.*\))?: ]]; then
    removed+=("- ${message}")
  else
    other+=("- ${message}")
  fi
done <<< "$COMMITS"

# If nothing was classified, put everything under "Changed"
if [ ${#added[@]} -eq 0 ] && [ ${#fixed[@]} -eq 0 ] && \
   [ ${#changed[@]} -eq 0 ] && [ ${#removed[@]} -eq 0 ] && \
   [ ${#other[@]} -gt 0 ]; then
  changed=("${other[@]}")
  other=()
fi

# ── Generate output ──────────────────────────────────────────────

TODAY=$(date '+%Y-%m-%d')
REPO_NAME=$(basename "$(git rev-parse --show-toplevel 2>/dev/null)" 2>/dev/null || echo "project")
REPO_URL=$(git config --get remote.origin.url 2>/dev/null | sed 's/\.git$//' | sed 's|^git@github.com:|https://github.com/|' || echo "")

{
  echo "# Changelog"
  echo ""
  echo "## [Unreleased] — ${TODAY}"
  echo ""
  echo "> Generated from: \`${VERSION}\`"
  if [ -n "$REPO_URL" ]; then
    echo "> Repository: [${REPO_NAME}](${REPO_URL})"
  fi
  echo ""

  # ── Added ──
  if [ ${#added[@]} -gt 0 ]; then
    echo "### Added"
    for entry in "${added[@]}"; do
      echo "$entry"
    done
    echo ""
  fi

  # ── Fixed ──
  if [ ${#fixed[@]} -gt 0 ]; then
    echo "### Fixed"
    for entry in "${fixed[@]}"; do
      echo "$entry"
    done
    echo ""
  fi

  # ── Changed ──
  if [ ${#changed[@]} -gt 0 ]; then
    echo "### Changed"
    for entry in "${changed[@]}"; do
      echo "$entry"
    done
    echo ""
  fi

  # ── Removed ──
  if [ ${#removed[@]} -gt 0 ]; then
    echo "### Removed"
    for entry in "${removed[@]}"; do
      echo "$entry"
    done
    echo ""
  fi

  # ── Uncategorised fallback ──
  if [ ${#other[@]} -gt 0 ]; then
    echo "### Other"
    for entry in "${other[@]}"; do
      echo "$entry"
    done
    echo ""
  fi

  echo "---"
  echo ""
  echo "*Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty)*"
} > "$OUTPUT_FILE"

echo "✅ CHANGELOG.md generated successfully!"
echo "   Commits processed: $(echo "$COMMITS" | grep -c '^')"
echo "   Added:   ${#added[@]}"
echo "   Fixed:   ${#fixed[@]}"
echo "   Changed: ${#changed[@]}"
echo "   Removed: ${#removed[@]}"
echo "   Other:   ${#other[@]}"
echo "   Output:  $OUTPUT_FILE"
