#!/usr/bin/env bash
set -euo pipefail

# -------------------------------------------------------------------
# changelog.sh — Generate a structured CHANGELOG.md from git history
# -------------------------------------------------------------------
# Usage: bash changelog.sh [--output CHANGELOG.md]
#
# Requirements: git, bash 4+
# -------------------------------------------------------------------

OUTPUT="${1:-CHANGELOG.md}"
REPO_NAME=""
PROJECT_NAME=""

# Try to detect repo name from git remote
if REMOTE_URL=$(git config --get remote.origin.url 2>/dev/null); then
    REPO_NAME=$(basename "$REMOTE_URL" .git 2>/dev/null || echo "project")
fi

# Get the last tag (if any)
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")

# Determine commit range
if [ -n "$LAST_TAG" ]; then
    COMMIT_RANGE="${LAST_TAG}..HEAD"
    RANGE_DESC="Since ${LAST_TAG}"
else
    COMMIT_RANGE="HEAD"
    RANGE_DESC="Initial commits"
fi

# Get current date
DATE=$(date +%Y-%m-%d)

# Gather commits
COMMITS=$(git log "${COMMIT_RANGE}" --pretty=format:"%H||%s||%an||%ad" --date=short 2>/dev/null || true)

if [ -z "$COMMITS" ]; then
    echo "No commits found in range ${COMMIT_RANGE}."
    exit 1
fi

# Categorize commits
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""

while IFS='||' read -r HASH SUBJECT AUTHOR DATE; do
    SHORT_HASH=$(echo "$HASH" | head -c 7)
    LINE="- ${SUBJECT} ([${SHORT_HASH}](https://github.com/${REPO_NAME}/commit/${HASH}))"

    # Categorize by conventional commit prefix
    case "$SUBJECT" in
        feat:*|feature:*|"feat("*|add:*|implement:*|create:*)
            ADDED="${ADDED}\n${LINE}"
            ;;
        fix:*|bugfix:*|hotfix:*|"fix("*)
            FIXED="${FIXED}\n${LINE}"
            ;;
        breaking:*|"!"*|*"!"*)
            CHANGED="${CHANGED}\n${LINE}"
            ;;
        remove:*|deprecate:*|"remove("*|drop:*)
            REMOVED="${REMOVED}\n${LINE}"
            ;;
        change:*|refactor:*|update:*|"change("*|"refactor("*)
            CHANGED="${CHANGED}\n${LINE}"
            ;;
        *)
            # Default: check keywords in subject
            LOWERCASE=$(echo "$SUBJECT" | tr '[:upper:]' '[:lower:]')
            case "$LOWERCASE" in
                *"add"*|*"new"*|*"implement"*|*"create"*|*"introduce"*)
                    ADDED="${ADDED}\n${LINE}" ;;
                *"fix"*|*"bug"*|*"correct"*|*"patch"*|*"resolve"*)
                    FIXED="${FIXED}\n${LINE}" ;;
                *"remove"*|*"delete"*|*"deprecat"*|*"drop"*)
                    REMOVED="${REMOVED}\n${LINE}" ;;
                *"change"*|*"update"*|*"refactor"*|*"improve"*|*"migrate"*)
                    CHANGED="${CHANGED}\n${LINE}" ;;
                *)
                    CHANGED="${CHANGED}\n${LINE}" ;;
            esac
            ;;
    esac
done <<< "$COMMITS"

# Generate CHANGELOG.md
cat > "$OUTPUT" << CHANGELOG_EOF
# Changelog

All notable changes to this project will be documented in this file.

${RANGE_DESC} — ${DATE}

$( [ -n "$ADDED" ] && echo -e "## Added\n${ADDED}\n" )
$( [ -n "$FIXED" ] && echo -e "## Fixed\n${FIXED}\n" )
$( [ -n "$CHANGED" ] && echo -e "## Changed\n${CHANGED}\n" )
$( [ -n "$REMOVED" ] && echo -e "## Removed\n${REMOVED}\n" )

---

*Generated by changelog.sh — ${DATE}*
CHANGELOG_EOF

echo "✓ CHANGELOG.md generated with $(echo "$COMMITS" | wc -l) commits"
