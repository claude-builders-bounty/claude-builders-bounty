#!/usr/bin/env bash
# =============================================================================
# CHANGELOG Generator — Structured CHANGELOG.md from git history
# =============================================================================
# Usage:  bash changelog.sh [--since <tag>] [--output <file>]
#         bash changelog.sh --since v1.0.0
#         bash changelog.sh                    # uses latest tag
#
# Works as: standalone shell script OR `/generate-changelog` Claude Code command
# =============================================================================

set -euo pipefail

OUTPUT="${OUTPUT:-CHANGELOG.md}"
SINCE_TAG=""

# ── Parse arguments ─────────────────────────────────────────────────────────
while [[ $# -gt 0 ]]; do
  case "$1" in
    --since) SINCE_TAG="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    -h|--help)
      echo "Usage: bash changelog.sh [--since <tag>] [--output <file>]"
      echo "Generates CHANGELOG.md from git commits since the specified tag"
      echo "If no --since provided, uses the most recent git tag"
      exit 0
      ;;
    *) shift ;;
  esac
done

# ── Determine starting point ────────────────────────────────────────────────
if [[ -z "$SINCE_TAG" ]]; then
  SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
  if [[ -z "$SINCE_TAG" ]]; then
    # No tags at all — use first commit
    SINCE_TAG=$(git rev-list --max-parents=0 HEAD 2>/dev/null || echo "HEAD~100")
    echo "⚠️  No git tags found. Including all commits since first commit." >&2
  fi
fi

echo "📝 Generating CHANGELOG from $SINCE_TAG to HEAD..."

# ── Fetch commits ───────────────────────────────────────────────────────────
# Format: hash|date|author|subject
COMMITS=$(git log "${SINCE_TAG}..HEAD" --pretty=format:"%h|%as|%an|%s" 2>/dev/null || echo "")

if [[ -z "$COMMITS" ]]; then
  echo "⚠️  No commits since $SINCE_TAG. Generating empty changelog." >&2
fi

# ── Version / date ──────────────────────────────────────────────────────────
VERSION=$(git describe --tags --abbrev=0 2>/dev/null || echo "Unreleased")
DATE=$(date +%Y-%m-%d)

# ── Categorize commits ──────────────────────────────────────────────────────
declare -a ADDED=()
declare -a FIXED=()
declare -a CHANGED=()
declare -a REMOVED=()
declare -a OTHER=()

while IFS='|' read -r hash date author subject; do
  [[ -z "$subject" ]] && continue

  REPO_URL=$(git remote get-url origin 2>/dev/null | sed 's|.*github.com[:/]||;s|\.git$||' | head -1)
  ENTRY="- ${subject} ([${hash}](https://github.com/${REPO_URL}/commit/${hash}))"

  # Categorize by conventional commit prefix
  if echo "$subject" | grep -qiE '^(feat|add|implement|introduce|create)'; then
    ADDED+=("$ENTRY")
  elif echo "$subject" | grep -qiE '^(fix|bug|resolve|patch|hotfix|repair)'; then
    FIXED+=("$ENTRY")
  elif echo "$subject" | grep -qiE '^(remove|drop|deprecate|delete)'; then
    REMOVED+=("$ENTRY")
  elif echo "$subject" | grep -qiE '^(change|refactor|update|modify|adjust|tweak|improve|enhance|perf|style)'; then
    CHANGED+=("$ENTRY")
  else
    OTHER+=("$ENTRY")
  fi
done <<< "$COMMITS"

# ── Generate CHANGELOG.md ───────────────────────────────────────────────────
{
  echo "# Changelog"
  echo ""
  echo "## [${VERSION}] — ${DATE}"
  echo ""

  if [[ ${#ADDED[@]} -gt 0 ]]; then
    echo "### Added"
    for item in "${ADDED[@]}"; do
      echo "$item"
    done
    echo ""
  fi

  if [[ ${#FIXED[@]} -gt 0 ]]; then
    echo "### Fixed"
    for item in "${FIXED[@]}"; do
      echo "$item"
    done
    echo ""
  fi

  if [[ ${#CHANGED[@]} -gt 0 ]]; then
    echo "### Changed"
    for item in "${CHANGED[@]}"; do
      echo "$item"
    done
    echo ""
  fi

  if [[ ${#REMOVED[@]} -gt 0 ]]; then
    echo "### Removed"
    for item in "${REMOVED[@]}"; do
      echo "$item"
    done
    echo ""
  fi

  if [[ ${#OTHER[@]} -gt 0 ]]; then
    echo "### Other"
    for item in "${OTHER[@]}"; do
      echo "$item"
    done
    echo ""
  fi

  echo "---"
  echo "*Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty)*"
} > "$OUTPUT"

# ── Summary ─────────────────────────────────────────────────────────────────
TOTAL=$(( ${#ADDED[@]} + ${#FIXED[@]} + ${#CHANGED[@]} + ${#REMOVED[@]} + ${#OTHER[@]} ))
echo ""
echo "✅ CHANGELOG.md generated successfully!"
echo "   📦 Total commits: $TOTAL"
echo "   ➕ Added:    ${#ADDED[@]}"
echo "   🐛 Fixed:    ${#FIXED[@]}"
echo "   🔄 Changed:  ${#CHANGED[@]}"
echo "   🗑️  Removed:  ${#REMOVED[@]}"
echo "   📋 Other:    ${#OTHER[@]}"
echo "   📄 Output:   $OUTPUT"
