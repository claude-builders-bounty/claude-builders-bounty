#!/usr/bin/env bash
# ============================================================
# changelog.sh — Generate structured CHANGELOG.md from git history
#
# Bounty: claude-builders-bounty #1 ($50)
# Usage:  bash changelog.sh [--since <tag>] [--output <file>] [--dry-run]
# ============================================================
set -euo pipefail

# --- config -------------------------------------------------
OUTPUT="${PWD}/CHANGELOG.md"
DRY_RUN=false
SINCE_TAG=""
TMPFILE=$(mktemp /tmp/changelog.XXXXXX)
trap 'rm -f "$TMPFILE"' EXIT

# --- helpers ------------------------------------------------
usage() {
  cat <<'EOF'
Usage: bash changelog.sh [options]

Options:
  --since <tag>   Start from a specific git tag (default: latest tag)
  --output <file> Output file path (default: ./CHANGELOG.md)
  --dry-run       Print to stdout instead of writing file
  --help          Show this help

Example:
  bash changelog.sh
  bash changelog.sh --since v1.0.0 --output RELEASE_NOTES.md
EOF
  exit 0
}

red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }
cyan()  { printf '\033[36m%s\033[0m\n' "$*"; }

# --- parse args ---------------------------------------------
while [[ $# -gt 0 ]]; do
  case "$1" in
    --since)   SINCE_TAG="$2"; shift 2 ;;
    --output)  OUTPUT="$2";   shift 2 ;;
    --dry-run) DRY_RUN=true;  shift ;;
    --help)    usage ;;
    *)         red "Unknown: $1"; usage ;;
  esac
done

# --- resolve tag --------------------------------------------
if [[ -z "$SINCE_TAG" ]]; then
  SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || true)
  if [[ -z "$SINCE_TAG" ]]; then
    cyan "No git tags found. Using first commit as start point."
    SINCE_TAG=$(git rev-list --max-parents=0 HEAD)
  fi
fi

cyan "Generating changelog from $SINCE_TAG to HEAD..."

# --- collect commits ----------------------------------------
COMMITS=$(git log "${SINCE_TAG}..HEAD" --no-merges \
  --pretty=format:"%s" 2>/dev/null || true)

if [[ -z "$COMMITS" ]]; then
  red "No commits found since $SINCE_TAG"
  exit 0
fi

# --- categorize commits -------------------------------------
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""

while IFS= read -r msg; do
  [[ -z "$msg" ]] && continue

  # Normalize: lowercase, strip leading/trailing spaces
  lower=$(echo "$msg" | tr '[:upper:]' '[:lower:]')

  # Categorize by commit convention prefix
  if   [[ "$lower" =~ ^(feat|add|new|implement|create|introduce) ]]; then
    ADDED+="  - ${msg}"$'\n'
  elif [[ "$lower" =~ ^(fix|bugfix|hotfix|resolve|patch|repair) ]]; then
    FIXED+="  - ${msg}"$'\n'
  elif [[ "$lower" =~ ^(remove|delete|drop|deprecate|deprecated|obsolete) ]]; then
    REMOVED+="  - ${msg}"$'\n'
  elif [[ "$lower" =~ ^(doc|docs|readme|comment) ]]; then
    CHANGED+="  - ${msg}"$'\n'
  else
    # Fallback: keywords in message body
    if   [[ "$lower" =~ (add|new|feat) ]]; then
      ADDED+="  - ${msg}"$'\n'
    elif [[ "$lower" =~ (fix|bug|correct|repair|patch) ]]; then
      FIXED+="  - ${msg}"$'\n'
    elif [[ "$lower" =~ (remov|delet|drop|deprecat) ]]; then
      REMOVED+="  - ${msg}"$'\n'
    else
      CHANGED+="  - ${msg}"$'\n'
    fi
  fi
done <<< "$COMMITS"

# --- build changelog ----------------------------------------
VERSION="${SINCE_TAG}"
if [[ "$VERSION" =~ ^[a-f0-9]{40}$ ]]; then
  VERSION="Unreleased"
fi

DATE=$(date +%Y-%m-%d)

{
  echo "# Changelog"
  echo ""
  echo "## [${VERSION}] — ${DATE}"
  echo ""

  if [[ -n "$ADDED" ]]; then
    echo "### Added"
    printf '%s' "$ADDED"
    echo ""
  fi

  if [[ -n "$FIXED" ]]; then
    echo "### Fixed"
    printf '%s' "$FIXED"
    echo ""
  fi

  if [[ -n "$CHANGED" ]]; then
    echo "### Changed"
    printf '%s' "$CHANGED"
    echo ""
  fi

  if [[ -n "$REMOVED" ]]; then
    echo "### Removed"
    printf '%s' "$REMOVED"
    echo ""
  fi

  echo "---"
  echo ""
  echo "*Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty) on ${DATE}*"
} > "$TMPFILE"

# --- output -------------------------------------------------
if $DRY_RUN; then
  cat "$TMPFILE"
  green "✅ Dry run complete (not written to file)"
else
  # Prepend to existing if there's old content
  if [[ -f "$OUTPUT" ]]; then
    # Save previous content under a new version
    OLD_CONTENT=$(cat "$OUTPUT")
    {
      cat "$TMPFILE"
      echo ""
      echo "$OLD_CONTENT" | tail -n +4  # skip old header lines
    } > "$OUTPUT"
  else
    mv "$TMPFILE" "$OUTPUT"
  fi
  green "✅ Changelog written to $OUTPUT"
fi
