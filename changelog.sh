#!/usr/bin/env bash
# ============================================================
# changelog.sh — Generate structured CHANGELOG.md from git history
# Usage: ./changelog.sh [since_tag] [output_file]
# ============================================================
set -euo pipefail

OUTPUT="${2:-CHANGELOG.md}"
REPO_NAME=$(basename "$(git rev-parse --show-toplevel 2>/dev/null)" 2>/dev/null || echo "project")

# Determine the starting point: last tag, or first commit
if [ -n "${1:-}" ]; then
    SINCE_TAG="$1"
elif latest_tag=$(git describe --tags --abbrev=0 2>/dev/null); then
    SINCE_TAG="$latest_tag"
else
    SINCE_TAG=""
fi

# Collect commits
if [ -n "$SINCE_TAG" ]; then
    echo "📋 Generating changelog since tag: $SINCE_TAG" >&2
    COMMITS=$(git log "${SINCE_TAG}..HEAD" --pretty=format:"%s" --no-merges 2>/dev/null || echo "")
else
    echo "📋 No tags found — using all commits" >&2
    COMMITS=$(git log --pretty=format:"%s" --no-merges 2>/dev/null || echo "")
fi

if [ -z "$COMMITS" ]; then
    echo "⚠️  No commits found since $SINCE_TAG" >&2
    cat > "$OUTPUT" <<EOF
# Changelog

## [Unreleased]

_No changes since ${SINCE_TAG:-the beginning}._
EOF
    echo "✅ Wrote empty changelog to $OUTPUT"
    exit 0
fi

# Categorize commits
ADDED=()
FIXED=()
CHANGED=()
REMOVED=()
OTHER=()

while IFS= read -r line; do
    line_trimmed=$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
    [ -z "$line_trimmed" ] && continue

    # Conventional commit: feat:, fix:, chore:, docs:, refactor:, etc.
    # Also match common patterns: add, fix, update, remove, delete, deprecate
    msg_lower=$(echo "$line_trimmed" | tr '[:upper:]' '[:lower:]')

    if echo "$msg_lower" | grep -qE '^(feat|add|added|implement|introduce|create)'; then
        ADDED+=("$line_trimmed")
    elif echo "$msg_lower" | grep -qE '^(fix|fixed|bug|hotfix|patch|resolve|correct)'; then
        FIXED+=("$line_trimmed")
    elif echo "$msg_lower" | grep -qE '^(remove|removed|delete|deleted|deprecate|drop)'; then
        REMOVED+=("$line_trimmed")
    elif echo "$msg_lower" | grep -qE '^(chore|refactor|update|change|changed|docs|style|perf|test|ci|build|revert|bump|merge|release)'; then
        CHANGED+=("$line_trimmed")
    else
        OTHER+=("$line_trimmed")
    fi
done <<< "$COMMITS"

# Merge OTHER into CHANGED for cleaner output
if [ ${#OTHER[@]} -gt 0 ]; then
    CHANGED+=("${OTHER[@]}")
fi

# Generate CHANGELOG.md
DATE=$(date +%Y-%m-%d)
VERSION="${SINCE_TAG:-0.1.0} → HEAD"

cat > "$OUTPUT" <<EOF
# Changelog

## [Unreleased] — $DATE

_${VERSION}_

EOF

# Helper to print section
print_section() {
    local title="$1"
    shift
    local items=("$@")
    if [ ${#items[@]} -gt 0 ]; then
        echo "### $title" >> "$OUTPUT"
        echo "" >> "$OUTPUT"
        for item in "${items[@]}"; do
            echo "- $item" >> "$OUTPUT"
        done
        echo "" >> "$OUTPUT"
    fi
}

print_section "🚀 Added" "${ADDED[@]}"
print_section "🐛 Fixed" "${FIXED[@]}"
print_section "🔧 Changed" "${CHANGED[@]}"
print_section "🗑️ Removed" "${REMOVED[@]}"

# Footer
cat >> "$OUTPUT" <<EOF
---
_Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty) on $(date -u +"%Y-%m-%dT%H:%M:%SZ")_
EOF

# Summary
echo "✅ Changelog written to $OUTPUT"
echo "   Added:   ${#ADDED[@]}"
echo "   Fixed:   ${#FIXED[@]}"
echo "   Changed: ${#CHANGED[@]}"
echo "   Removed: ${#REMOVED[@]}"
