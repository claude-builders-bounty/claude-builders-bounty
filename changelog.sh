#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# generate-changelog — Auto-generate a structured CHANGELOG.md from git history
# Bounty: $50 — https://github.com/claude-builders-bounty/claude-builders-bounty/issues/1
#
# Usage:
#   ./changelog.sh                    # generates CHANGELOG.md
#   ./changelog.sh --stdout           # prints to stdout
#   ./changelog.sh --tag v1.0.0      # use specific tag as base
#   ./changelog.sh --since 2026-01-01 # commits since date
# ═══════════════════════════════════════════════════════════════════════════════
set -euo pipefail

OUTPUT_FILE="${OUTPUT_FILE:-CHANGELOG.md}"
VERBOSE="${VERBOSE:-false}"
BASE_TAG=""
SINCE_DATE=""
WRITE_STDOUT=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --stdout)      WRITE_STDOUT=true; shift ;;
    --tag)         BASE_TAG="$2"; shift 2 ;;
    --since)       SINCE_DATE="$2"; shift 2 ;;
    -v|--verbose)  VERBOSE=true; shift ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

# Determine commit range
if [[ -n "$BASE_TAG" ]]; then
  RANGE="${BASE_TAG}..HEAD"
elif [[ -n "$SINCE_DATE" ]]; then
  RANGE="--since=${SINCE_DATE}"
else
  LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || true)
  if [[ -z "$LAST_TAG" ]]; then
    RANGE=""
    echo "⚠️  No tags found. Using all commits." >&2
  else
    RANGE="${LAST_TAG}..HEAD"
  fi
fi

# Categorise a commit message
categorise() {
  local msg="$1"
  local lower
  lower=$(echo "$msg" | tr '[:upper:]' '[:lower:]')

  if echo "$lower" | grep -qE '(BREAKING[ -]CHANGE|!:)'; then
    echo "breaking"; return
  fi
  if echo "$lower" | grep -qE '^(feat(ure)?|add|new|implement)'; then
    echo "added"; return
  fi
  if echo "$lower" | grep -qE '^(fix|bugfix|hotfix|patch|bug|resolve)'; then
    echo "fixed"; return
  fi
  if echo "$lower" | grep -qE '^(change|refactor|update|migrate|improv|perf|optimize|redesign)'; then
    echo "changed"; return
  fi
  if echo "$lower" | grep -qE '^(remove|delete|deprecate|drop|retire)'; then
    echo "removed"; return
  fi
  if echo "$lower" | grep -qE '^(docs?|document|readme|comment|typo)'; then
    echo "documentation"; return
  fi
  if echo "$lower" | grep -qE '^(security|vuln|cve|audit)'; then
    echo "security"; return
  fi
  if echo "$lower" | grep -qE '^(test|ci|cd|deploy|build|chore|bump|deps?|config|format|style|tool)'; then
    echo "internal"; return
  fi
  echo "changed"
}

# Build section headers
declare -A HEADERS
HEADERS[breaking]="## 💥 Breaking Changes"
HEADERS[added]="## 🚀 Added"
HEADERS[fixed]="## 🐛 Fixed"
HEADERS[changed]="## 🔄 Changed"
HEADERS[removed]="## 🗑️ Removed"
HEADERS[documentation]="## 📚 Documentation"
HEADERS[security]="## 🔒 Security"
HEADERS[internal]="## ⚙️ Internal"

declare -A SECTION_DATA
for key in "${!HEADERS[@]}"; do
  SECTION_DATA[$key]=""
done

# Collect and categorise all commits
TOTAL=0
while IFS= read -r line; do
  [[ -z "$line" ]] && continue
  commit_hash=$(echo "$line" | awk '{print $1}')
  msg=$(echo "$line" | cut -d' ' -f2-)
  cat=$(categorise "$msg")
  SECTION_DATA[$cat]+="- ${msg}  (${commit_hash:0:7})"$'\n'
  TOTAL=$((TOTAL + 1))
done < <(git log --oneline $RANGE 2>/dev/null)

# Get version
VERSION=$(git describe --tags --abbrev=0 2>/dev/null || echo "0.0.0")
DATE=$(date +%Y-%m-%d)

# Output
output() {
  echo "# Changelog"
  echo ""
  echo "## [${VERSION}] — ${DATE}"
  echo ""
  echo "_${TOTAL} changes since last release_"
  echo ""
  for section in breaking added fixed changed removed documentation security internal; do
    local content="${SECTION_DATA[$section]}"
    if [[ -n "$content" ]]; then
      echo "${HEADERS[$section]}"
      echo ""
      echo "$content"
    fi
  done
  echo "---"
  echo "_Auto-generated by [generate-changelog](https://github.com/claude-builders-bounty/claude-builders-bounty)_"
}

if $WRITE_STDOUT; then
  output
else
  output > "$OUTPUT_FILE"
  echo "✅ Changelog written to ${OUTPUT_FILE} (${TOTAL} changes)"
fi
