#!/bin/bash
# CHANGELOG Generator - Claude Builders Bounty #1
# Auto-generates structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--since TAG|DATE]

set -euo pipefail

CHANGELOG_FILE="CHANGELOG.md"
SINCE_REF=""

# Parse args
while [[ $# -gt 0 ]]; do
  case "$1" in
    --since) SINCE_REF="$2"; shift 2 ;;
    --help) echo "Usage: bash changelog.sh [--since TAG|DATE]"; exit 0 ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

# Determine starting point
if [[ -z "$SINCE_REF" ]]; then
  SINCE_REF=$(git describe --tags --abbrev=0 2>/dev/null || git rev-list --max-parents=0 HEAD)
fi

echo "Generating CHANGELOG from $SINCE_REF..."

# Initialize sections
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""

# Get the tag name for the version header
VERSION=$(git describe --tags --abbrev=0 2>/dev/null || echo "v0.1.0")
DATE=$(git log -1 --format=%ai "$SINCE_REF" 2>/dev/null | head -1 | cut -d' ' -f1 || date +%Y-%m-%d)

# Categorize commits
while IFS='|' read -r hash subject; do
  [[ -z "$hash" ]] && continue
  # Skip merge commits
  echo "$subject" | grep -qi "^merge " && continue

  if echo "$subject" | grep -qiE "^feat|^feature|^add|^create|^implement|^new"; then
    ADDED+="  - $subject ($hash)\n"
  elif echo "$subject" | grep -qiE "^fix|^bug|^hotfix|^patch|^correct"; then
    FIXED+="  - $subject ($hash)\n"
  elif echo "$subject" | grep -qiE "^remove|^delete|^drop|^deprecat"; then
    REMOVED+="  - $subject ($hash)\n"
  elif echo "$subject" | grep -qiE "^refactor|^update|^upgrade|^change|^improve|^optimize"; then
    CHANGED+="  - $subject ($hash)\n"
  else
    CHANGED+="  - $subject ($hash)\n"
  fi
done < <(git log --oneline --no-merges "$SINCE_REF..HEAD" 2>/dev/null | sed 's/^\([a-f0-9]\{7,\}\) \(.*\)/\1|\2/')

# Generate CHANGELOG.md
{
  echo "# Changelog"
  echo ""
  echo "## [$VERSION] - $DATE"
  echo ""
  
  if [[ -n "$ADDED" ]]; then
    echo "### Added"
    echo -e "$ADDED"
    echo ""
  fi
  
  if [[ -n "$FIXED" ]]; then
    echo "### Fixed"
    echo -e "$FIXED"
    echo ""
  fi
  
  if [[ -n "$CHANGED" ]]; then
    echo "### Changed"
    echo -e "$CHANGED"
    echo ""
  fi
  
  if [[ -n "$REMOVED" ]]; then
    echo "### Removed"
    echo -e "$REMOVED"
    echo ""
  fi
  
  echo "---"
  echo "_Generated by changelog.sh_"
} > "$CHANGELOG_FILE"

echo "Done! CHANGELOG.md generated with $(echo -e "$ADDED$FIXED$CHANGED$REMOVED" | grep -c '^-' || true) entries."
