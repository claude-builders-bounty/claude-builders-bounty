#!/usr/bin/env bash
# changelog.sh — Generate structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--output CHANGELOG.md] [--since <tag>]

set -eo pipefail

OUTPUT="CHANGELOG.md"
SINCE_TAG=""
REPO_PATH="."
VERBOSE=0

usage() {
    cat <<'EOF'
Usage: bash changelog.sh [OPTIONS]

Generate a structured CHANGELOG.md from git history.
Commits are categorized by Conventional Commits prefixes.

Options:
  --output FILE     Output file (default: CHANGELOG.md)
  --since TAG       Start from a specific tag (default: last tag)
  --repo PATH       Path to the git repository (default: .)
  --verbose         Print extra details during generation
  -h, --help        Show this help message

Examples:
  bash changelog.sh
  bash changelog.sh --output docs/CHANGELOG.md
  bash changelog.sh --since v1.0.0
EOF
    exit 0
}

# --- argument parsing ---
while [[ $# -gt 0 ]]; do
    case "$1" in
        --output) OUTPUT="$2"; shift 2 ;;
        --since)  SINCE_TAG="$2"; shift 2 ;;
        --repo)   REPO_PATH="$2"; shift 2 ;;
        --verbose) VERBOSE=1; shift ;;
        -h|--help) usage ;;
        *) echo "Unknown option: $1"; usage ;;
    esac
done

cd "$REPO_PATH"

if ! git rev-parse --is-inside-work-tree &>/dev/null; then
    echo "ERROR: Not inside a git repository (path: $REPO_PATH)" >&2
    exit 1
fi

# --- determine tag range ---
if [[ -z "$SINCE_TAG" ]]; then
    LATEST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || true)
    if [[ -z "$LATEST_TAG" ]]; then
        SINCE_TAG=""
        echo "[changelog] No tags found — generating from the first commit"
    else
        SINCE_TAG="$LATEST_TAG"
        echo "[changelog] Scanning commits since tag: $SINCE_TAG"
    fi
fi

# --- collect commits ---
if [[ -n "$SINCE_TAG" ]]; then
    RANGE="$SINCE_TAG..HEAD"
else
    RANGE="HEAD"
fi

mapfile -t COMMITS < <(git log "$RANGE" --no-merges --pretty=format:"%h %s" 2>/dev/null || true)

if [[ ${#COMMITS[@]} -eq 0 ]]; then
    echo "[changelog] No new commits since $SINCE_TAG"
    # still write an empty changelog so the file exists
    {
        echo "# Changelog"
        echo ""
        echo "## [Unreleased]"
        echo ""
        echo "No changes since ${SINCE_TAG:-the beginning}."
    } > "$OUTPUT"
    echo "[changelog] Written: $OUTPUT"
    exit 0
fi

# --- categorize commits ---
declare -a ADDED FIXED CHANGED REMOVED OTHER

for line in "${COMMITS[@]}"; do
    hash="${line:0:7}"
    msg="${line:8}"

    if [[ "$msg" =~ ^feat(\(.+\))?[:\ ] ]]; then
        clean=$(sed -E 's/^feat(\(.+\))?[:\ ]*//' <<<"$msg")
        ADDED+=("- ${clean} (${hash})")
    elif [[ "$msg" =~ ^fix(\(.+\))?[:\ ] ]]; then
        clean=$(sed -E 's/^fix(\(.+\))?[:\ ]*//' <<<"$msg")
        FIXED+=("- ${clean} (${hash})")
    elif [[ "$msg" =~ ^(refactor|perf|style)(\(.+\))?[:\ ] ]]; then
        clean=$(sed -E 's/^(refactor|perf|style)(\(.+\))?[:\ ]*//' <<<"$msg")
        CHANGED+=("- ${clean} (${hash})")
    elif [[ "$msg" =~ ^(revert|remove|drop)(\(.+\))?[:\ ] ]]; then
        clean=$(sed -E 's/^(revert|remove|drop)(\(.+\))?[:\ ]*//' <<<"$msg")
        REMOVED+=("- ${clean} (${hash})")
    elif [[ "$msg" =~ ^(build|ci|docs|test|chore)(\(.+\))?[:\ ] ]]; then
        clean=$(sed -E 's/^(build|ci|docs|test|chore)(\(.+\))?[:\ ]*//' <<<"$msg")
        CHANGED+=("- ${clean} (${hash})")
    else
        OTHER+=("- ${msg} (${hash})")
    fi
done

# --- build changelog ---
TAG_NAME="${SINCE_TAG:-unreleased}"
DATE=$(date +%Y-%m-%d)

{
    echo "# Changelog"
    echo ""
    echo "## [${TAG_NAME}] — ${DATE}"
    echo ""

    [[ ${#ADDED[@]} -gt 0 ]] && { echo "### Added"; printf '%s\n' "${ADDED[@]}"; echo ""; }
    [[ ${#FIXED[@]} -gt 0 ]] && { echo "### Fixed"; printf '%s\n' "${FIXED[@]}"; echo ""; }
    [[ ${#CHANGED[@]} -gt 0 ]] && { echo "### Changed"; printf '%s\n' "${CHANGED[@]}"; echo ""; }
    [[ ${#REMOVED[@]} -gt 0 ]] && { echo "### Removed"; printf '%s\n' "${REMOVED[@]}"; echo ""; }
    [[ ${#OTHER[@]} -gt 0 ]] && { echo "### Other"; printf '%s\n' "${OTHER[@]}"; echo ""; }

    echo "---"
    echo "_Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty)_"
} > "$OUTPUT"

total_added=${#ADDED[@]}
total_fixed=${#FIXED[@]}
total_changed=${#CHANGED[@]}
total_removed=${#REMOVED[@]}
total_other=${#OTHER[@]}
echo "[changelog] Done — $((total_added + total_fixed + total_changed + total_removed + total_other)) commits written to $OUTPUT"
