#!/usr/bin/env bash
# changelog.sh — Generate structured CHANGELOG.md from git history
# Usage: bash changelog.sh [since_tag] > CHANGELOG.md
#   Defaults to commits since the most recent git tag.

set -euo pipefail

SINCE="${1:-$(git describe --tags --abbrev=0 2>/dev/null || echo '')}"

if [ -z "$SINCE" ]; then
  echo "# Changelog" 
  echo ""
  echo "## [Unreleased]"
  echo ""
  echo "Initial release."
  exit 0
fi

echo "# Changelog"
echo ""
echo "## [Unreleased]"
echo ""

declare -A CATEGORIES
CATEGORIES=(
  ["feat"]="Added"
  ["fix"]="Fixed"
  ["refactor"]="Changed"
  ["perf"]="Changed"
  ["docs"]="Changed"
  ["chore"]="Changed"
  ["revert"]="Removed"
)

declare -A GROUPS

while IFS= read -r line; do
  # Parse conventional commit: type(scope): message
  if [[ "$line" =~ ^([a-z]+)(\([^)]*\))?!?:\ (.+)$ ]]; then
    type="${BASH_REMATCH[1]}"
    msg="${BASH_REMATCH[3]}"
    category="${CATEGORIES[$type]:-Changed}"
    GROUPS["$category"]+="  - ${msg}"$'\n'
  fi
done < <(git log "${SINCE}..HEAD" --pretty=format:"%s" 2>/dev/null || true)

for category in Added Fixed Changed Removed; do
  if [ -n "${GROUPS[$category]:-}" ]; then
    echo "### $category"
    echo "${GROUPS[$category]}"
  fi
done

echo ""
echo "---"
echo "*Generated by changelog.sh*"
