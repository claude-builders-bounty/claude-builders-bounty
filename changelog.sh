#!/usr/bin/env bash
set -euo pipefail

# changelog.sh — Generate a structured CHANGELOG.md from git history
#
# Usage:
#   bash changelog.sh              # Generate for the current repo (since last tag)
#   bash changelog.sh /path/to/repo  # Generate for a specific repo
#
# Categories:
#   Added      — new features, files, APIs
#   Fixed      — bug fixes, corrections
#   Changed    — modifications, refactors, dependency updates
#   Removed    — deleted features, deprecated removals

REPO_DIR="${1:-.}"
cd "$REPO_DIR"

# Determine the last tag, or fall back to the first commit
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
if [ -z "$LAST_TAG" ]; then
  echo "No tags found — generating from the entire git history."
  LOG_RANGE="HEAD"
  TAG_LABEL="initial commit"
else
  LOG_RANGE="${LAST_TAG}..HEAD"
  TAG_LABEL="$LAST_TAG"
fi

# If there's nothing since the tag, report it
if ! git log "$LOG_RANGE" --oneline 2>/dev/null | grep -q .; then
  echo "No new commits since $TAG_LABEL. Nothing to log."
  exit 0
fi

# ── Build changelog entries ────────────────────────────────────────

declare -A SECTIONS
SECTIONS[Added]=""
SECTIONS[Fixed]=""
SECTIONS[Changed]=""
SECTIONS[Removed]=""

while IFS='|' read -r HASH SUBJECT BODY; do
  # Categorise by conventional-commit prefix
  CATEGORY="Changed"
  LOWER=$(echo "$SUBJECT" | tr '[:upper:]' '[:lower:]')

  if echo "$LOWER" | grep -qE '^(feat|add|create|implement|introduce|new)'; then
    CATEGORY="Added"
  elif echo "$LOWER" | grep -qE '^(fix|patch|correct|hotfix|bug)'; then
    CATEGORY="Fixed"
  elif echo "$LOWER" | grep -qE '^(remove|delete|deprecate|drop|clean)'; then
    CATEGORY="Removed"
  fi

  # Build the short hash link
  SHORT_HASH="${HASH:0:7}"
  ENTRY="- ${SUBJECT} (\`${SHORT_HASH}\`)"

  SECTIONS["$CATEGORY"]+="${ENTRY}"$'\n'
done < <(git log "$LOG_RANGE" --format="%H|%s|%b" --reverse)

# ── Generate CHANGELOG.md ──────────────────────────────────────────
{
  echo "# Changelog"
  echo ""
  echo "_Generated on $(date '+%Y-%m-%d %H:%M:%S') from commits since \`${TAG_LABEL}\`._"
  echo ""

  for CAT in Added Fixed Changed Removed; do
    ENTRIES="${SECTIONS[$CAT]}"
    if [ -n "$ENTRIES" ]; then
      echo "## ${CAT}"
      echo ""
      echo "${ENTRIES}"
    fi
  done

  echo "---"
  echo "_Auto-generated by [changelog.sh](bounties/bounty-1-changelog/changelog.sh)_"
} > CHANGELOG.md

echo "✓ Generated CHANGELOG.md ($(grep -cE '^## ' CHANGELOG.md) sections)"
