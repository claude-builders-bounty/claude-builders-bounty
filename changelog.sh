#!/bin/bash

# changelog.sh - Generate a structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--output CHANGELOG.md] [--since <tag>]

set -euo pipefail

# Default values
OUTPUT_FILE="CHANGELOG.md"
SINCE_TAG=""

# Parse arguments
while [[ $# -gt 0 ]]; do
    case "$1" in
        --output|-o)
            OUTPUT_FILE="$2"
            shift 2
            ;;
        --since|-s)
            SINCE_TAG="$2"
            shift 2
            ;;
        --help|-h)
            echo "Usage: $0 [--output CHANGELOG.md] [--since <tag>]"
            echo ""
            echo "Options:"
            echo "  --output, -o   Output file (default: CHANGELOG.md)"
            echo "  --since, -s    Git tag to start from (default: last tag)"
            echo "  --help, -h     Show this help message"
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            echo "Use --help for usage information."
            exit 1
            ;;
    esac
done

# Check if we're in a git repository
if ! git rev-parse --git-dir > /dev/null 2>&1; then
    echo "Error: Not in a git repository."
    exit 1
fi

# Determine the starting point for changelog
if [[ -z "$SINCE_TAG" ]]; then
    # Get the last tag, if any
    LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
    if [[ -z "$LAST_TAG" ]]; then
        echo "No tags found. Generating changelog from the beginning of history."
        SINCE_REF=""
    else
        SINCE_REF="$LAST_TAG"
        echo "Using last tag: $LAST_TAG"
    fi
else
    SINCE_REF="$SINCE_TAG"
    echo "Using specified tag: $SINCE_TAG"
fi

# Get current date
CURRENT_DATE=$(date +"%Y-%m-%d")

# Get current version (use last tag or "0.0.0")
if [[ -n "$SINCE_REF" ]]; then
    CURRENT_VERSION="$SINCE_REF"
else
    CURRENT_VERSION="0.0.0"
fi

# Fetch commits
if [[ -n "$SINCE_REF" ]]; then
    COMMITS=$(git log "$SINCE_REF"..HEAD --oneline --no-merges 2>/dev/null || git log --oneline --no-merges)
else
    COMMITS=$(git log --oneline --no-merges)
fi

if [[ -z "$COMMITS" ]]; then
    echo "No commits found since $SINCE_REF."
    exit 0
fi

# Initialize category arrays
declare -a ADDED=()
declare -a FIXED=()
declare -a CHANGED=()
declare -a REMOVED=()

# Categorize commits based on conventional commit prefixes
while IFS= read -r line; do
    # Extract commit hash and message
    HASH=$(echo "$line" | awk '{print $1}')
    MESSAGE=$(echo "$line" | cut -d' ' -f2-)

    # Normalize to lowercase for matching
    LOWERCASE_MSG=$(echo "$MESSAGE" | tr '[:upper:]' '[:lower:]')

    # Categorize based on conventional commit types
    if echo "$LOWERCASE_MSG" | grep -qE '^(feat|feature|add|new):'; then
        ADDED+=("$MESSAGE")
    elif echo "$LOWERCASE_MSG" | grep -qE '^(fix|bugfix|bug|hotfix):'; then
        FIXED+=("$MESSAGE")
    elif echo "$LOWERCASE_MSG" | grep -qE '^(change|update|refactor|perf|improve|style):'; then
        CHANGED+=("$MESSAGE")
    elif echo "$LOWERCASE_MSG" | grep -qE '^(remove|delete|deprecate):'; then
        REMOVED+=("$MESSAGE")
    else
        # Default to Changed if no prefix matches
        CHANGED+=("$MESSAGE")
    fi
done <<< "$COMMITS"

# Generate CHANGELOG.md content
cat > "$OUTPUT_FILE" << EOF
# Changelog

All notable changes to this project will be documented in this file.

## [$CURRENT_VERSION] - $CURRENT_DATE

EOF

# Helper function to write a section
write_section() {
    local title="$1"
    local icon="$2"
    shift 2
    local items=("$@")

    if [[ ${#items[@]} -gt 0 ]]; then
        echo "### $icon $title" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"
        for item in "${items[@]}"; do
            echo "- $item" >> "$OUTPUT_FILE"
        done
        echo "" >> "$OUTPUT_FILE"
    fi
}

# Write sections
write_section "Added" "✨" "${ADDED[@]}"
write_section "Fixed" "🐛" "${FIXED[@]}"
write_section "Changed" "🔄" "${CHANGED[@]}"
write_section "Removed" "🗑️" "${REMOVED[@]}"

# Add footer
cat >> "$OUTPUT_FILE" << EOF
---
*This changelog was automatically generated by [changelog.sh](changelog.sh).*
EOF

echo "✅ CHANGELOG generated successfully: $OUTPUT_FILE"