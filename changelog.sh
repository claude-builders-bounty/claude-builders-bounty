#!/usr/bin/env bash
# changelog.sh — Generate structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--output FILE] [--since TAG]
set -euo pipefail

OUTPUT="${2:-CHANGELOG.md}"
SINCE_TAG=""

# Parse args
while [[ $# -gt 0 ]]; do
  case "$1" in
    --output) OUTPUT="$2"; shift 2 ;;
    --since)  SINCE_TAG="$2"; shift 2 ;;
    --help|-h) echo "Usage: bash changelog.sh [--output FILE] [--since TAG]"; exit 0 ;;
    *) echo "Unknown option: $1"; exit 1 ;;
  esac
done

# Determine commit range
RANGE=""
if [ -n "$SINCE_TAG" ]; then
  RANGE="${SINCE_TAG}..HEAD"
else
  LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || true)
  if [ -n "$LAST_TAG" ]; then
    RANGE="${LAST_TAG}..HEAD"
  else
    RANGE="HEAD"
  fi
fi

echo "📋 Generating changelog from: git log ${RANGE}" >&2

# Gather commit data
COMMITS=$(git log --no-merges --format="%H|%s|%an|%aI" "${RANGE}" 2>/dev/null || true)

if [ -z "$COMMITS" ]; then
  echo "No commits found in range: ${RANGE}" >&2
  echo "# Changelog" > "$OUTPUT"
  echo "" >> "$OUTPUT"
  echo "No changes." >> "$OUTPUT"
  exit 0
fi

# Categorize commits
ADDED=""; FIXED=""; CHANGED=""; REMOVED=""; OTHER=""

while IFS='|' read -r hash subject author date; do
  [ -z "$hash" ] && continue
  SHORT_HASH="${hash:0:7}"
  SUBJECT_LOWER="$(echo "$subject" | tr '[:upper:]' '[:lower:]')"

  LINE="- ${subject} (${SHORT_HASH}, ${author})"

  if echo "$SUBJECT_LOWER" | grep -qE '^(feat|add|create|implement|introduce|new)\b'; then
    ADDED="${ADDED}${LINE}\n"
  elif echo "$SUBJECT_LOWER" | grep -qE '^(fix|bug|patch|correct|resolve|hotfix)\b'; then
    FIXED="${FIXED}${LINE}\n"
  elif echo "$SUBJECT_LOWER" | grep -qE '^(refactor|update|bump|upgrade|migrate|improve|change|revise)\b'; then
    CHANGED="${CHANGED}${LINE}\n"
  elif echo "$SUBJECT_LOWER" | grep -qE '^(remove|delete|drop|deprecate|cleanup)\b'; then
    REMOVED="${REMOVED}${LINE}\n"
  else
    OTHER="${OTHER}${LINE}\n"
  fi
done <<< "$COMMITS"

# Write CHANGELOG.md
{
  echo "# Changelog"
  echo ""

  CURRENT_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "unreleased")
  CURRENT_DATE=$(date +%Y-%m-%d)
  echo "## [${CURRENT_TAG}] — ${CURRENT_DATE}"
  echo ""

  if [ -n "$ADDED" ]; then
    echo "### Added"
    echo -e "$ADDED" | while IFS= read -r line; do [ -n "$line" ] && echo "$line"; done
    echo ""
  fi

  if [ -n "$FIXED" ]; then
    echo "### Fixed"
    echo -e "$FIXED" | while IFS= read -r line; do [ -n "$line" ] && echo "$line"; done
    echo ""
  fi

  if [ -n "$CHANGED" ]; then
    echo "### Changed"
    echo -e "$CHANGED" | while IFS= read -r line; do [ -n "$line" ] && echo "$line"; done
    echo ""
  fi

  if [ -n "$REMOVED" ]; then
    echo "### Removed"
    echo -e "$REMOVED" | while IFS= read -r line; do [ -n "$line" ] && echo "$line"; done
    echo ""
  fi

  if [ -n "$OTHER" ]; then
    echo "### Other"
    echo -e "$OTHER" | while IFS= read -r line; do [ -n "$line" ] && echo "$line"; done
    echo ""
  fi

  echo "---"
  echo "_Generated by changelog.sh_"
} > "$OUTPUT"

echo "✅ Changelog written to: ${OUTPUT}" >&2
echo "   $(grep -c '^- ' "$OUTPUT" || true) commits categorized" >&2
