#!/usr/bin/env bash
set -euo pipefail

# generate-changelog.sh
# Auto-generates a structured CHANGELOG.md from git history since the last tag.
# Categorizes: Added / Fixed / Changed / Removed / Other

REPO_URL=$(git remote get-url origin 2>/dev/null || echo "")
LATEST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")

if [ -z "$LATEST_TAG" ]; then
  echo "No tags found — using all commits."
  COMMIT_RANGE=""
else
  echo "Generating changelog since tag: $LATEST_TAG"
  COMMIT_RANGE="${LATEST_TAG}..HEAD"
fi

TMPDIR=$(mktemp -d)
trap "rm -rf $TMPDIR" EXIT

for cat in Added Fixed Changed Removed Other; do
  touch "$TMPDIR/$cat"
done

categorize() {
  local s="$1"
  local lower=$(echo "$s" | tr '[:upper:]' '[:lower:]')
  if echo "$lower" | grep -qE '^(feat|add|new|introduce|implement|create|build)'; then
    echo "Added"
  elif echo "$lower" | grep -qE '^(fix|bugfix|hotfix|patch|resolve|closes?)'; then
    echo "Fixed"
  elif echo "$lower" | grep -qE '^(change|update|refactor|perf|improve|enhance|modify|upgrade|optimize)'; then
    echo "Changed"
  elif echo "$lower" | grep -qE '^(remove|delete|drop|deprecate|revert|clean)'; then
    echo "Removed"
  else
    echo "Other"
  fi
}

# Read commits — skip empty subjects
git log $COMMIT_RANGE --pretty=format:"%s" | while read -r subject; do
  [ -z "$subject" ] && continue
  cat=$(categorize "$subject")
  # Append PR reference if present
  if echo "$subject" | grep -qE '#[0-9]+'; then
    pr=$(echo "$subject" | grep -oE '#[0-9]+')
    echo "- ${subject} (${pr})" >> "$TMPDIR/$cat"
  else
    echo "- ${subject}" >> "$TMPDIR/$cat"
  fi
done

OUT="CHANGELOG.md"
{
  echo "# Changelog"
  echo ""
  if [ -n "$LATEST_TAG" ] && [ -n "$REPO_URL" ]; then
    echo "All notable changes since [$LATEST_TAG](${REPO_URL}/releases/tag/${LATEST_TAG})."
  elif [ -n "$LATEST_TAG" ]; then
    echo "All notable changes since $LATEST_TAG."
  else
    echo "All notable changes."
  fi
  echo ""
  echo "## [Unreleased]"
  echo ""

  for cat in Added Fixed Changed Removed Other; do
    if [ -s "$TMPDIR/$cat" ]; then
      echo "### $cat"
      cat "$TMPDIR/$cat"
      echo ""
    fi
  done

  echo "---"
  echo "Generated by generate-changelog.sh on $(date -u +%Y-%m-%d)."
} > "$OUT"

count=$(grep -c '^-' "$OUT" || true)
echo "Changelog generated: $count entries."
