#!/usr/bin/env bash
# changelog.sh — Generate a structured CHANGELOG.md from git history
# Usage: bash changelog.sh [--since <tag>] [--output <file>]
set -eo pipefail

OUTPUT="${OUTPUT:-CHANGELOG.md}"
SINCE_TAG=""
REPO_DIR="."

usage() {
  cat <<EOF
Usage: bash changelog.sh [OPTIONS]

Generate a structured CHANGELOG.md from conventional commits since the last git tag.

Options:
  --since <tag>   Start from a specific tag (default: latest tag, or first commit)
  --output <file> Write to a custom file (default: CHANGELOG.md)
  --repo <path>   Path to the git repository (default: current directory)
  -h, --help      Show this help

Categories auto-detected from conventional commit prefixes:
  feat → Added
  fix  → Fixed
  refactor, perf, style → Changed
  revert → Removed
  Everything else → Changed
EOF
  exit 0
}

# Parse arguments
while [[ $# -gt 0 ]]; do
  case "$1" in
    --since)  SINCE_TAG="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    --repo)   REPO_DIR="$2"; shift 2 ;;
    -h|--help) usage ;;
    *) echo "Unknown option: $1"; usage ;;
  esac
done

cd "$REPO_DIR"

# Determine start point
if [[ -n "$SINCE_TAG" ]]; then
  START="$SINCE_TAG"
elif latest_tag=$(git describe --tags --abbrev=0 2>/dev/null); then
  START="$latest_tag"
else
  # No tags at all — use the first commit
  START=$(git rev-list --max-parents=0 HEAD)
fi

TAG_DATE=$(git log -1 --format='%ad' --date=short "$START" 2>/dev/null || echo "unknown")
TODAY=$(date +%Y-%m-%d)

# Get version string
if git describe --tags --abbrev=0 &>/dev/null; then
  VERSION=$(git describe --tags --abbrev=0 2>/dev/null)
else
  VERSION="unreleased"
fi

# Collect commits since START (exclusive of START itself)
COMMITS=$(git log "${START}..HEAD" --pretty=format:'%s' 2>/dev/null || true)

if [[ -z "$COMMITS" ]]; then
  echo "No commits found since $START. Nothing to generate."
  exit 0
fi

# Categorize commits
declare -a ADDED FIXED CHANGED REMOVED

while IFS= read -r line; do
  [[ -z "$line" ]] && continue

  # Strip merge commit prefixes
  clean=$(echo "$line" | sed 's/^Merge .*//' | sed 's/^Revert "//;s/"$//')
  [[ -z "$clean" ]] && continue

  # Detect category from conventional commit prefix
  prefix=$(echo "$clean" | grep -oP '^[a-z]+(?=[(:])' 2>/dev/null || echo "")

  case "$prefix" in
    feat)
      msg=$(echo "$clean" | sed 's/^feat[(][^)]*[)]:[[:space:]]*//;s/^feat:[[:space:]]*//')
      ADDED+=("- $msg") ;;
    fix)
      msg=$(echo "$clean" | sed 's/^fix[(][^)]*[)]:[[:space:]]*//;s/^fix:[[:space:]]*//')
      FIXED+=("- $msg") ;;
    revert)
      msg=$(echo "$clean" | sed 's/^revert[(][^)]*[)]:[[:space:]]*//;s/^revert:[[:space:]]*//')
      REMOVED+=("- $msg") ;;
    *)
      CHANGED+=("- $clean") ;;
  esac
done <<< "$COMMITS"

# Build CHANGELOG
{
  echo "# Changelog"
  echo ""
  echo "## [$VERSION] — $TODAY"
  echo ""

  if [[ ${#ADDED[@]} -gt 0 ]]; then
    echo "### Added"
    printf '%s\n' "${ADDED[@]}"
    echo ""
  fi

  if [[ ${#FIXED[@]} -gt 0 ]]; then
    echo "### Fixed"
    printf '%s\n' "${FIXED[@]}"
    echo ""
  fi

  if [[ ${#CHANGED[@]} -gt 0 ]]; then
    echo "### Changed"
    printf '%s\n' "${CHANGED[@]}"
    echo ""
  fi

  if [[ ${#REMOVED[@]} -gt 0 ]]; then
    echo "### Removed"
    printf '%s\n' "${REMOVED[@]}"
    echo ""
  fi

  echo "---"
  echo "*Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty)*"
} > "$OUTPUT"

echo "✅ CHANGELOG written to $OUTPUT"
echo "   $(wc -l < "$OUTPUT") lines, $(grep -c '^- ' "$OUTPUT" || echo 0) entries"
