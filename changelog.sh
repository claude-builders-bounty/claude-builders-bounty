#!/usr/bin/env bash
# changelog.sh - Generate structured CHANGELOG.md from git history
# Usage: ./changelog.sh [--since TAG] [--output FILE]

set -euo pipefail

SINCE_TAG=""
OUTPUT_FILE="CHANGELOG.md"

while [[ $# -gt 0 ]]; do
    case $1 in
        --since)
            SINCE_TAG="$2"
            shift 2
            ;;
        --output)
            OUTPUT_FILE="$2"
            shift 2
            ;;
        *)
            echo "Unknown option: $1"
            exit 1
            ;;
    esac
done

# Get the last tag if not specified
if [[ -z "$SINCE_TAG" ]]; then
    SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
fi

# Build git log command
if [[ -n "$SINCE_TAG" ]]; then
    GIT_RANGE="${SINCE_TAG}..HEAD"
else
    GIT_RANGE="HEAD"
fi

# Fetch commits with conventional commit format
# Format: <type>(<scope>): <subject>
commits=$(git log --pretty=format:"%s|%b|%h" $GIT_RANGE --reverse 2>/dev/null || echo "")

# Categorize commits
declare -A categories
categories["Added"]=""
categories["Fixed"]=""
categories["Changed"]=""
categories["Removed"]=""
categories["Other"]=""

while IFS='|' read -r subject body hash; do
    [[ -z "$subject" ]] && continue
    
    # Parse conventional commit type
    if [[ "$subject" =~ ^(feat|feature|add)(\(.+\))?: ]]; then
        category="Added"
    elif [[ "$subject" =~ ^(fix|bugfix|hotfix)(\(.+\))?: ]]; then
        category="Fixed"
    elif [[ "$subject" =~ ^(change|chore|refactor|style|perf|improve)(\(.+\))?: ]]; then
        category="Changed"
    elif [[ "$subject" =~ ^(remove|delete|drop)(\(.+\))?: ]]; then
        category="Removed"
    elif [[ "$subject" =~ ^(docs|doc|test|ci|build|revert)(\(.+\))?: ]]; then
        category="Other"
    else
        # Try to infer from keywords
        lower_subject="${subject,,}"
        if [[ "$lower_subject" =~ (add|new|implement|create|introduce) ]]; then
            category="Added"
        elif [[ "$lower_subject" =~ (fix|resolve|repair|patch|hotfix) ]]; then
            category="Fixed"
        elif [[ "$lower_subject" =~ (change|update|modify|refactor|improve|optimize) ]]; then
            category="Changed"
        elif [[ "$lower_subject" =~ (remove|delete|drop|deprecat) ]]; then
            category="Removed"
        else
            category="Other"
        fi
    fi
    
    # Clean subject for display
    clean_subject=$(echo "$subject" | sed -E 's/^[a-z]+(\(.+\))?://' | sed 's/^ *//')
    categories["$category"]+="- $clean_subject ($hash)"$'\n'
done <<< "$commits"

# Generate CHANGELOG.md
{
    echo "# Changelog"
    echo ""
    echo "All notable changes to this project will be documented in this file."
    echo ""
    echo "The format is based on [Keep a Changelog](https://keepachangelog.com/en/1.0.0/),"
    echo "and this project adheres to [Semantic Versioning](https://semver.org/spec/v2.0.0.html)."
    echo ""
    
    date_str=$(date -u +"%Y-%m-%d")
    if [[ -n "$SINCE_TAG" ]]; then
        echo "## [Unreleased] - $date_str"
    else
        echo "## [Initial] - $date_str"
    fi
    echo ""
    
    for cat in "Added" "Fixed" "Changed" "Removed" "Other"; do
        if [[ -n "${categories[$cat]}" ]]; then
            echo "### $cat"
            echo -n "${categories[$cat]}"
            echo ""
        fi
    done
    
    echo ""
    echo "---"
    echo "*Generated by changelog.sh on $(date -u +"%Y-%m-%d %H:%M:%S UTC")*"
} > "$OUTPUT_FILE"

echo "Changelog generated: $OUTPUT_FILE"
echo "Preview:"
head -50 "$OUTPUT_FILE"
