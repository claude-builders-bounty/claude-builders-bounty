#!/usr/bin/env bash
# changelog.sh — generate a structured CHANGELOG.md from git history.
# Usage: bash changelog.sh [--all] [--stdout]
#   (default)  changes since the most recent git tag (unreleased section)
#   --all      regenerate sections for every tag
#   --stdout   print instead of writing CHANGELOG.md
set -euo pipefail

MODE="unreleased"
OUTPUT="CHANGELOG.md"
for arg in "$@"; do
  case "$arg" in
    --all) MODE="all" ;;
    --stdout) OUTPUT="/dev/stdout" ;;
    *) echo "unknown arg: $arg" >&2; exit 64 ;;
  esac
done

# Security: values come from git itself; force them through a sanitizer before
# they reach eval-free string assembly. Also guard against option injection.
sanitize() { printf '%s' "$1" | tr -d '\r\n' | sed 's/[{}()\[\]<>|`$&;!#~^"'"'"']//g' | head -c 200; }

categorize() {
  # $1 = subject. echoes category name.
  local s lc
  s="$1"; lc="$(printf '%s' "$s" | tr 'A-Z' 'a-z')"
  case "$lc" in
    feat\:*|feature\:*|feat\(*)           echo "Added" ;;
    add*|new\ *|implement*|introduc*)     echo "Added" ;;
    fix\:*|fix\(*|fixup*|bugfix*|patch\:*|hotfix\(*)  echo "Fixed" ;;
    fix\ *|resolve*|correct*|revert*)     echo "Fixed" ;;
    remove*|drop*|delete*|deprecat*)      echo "Removed" ;;
    *)                                    echo "Changed" ;;
  esac
}

emit_section() {
  # $1 = heading, $2 = range spec for git log (e.g. "v1.0.0..HEAD" or a tag)
  local heading range line subj hash cat
  heading="$1"; range="$2"
  declare -A buckets=( [Added]="" [Fixed]="" [Changed]="" [Removed]="" )
  while IFS= read -r line; do
    hash="${line%% *}"
    subj="$(sanitize "${line#* }")"
    [ -z "$subj" ] && continue
    # skip merge noise and release bookkeeping
    case "$(printf '%s' "$subj" | tr 'A-Z' 'a-z')" in
      merge\ *|changelog*|bump\ version*|release\ v*) continue ;;
    esac
    cat="$(categorize "$subj")"
    buckets[$cat]+="- ${subj} (${hash})"$'\n'
  done < <(git log --no-merges --pretty=format:'%h %s' ${range:+$range} ; echo)
  printf '## %s\n\n' "$heading"
  local any=0 k
  for k in Added Fixed Changed Removed; do
    if [ -n "${buckets[$k]}" ]; then
      printf '### %s\n\n%s\n' "$k" "${buckets[$k]}"
      any=1
    fi
  done
  [ "$any" -eq 0 ] && printf '_No notable changes._\n\n'
  unset buckets
}

{
  printf '# Changelog\n\n'
  printf '_Auto-generated by changelog.sh from git history._\n\n'
  if [ "$MODE" = "unreleased" ]; then
    last_tag="$(git tag --sort=-creatordate 2>/dev/null | head -n1 || true)"
    if [ -n "$last_tag" ]; then
      emit_section "Unreleased (since ${last_tag})" "${last_tag}..HEAD"
    else
      emit_section "Unreleased" ""
    fi
  else
    mapfile -t tags < <(git tag --sort=creatordate)
    prev=""
    for t in "${tags[@]:-}"; do
      [ -z "$t" ] && continue
      date="$(git log -1 --pretty=format:'%cs' "$t" 2>/dev/null || echo '')"
      if [ -z "$prev" ]; then
        emit_section "${t} — ${date}" "${t}"
      else
        emit_section "${t} — ${date}" "${prev}..${t}"
      fi
      prev="$t"
    done
    if [ -n "$prev" ]; then
      emit_section "Unreleased" "${prev}..HEAD"
    elif [ "${#tags[@]}" -eq 0 ]; then
      emit_section "Unreleased" ""
    fi
  fi
} > "$OUTPUT"

[ "$OUTPUT" != "/dev/stdout" ] && echo "Wrote $OUTPUT" >&2
