'use strict';

const { spawn } = require('child_process');

function buildPrompt(prData) {
  const diffTruncated = prData.diff.length > 50000
    ? prData.diff.slice(0, 50000) + '\n\n[... diff truncated at 50000 chars ...]'
    : prData.diff;

  return `You are a senior code reviewer. Analyze the following pull request and provide a structured review.

## PR Information
- **Title:** ${prData.title}
- **Author:** ${prData.author}
- **Branch:** ${prData.head} → ${prData.base}
- **Files changed:** ${prData.filesChanged}
- **Lines:** +${prData.additions} / -${prData.deletions}

## PR Description
${prData.body || '(no description provided)'}

## Diff
\`\`\`diff
${diffTruncated}
\`\`\`

## Instructions
Provide your review in EXACTLY this Markdown format (no deviations):

## Summary
(2-3 sentences summarizing what this PR does and its purpose)

## Risks
(Bulleted list of potential risks, bugs, or concerns. If none, write "- None identified")

## Suggestions
(Bulleted list of improvement suggestions. If none, write "- No suggestions")

## Confidence
(Exactly one of: **Low** / **Medium** / **High** — how confident you are in the review given the context available)

Do not include any text outside of these four sections.`;
}

function reviewWithClaude(prompt) {
  return new Promise((resolve, reject) => {
    const proc = spawn('claude', ['-p', '--output-format', 'text'], {
      stdio: ['pipe', 'pipe', 'pipe'],
    });

    let stdout = '';
    let stderr = '';

    proc.stdout.on('data', (data) => { stdout += data.toString(); });
    proc.stderr.on('data', (data) => { stderr += data.toString(); });

    proc.on('close', (code) => {
      if (code !== 0) {
        reject(new Error(`Claude CLI exited with code ${code}: ${stderr}`));
      } else {
        resolve(stdout.trim());
      }
    });

    proc.on('error', (err) => {
      reject(new Error(`Failed to spawn Claude CLI: ${err.message}. Is 'claude' installed and in PATH?`));
    });

    proc.stdin.write(prompt);
    proc.stdin.end();
  });
}

function formatReviewComment(review, prData) {
  return `# 🤖 Claude Code Review

> Automated review of PR #${prData.number || ''} — *${prData.title}*

${review}

---
*Generated by [claude-review](https://github.com/claude-builders-bounty/claude-review) · Claude Code Sub-Agent*`;
}

function validateReview(review) {
  const requiredSections = ['## Summary', '## Risks', '## Suggestions', '## Confidence'];
  const missing = requiredSections.filter(s => !review.includes(s));
  if (missing.length > 0) {
    return { valid: false, missing };
  }
  return { valid: true, missing: [] };
}

module.exports = { buildPrompt, reviewWithClaude, formatReviewComment, validateReview };
