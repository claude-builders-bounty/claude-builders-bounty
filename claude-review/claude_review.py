#!/usr/bin/env python3
"""claude-review — AI pull-request reviewer.

Fetches a GitHub PR diff and returns a structured Markdown review with four
sections: Summary, Risks, Suggestions, and a Confidence score (Low/Medium/High),
using the Claude API (model claude-sonnet-4-20250514).

Usage:
    claude-review --pr https://github.com/owner/repo/pull/123
    claude-review --diff-file path/to/change.diff          # review a local diff
    claude-review --pr <url> --output review.md

Auth:
    ANTHROPIC_API_KEY   required to call Claude (unless --stub-file is given)
    GITHUB_TOKEN        optional; raises rate limits / enables private PR diffs

Offline/testing:
    --stub-file FILE    use FILE's contents as the model output (no API call)
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request

MODEL = "claude-sonnet-4-20250514"
_PR_RE = re.compile(r"github\.com/([^/]+)/([^/]+)/pull/(\d+)")
_SECTIONS = ("Summary", "Risks", "Suggestions", "Confidence")
_CONFIDENCE = ("Low", "Medium", "High")

_PROMPT = (
    "You are a senior code reviewer. Review the following pull-request diff and reply "
    "with GitHub-flavored Markdown ONLY, using EXACTLY these four second-level headings "
    "in this order:\n"
    "## Summary\n(2-3 sentences describing what the PR changes)\n"
    "## Risks\n(a bullet list of concrete risks or bugs; write '- None identified' if none)\n"
    "## Suggestions\n(a bullet list of specific improvements; write '- None' if none)\n"
    "## Confidence\n(exactly one word: Low, Medium, or High)\n\n"
    "Do not add any other headings or preamble.\n\nDIFF:\n")


def parse_pr(url: str) -> tuple[str, str, str]:
    m = _PR_RE.search(url or "")
    if not m:
        raise SystemExit(f"error: not a GitHub PR URL: {url!r}")
    return m.group(1), m.group(2), m.group(3)


def fetch_diff(owner: str, repo: str, number: str) -> str:
    req = urllib.request.Request(
        f"https://api.github.com/repos/{owner}/{repo}/pulls/{number}",
        headers={"Accept": "application/vnd.github.v3.diff", "User-Agent": "claude-review/1.0"})
    token = (os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN") or "").strip()
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as exc:
        raise SystemExit(f"error: GitHub returned {exc.code} for the PR diff")


def call_claude(diff: str, api_key: str) -> str:
    payload = {"model": MODEL, "max_tokens": 1500,
               "messages": [{"role": "user", "content": _PROMPT + diff[:120000]}]}
    req = urllib.request.Request(
        "https://api.anthropic.com/v1/messages", method="POST",
        data=json.dumps(payload).encode("utf-8"),
        headers={"x-api-key": api_key, "anthropic-version": "2023-06-01",
                 "content-type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=90) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        raise SystemExit(f"error: Claude API returned {exc.code}")
    return "".join(block.get("text", "") for block in data.get("content", []) if block.get("type") == "text")


def _extract(raw: str, name: str) -> str:
    m = re.search(rf"^##\s+{name}\s*\n(.*?)(?=^##\s+|\Z)", raw, re.S | re.M | re.I)
    return m.group(1).strip() if m else ""


def format_review(raw: str, pr_ref: str) -> str:
    body = {name: _extract(raw, name) for name in _SECTIONS}
    conf = "Medium"
    for level in _CONFIDENCE:
        if re.search(rf"\b{level}\b", body["Confidence"], re.I):
            conf = level
            break
    out = [f"## PR Review - {pr_ref}", "",
           "## Summary", body["Summary"] or "_No summary produced._", "",
           "## Risks", body["Risks"] or "- None identified", "",
           "## Suggestions", body["Suggestions"] or "- None", "",
           "## Confidence", conf, "",
           "_Generated by `claude-review` (model: " + MODEL + ")._"]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="claude-review", description="AI PR reviewer (Claude)")
    ap.add_argument("--pr", help="GitHub PR URL")
    ap.add_argument("--diff-file", help="review a local unified-diff file instead of fetching")
    ap.add_argument("--stub-file", help="use this file's contents as the model output (offline/testing)")
    ap.add_argument("--output", help="write the review to this path (default: stdout)")
    args = ap.parse_args(argv)

    if args.diff_file:
        with open(args.diff_file, encoding="utf-8") as fh:
            diff = fh.read()
        pr_ref = args.pr or os.path.basename(args.diff_file)
    elif args.pr:
        owner, repo, number = parse_pr(args.pr)
        diff = fetch_diff(owner, repo, number)
        pr_ref = f"{owner}/{repo}#{number}"
    else:
        ap.error("provide --pr URL or --diff-file")

    if args.stub_file:
        with open(args.stub_file, encoding="utf-8") as fh:
            raw = fh.read()
    else:
        api_key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
        if not api_key:
            raise SystemExit("error: set ANTHROPIC_API_KEY (or pass --stub-file for offline use)")
        raw = call_claude(diff, api_key)

    review = format_review(raw, pr_ref)
    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(review)
        print(f"review written to {args.output}")
    else:
        sys.stdout.write(review)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
