#!/usr/bin/env python3
"""
Bounty #4: Claude Code Sub-agent for PR Reviews
A script that helps automate PR reviews using Claude Code.

This tool can be used as a GitHub Action or standalone script
to fetch PRs, run code analysis, and generate review comments.
"""

import json
import sys
import os
import subprocess
import github  # PyGithub library


def get_pr_info(github_token, pr_number, repo_name):
    """Fetch PR information from GitHub."""
    try:
        from github import Github
        
        gh = Github(github_token)
        repo = gh.get_repo(repo_name)
        pr = repo.get_pull(pr_number)
        
        return {
            "number": pr.number,
            "title": pr.title,
            "body": pr.body or "",
            "user": pr.user.login,
            "head_sha": pr.head.sha,
            "base_sha": pr.base.sha,
            "files": [f.filename for f in pr.get_files()],
            "changed_files": pr.get_files(),
        }
    except ImportError:
        print("PyGithub not installed. Install with: pip install PyGithub")
        return None
    except Exception as e:
        print(f"Error fetching PR: {e}", file=sys.stderr)
        return None


def analyze_code_changes(repo_name, github_token, pr_number):
    """Analyze PR code changes for common issues."""
    try:
        # Fetch changed files
        result = subprocess.run(
            ["gh", "pr", "view", str(pr_number),
             "--repo", repo_name,
             "--json", "changedFiles,files"],
            capture_output=True,
            text=True,
        )
        
        if result.returncode != 0:
            # Fallback: use git commands
            return analyze_with_git(repo_name, pr_number)
        
        return json.loads(result.stdout)
    except FileNotFoundError:
        # gh CLI not available, use git
        return analyze_with_git(repo_name, pr_number)


def analyze_with_git(repo_name, pr_number):
    """Analyze PR changes using git commands."""
    try:
        # Get changed files
        result = subprocess.run(
            ["git", "diff", "--name-only", "HEAD~1..HEAD"],
            capture_output=True,
            text=True,
            cwd=f"/tmp/{repo_name}" if os.path.exists(f"/tmp/{repo_name}") else ".",
        )
        
        files = [f.strip() for f in result.stdout.strip().split("\n") if f.strip()]
        
        analysis = {
            "changed_files": files,
            "issues": [],
        }
        
        # Check for common issues in changed files
        for filepath in files:
            if filepath.endswith(".py"):
                # Check for TODO comments
                result = subprocess.run(
                    ["git", "diff", "HEAD~1..HEAD", "--", filepath],
                    capture_output=True,
                    text=True,
                )
                if "TODO" in result.stdout:
                    analysis["issues"].append(
                        f"TODO comment found in {filepath}"
                    )
                # Check for print statements
                if "print(" in result.stdout:
                    analysis["issues"].append(
                        f"Debug print statement in {filepath}"
                    )
            elif filepath.endswith(".js") or filepath.endswith(".ts"):
                # Check for console.log
                result = subprocess.run(
                    ["git", "diff", "HEAD~1..HEAD", "--", filepath],
                    capture_output=True,
                    text=True,
                )
                if "console.log" in result.stdout:
                    analysis["issues"].append(
                        f"console.log found in {filepath}"
                    )
        
        return analysis
    except Exception as e:
        print(f"Git analysis error: {e}", file=sys.stderr)
        return {"changed_files": [], "issues": []}


def generate_review_comment(pr_analysis):
    """Generate a PR review comment based on analysis."""
    lines = []
    lines.append("### PR Review Summary")
    lines.append("")
    
    changed_files = pr_analysis.get("changed_files", [])
    issues = pr_analysis.get("issues", [])
    
    if changed_files:
        lines.append(f"**Changed files:** {len(changed_files)}")
        lines.append("- " + "\n- ".join(changed_files[:10]))
        if len(changed_files) > 10:
            lines.append(f"- ... and {len(changed_files) - 10} more")
        lines.append("")
    
    if issues:
        lines.append(f"**Found {len(issues)} issues:**")
        for issue in issues:
            lines.append(f"- {issue}")
        lines.append("")
    else:
        lines.append("No issues found in the code changes.")
        lines.append("")
    
    lines.append("---\n*Generated by Claude Code PR Review Bot*")
    
    return "\n".join(lines)


def main():
    """Main entry point."""
    # Get configuration from environment
    github_token = os.environ.get("GITHUB_TOKEN", "")
    pr_number = os.environ.get("PR_NUMBER", "0")
    repo_name = os.environ.get("REPO_NAME", "")
    
    if not all([github_token, repo_name]):
        print("Missing required environment variables: GITHUB_TOKEN, REPO_NAME", file=sys.stderr)
        sys.exit(1)
    
    pr_number = int(pr_number) if pr_number else 0
    
    # Fetch PR info
    pr_info = get_pr_info(github_token, pr_number, repo_name)
    if not pr_info:
        sys.exit(1)
    
    # Analyze code changes
    analysis = analyze_code_changes(repo_name, github_token, pr_number)
    
    # Generate review comment
    comment = generate_review_comment(analysis)
    
    # Output the comment (GitHub Actions will capture stdout)
    print(comment)


if __name__ == "__main__":
    main()