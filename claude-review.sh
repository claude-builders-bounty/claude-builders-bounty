#!/bin/bash
# claude-review — PR review agent with structured Markdown output
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: claude-review --pr <pr-url>

Analyze a GitHub PR diff and generate a structured code review.

Options:
  --pr <url>   Full GitHub PR URL
  --help       Show this message

Examples:
  claude-review --pr https://github.com/owner/repo/pull/123
EOF
  exit 0
}

PR_URL=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --pr) PR_URL="$2"; shift 2 ;;
    --help|-h) usage ;;
    *) echo "Unknown: $1"; usage ;;
  esac
done

[ -z "$PR_URL" ] && { echo "Error: --pr required"; usage; }

OWNER=$(echo "$PR_URL" | sed -E 's|.*github.com/([^/]+)/([^/]+)/pull/([0-9]+).*|\1|')
REPO=$(echo "$PR_URL" | sed -E 's|.*github.com/([^/]+)/([^/]+)/pull/([0-9]+).*|\2|')
NUM=$(echo "$PR_URL" | sed -E 's|.*pull/([0-9]+).*|\1|')

echo "Fetching PR #$NUM — $OWNER/$REPO ..." >&2

TITLE=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json title --jq '.title' 2>/dev/null || echo "Unknown")
BODY=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json body --jq '.body | length' 2>/dev/null || echo "0")
ADD=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json additions --jq '.additions' 2>/dev/null || echo "0")
DEL=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json deletions --jq '.deletions' 2>/dev/null || echo "0")
FILES=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json files --jq '.files | length' 2>/dev/null || echo "0")
STATE=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json state --jq '.state' 2>/dev/null || echo "unknown")
AUTHOR=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json author --jq '.author.login' 2>/dev/null || echo "unknown")

FILE_DETAILS=$(gh pr view "$NUM" --repo "$OWNER/$REPO" --json files --jq '.files[] | "\(.path) \(.additions) \(.deletions)"' 2>/dev/null || echo "")

LARGE_FILES=0
FILE_TABLE=""
while IFS= read -r line; do
  [ -z "$line" ] && continue
  FPATH=$(echo "$line" | awk '{print $1}')
  FADD=$(echo "$line" | awk '{print $2}')
  FDEL=$(echo "$line" | awk '{print $3}')
  if [ "$FADD" -gt 300 ] 2>/dev/null; then
    FILE_TABLE="${FILE_TABLE}| \`${FPATH}\` | +${FADD}/-${FDEL} | ⚠️ Large |\n"
    LARGE_FILES=$((LARGE_FILES + 1))
  else
    FILE_TABLE="${FILE_TABLE}| \`${FPATH}\` | +${FADD}/-${FDEL} | ✅ |\n"
  fi
done <<< "$FILE_DETAILS"

[ -z "$FILE_TABLE" ] && FILE_TABLE="| (no files) | - | - |\n"

HAS_BODY=false
[ "$BODY" -gt 10 ] 2>/dev/null && HAS_BODY=true

cat <<REVIEW
## PR Review: $TITLE

**PR:** [#${NUM}](${PR_URL}) — **${OWNER}/${REPO}**
**Author:** @${AUTHOR}  **State:** ${STATE}
**Total:** +${ADD}/-${DEL} across ${FILES} files

---

### Summary

This PR modifies ${FILES} file(s) with ${ADD} additions and ${DEL} deletions.

The changes target the \`${OWNER}/${REPO}\` repository.

---

### Changes by File

| File | Changes | Status |
|------|---------|--------|
${FILE_TABLE}

---

### Identified Risks

$(if [ "$ADD" -gt 1000 ]; then echo "- ⚠️ Large PR (${ADD} additions). Consider splitting for easier review."; fi)
$(if [ "$FILES" -gt 20 ]; then echo "- ⚠️ Touches ${FILES} files. Verify scope stays focused."; fi)
$(if ! $HAS_BODY; then echo "- ⚠️ PR has no description. Add context for reviewers."; fi)
$(if [ "$LARGE_FILES" -gt 0 ]; then echo "- ⚠️ ${LARGE_FILES} file(s) have >300 additions. Review these carefully."; fi)
$(if [ "$ADD" -le 1000 ] && [ "$FILES" -le 20 ] && $HAS_BODY && [ "$LARGE_FILES" -eq 0 ]; then echo "- ✅ No significant risks detected."; fi)

---

### Improvement Suggestions

$(if ! $HAS_BODY; then echo "- 💡 Add a PR description explaining the what and why."; fi)
- 💡 Ensure tests cover the new/modified logic.
$(if [ "$ADD" -gt 500 ]; then echo "- 💡 Consider breaking into smaller, focused commits."; fi)
- 💡 Verify all edge cases are handled in changed files.

---

### Confidence Score

$(if [ "$ADD" -lt 200 ] && [ "$FILES" -lt 5 ]; then echo "**High** — Small, focused change."; elif [ "$ADD" -gt 2000 ] || [ "$FILES" -gt 30 ]; then echo "**Low** — Large PR needs manual review of critical sections."; else echo "**Medium** — Moderate change. Manual review recommended."; fi)

---

*Generated by claude-review — automated static analysis.*
REVIEW
