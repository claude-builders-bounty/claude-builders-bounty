#!/usr/bin/env bash
# claude-review — Structured PR review with Markdown output
# Usage: claude-review --pr https://github.com/owner/repo/pull/123

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
NC='\033[0m'

usage() {
  echo "Usage: claude-review --pr <PR_URL> [--token <GH_TOKEN>]"
  echo "  --pr     GitHub PR URL (e.g., https://github.com/owner/repo/pull/123)"
  echo "  --token  GitHub token (or set GH_TOKEN env var)"
  exit 1
}

PR_URL=""
GH_TOKEN="${GH_TOKEN:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --pr) PR_URL="$2"; shift 2 ;;
    --token) GH_TOKEN="$2"; shift 2 ;;
    *) usage ;;
  esac
done

[[ -z "$PR_URL" ]] && usage && exit 1

# Parse PR URL: https://github.com/OWNER/REPO/pull/NUMBER
if [[ "$PR_URL" =~ github\.com/([^/]+)/([^/]+)/pull/([0-9]+) ]]; then
  OWNER="${BASH_REMATCH[1]}"
  REPO="${BASH_REMATCH[2]}"
  PR_NUM="${BASH_REMATCH[3]}"
else
  echo -e "${RED}Error: Invalid PR URL format${NC}"
  exit 1
fi

echo -e "${GREEN}→ Reviewing $OWNER/$REPO PR #$PR_NUM${NC}"

# Fetch PR data
AUTH_HEADER=""
[[ -n "$GH_TOKEN" ]] && AUTH_HEADER="Authorization: Bearer $GH_TOKEN"

PR_DATA=$(curl -s ${AUTH_HEADER:+-H "$AUTH_HEADER"} \
  "https://api.github.com/repos/$OWNER/$REPO/pulls/$PR_NUM")

PR_TITLE=$(echo "$PR_DATA" | python3 -c "import sys,json; print(json.load(sys.stdin).get('title','Unknown'))" 2>/dev/null || echo "Unknown")
PR_BODY=$(echo "$PR_DATA" | python3 -c "import sys,json; print(json.load(sys.stdin).get('body','') or '')" 2>/dev/null || echo "")

# Fetch diff
DIFF=$(curl -s ${AUTH_HEADER:+-H "$AUTH_HEADER"} \
  -H "Accept: application/vnd.github.v3.diff" \
  "https://api.github.com/repos/$OWNER/$REPO/pulls/$PR_NUM")

# Analyze
ADDITIONS=$(echo "$DIFF" | grep -c '^+' || echo 0)
DELETIONS=$(echo "$DIFF" | grep -c '^-' || echo 0)
FILES_CHANGED=$(echo "$DIFF" | grep -c '^diff --git' || echo 0)

# Risk detection
RISKS=""
echo "$DIFF" | grep -qi 'TODO\|FIXME\|HACK\|XXX' && RISKS+="  - Contains TODO/FIXME/HACK markers — may be incomplete\n"
echo "$DIFF" | grep -qi 'console\.log\|print(\|debugger' && RISKS+="  - Contains debug statements (console.log, print, debugger)\n"
echo "$DIFF" | grep -qi '\.env\|SECRET\|PASSWORD\|TOKEN' && RISKS+="  - May expose environment variables or secrets\n"
echo "$DIFF" | grep -qi '\.only(' && RISKS+="  - Contains .only() test filter — may skip other tests\n"
[[ "$FILES_CHANGED" -gt 20 ]] && RISKS+="  - Large PR (>20 files) — consider splitting\n"
[[ "$ADDITIONS" -gt 500 ]] && RISKS+="  - Large PR (>500 additions) — review complexity is high\n"

# Improvement suggestions
SUGGESTIONS=""
echo "$DIFF" | grep -q '^+.*TODO' && SUGGESTIONS+="  - Create follow-up issues for TODO items\n"
[[ "$FILES_CHANGED" -gt 10 ]] && SUGGESTIONS+="  - Consider splitting into smaller, focused PRs\n"
[[ -z "$PR_BODY" || ${#PR_BODY} -lt 50 ]] && SUGGESTIONS+="  - PR description is short — add context, screenshots, or testing notes\n"

# Confidence
if [[ -n "$RISKS" ]]; then
  CONFIDENCE="Medium"
  [[ $(echo "$RISKS" | wc -l) -gt 3 ]] && CONFIDENCE="Low"
else
  CONFIDENCE="High"
fi

# Structured output
cat << REVIEW

## PR Review: $PR_TITLE

**PR:** [#$PR_NUM]($PR_URL) · **Repo:** $OWNER/$REPO  
**Files:** $FILES_CHANGED · **+$ADDITIONS** / **-$DELETIONS**

### Summary
This PR modifies $FILES_CHANGED file(s) with $ADDITIONS additions and $DELETIONS deletions.
$([[ -n "$PR_BODY" ]] && echo "The author describes it as: \"${PR_BODY:0:150}...\"" || echo "The PR description is minimal — consider requesting more context.")

### Identified Risks
${RISKS:-  - No significant risks detected}

### Improvement Suggestions
${SUGGESTIONS:-  - No suggestions — PR looks clean}

### Confidence: **$CONFIDENCE**

---
*Generated by claude-review*
REVIEW
