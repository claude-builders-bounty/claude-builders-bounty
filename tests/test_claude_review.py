#!/usr/bin/env python3
"""
Unit and Integration Test Suite for Claude Code PR Review Agent.
"""

import sys
import os
import unittest
import tempfile
import subprocess
from pathlib import Path

# Add root directory to path for import
ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

import claude_review


class TestUrlParsing(unittest.TestCase):
    """Test GitHub PR URL and argument parsing."""

    def test_standard_https_url(self):
        owner, repo, num = claude_review.parse_pr_url("https://github.com/octocat/Hello-World/pull/42")
        self.assertEqual(owner, "octocat")
        self.assertEqual(repo, "Hello-World")
        self.assertEqual(num, 42)

    def test_short_domain_url(self):
        owner, repo, num = claude_review.parse_pr_url("github.com/facebook/react/pull/9999")
        self.assertEqual(owner, "facebook")
        self.assertEqual(repo, "react")
        self.assertEqual(num, 9999)

    def test_number_with_repo_override(self):
        owner, repo, num = claude_review.parse_pr_url("123", repo_override="owner/my-repo")
        self.assertEqual(owner, "owner")
        self.assertEqual(repo, "my-repo")
        self.assertEqual(num, 123)

    def test_invalid_url_raises_error(self):
        with self.assertRaises(ValueError):
            claude_review.parse_pr_url("https://gitlab.com/owner/repo/merge_requests/1")

    def test_number_without_repo_raises_error(self):
        with self.assertRaises(ValueError):
            claude_review.parse_pr_url("123")


class TestReviewFormatting(unittest.TestCase):
    """Test structured review format compliance."""

    def setUp(self):
        self.sample_pr_data = {
            "title": "feat: add user authentication",
            "body": "Implements JWT login",
            "additions": 150,
            "deletions": 20,
            "changedFiles": 3,
            "url": "https://github.com/example/repo/pull/1",
            "author": "dev-user",
            "diff": """diff --git a/auth.py b/auth.py
new file mode 100644
--- /dev/null
+++ b/auth.py
@@ -0,0 +1,15 @@
+import jwt
+def authenticate(token):
+    return jwt.decode(token, 'secret-key', algorithms=['HS256'])
diff --git a/tests/test_auth.py b/tests/test_auth.py
new file mode 100644
--- /dev/null
+++ b/tests/test_auth.py
@@ -0,0 +1,10 @@
+def test_auth():
+    pass
+"""
        }

    def test_review_sections_exist(self):
        review = claude_review.generate_heuristic_review(self.sample_pr_data)
        self.assertIn("## Summary", review)
        self.assertIn("## Risks", review)
        self.assertIn("## Suggestions", review)
        self.assertIn("## Confidence", review)

    def test_confidence_score_values(self):
        review = claude_review.generate_heuristic_review(self.sample_pr_data)
        has_valid_confidence = any(level in review for level in ["High —", "Medium —", "Low —"])
        self.assertTrue(has_valid_confidence, f"Confidence score line format invalid:\n{review}")

    def test_format_full_markdown_header(self):
        review_body = "## Summary\nTest\n\n## Risks\n- None\n\n## Suggestions\n- None\n\n## Confidence\nHigh — Solid"
        full = claude_review.format_full_markdown_output(self.sample_pr_data, review_body)
        self.assertIn("# PR Review: feat: add user authentication", full)
        self.assertIn("**Repository:**", full)
        self.assertIn("**Generated by:** Claude Code PR Reviewer", full)


class TestCliExecution(unittest.TestCase):
    """Test running the CLI tool with --diff and --output."""

    def test_diff_mode_cli(self):
        with tempfile.TemporaryDirectory() as tmp_dir:
            diff_file = Path(tmp_dir) / "sample.diff"
            out_file = Path(tmp_dir) / "review.md"

            diff_file.write_text("""diff --git a/main.py b/main.py
--- a/main.py
+++ b/main.py
@@ -1,3 +1,4 @@
 def main():
+    print("Hello world")
     return 0
""", encoding="utf-8")

            res = subprocess.run(
                [sys.executable, str(ROOT_DIR / "claude_review.py"), "--diff", str(diff_file), "--output", str(out_file), "--offline"],
                capture_output=True,
                text=True
            )

            self.assertEqual(res.returncode, 0)
            self.assertTrue(out_file.exists())
            content = out_file.read_text(encoding="utf-8")
            self.assertIn("## Summary", content)
            self.assertIn("## Risks", content)
            self.assertIn("## Suggestions", content)
            self.assertIn("## Confidence", content)


if __name__ == "__main__":
    unittest.main()
