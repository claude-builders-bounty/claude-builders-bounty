import subprocess
import tempfile
import unittest
from pathlib import Path

from tools.changelog_generator import (
    categorize_commit,
    collect_commits,
    generate_changelog,
    render_changelog,
)


class ChangelogGeneratorTests(unittest.TestCase):
    def test_categorizes_conventional_commits_and_breaking_changes(self):
        cases = {
            "feat(parser): add markdown renderer": ("Added", "parser", False),
            "fix(cli): handle empty repositories": ("Fixed", "cli", False),
            "refactor(core): simplify walker": ("Changed", "core", False),
            "docs: remove stale instructions": ("Removed", "general", False),
            "feat!: drop Python 3.8 support": ("Changed", "general", True),
            "chore(deps)!: remove legacy package": ("Changed", "deps", True),
        }

        for subject, expected in cases.items():
            with self.subTest(subject=subject):
                result = categorize_commit(subject, "")
                self.assertEqual((result.category, result.scope, result.breaking), expected)

    def test_collects_commits_since_latest_tag_with_pr_and_author_metadata(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = Path(tmp)
            self._git(repo, "init")
            self._git(repo, "config", "user.email", "test@example.com")
            self._git(repo, "config", "user.name", "Test User")
            (repo / "file.txt").write_text("v1\n")
            self._git(repo, "add", ".")
            self._git(repo, "commit", "-m", "chore: initial release")
            self._git(repo, "tag", "v0.1.0")
            (repo / "file.txt").write_text("v2\n")
            self._git(repo, "commit", "-am", "feat(api): add export endpoint (#42)")
            (repo / "file.txt").write_text("v3\n")
            self._git(repo, "commit", "-am", "fix!: normalize token cache\n\nBREAKING CHANGE: cache keys changed")

            commits = collect_commits(repo)

            self.assertEqual(len(commits), 2)
            self.assertEqual(commits[0].subject, "fix!: normalize token cache")
            self.assertTrue(commits[0].breaking)
            self.assertEqual(commits[1].pr_number, "42")
            self.assertEqual(commits[1].scope, "api")
            self.assertEqual(commits[1].author, "Test User")

    def test_write_changelog_creates_parent_directories(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = Path(tmp)
            self._git(repo, "init")
            self._git(repo, "config", "user.email", "test@example.com")
            self._git(repo, "config", "user.name", "Test User")
            (repo / "file.txt").write_text("v1\n")
            self._git(repo, "add", ".")
            self._git(repo, "commit", "-m", "feat(cli): add command")

            from tools.changelog_generator import write_changelog

            output = repo / "nested" / "CHANGELOG.generated.md"
            write_changelog(repo, output, "Unreleased", None)

            self.assertTrue(output.exists())
            self.assertIn("add command", output.read_text())

    def test_renders_keepachangelog_style_output_grouped_by_category_and_scope(self):
        changelog = generate_changelog(
            repo_path=Path(__file__).resolve().parents[1],
            commits=[
                self._commit("feat(api): add export endpoint (#42)", "abc1234", "Alice"),
                self._commit("fix(cli): handle empty repositories", "def5678", "Bob"),
                self._commit("feat!: drop old config format", "fed9999", "Cara", body="BREAKING CHANGE: config v1 removed"),
            ],
            version="Unreleased",
            compare_url="https://github.com/example/repo/compare/v1.0.0...HEAD",
        )

        text = render_changelog(changelog)

        self.assertIn("# Changelog", text)
        self.assertIn("## [Unreleased]", text)
        self.assertIn("[Compare changes](https://github.com/example/repo/compare/v1.0.0...HEAD)", text)
        self.assertIn("### Breaking Changes", text)
        self.assertIn("drop old config format", text)
        self.assertIn("### Added", text)
        self.assertIn("**api**: add export endpoint ([#42]", text)
        self.assertIn("### Fixed", text)
        self.assertIn("**cli**: handle empty repositories", text)
        self.assertIn("_Generated by `tools/changelog_generator.py`", text)

    def _commit(self, subject, sha, author, body=""):
        return categorize_commit(subject, body).with_metadata(
            sha=sha,
            author=author,
            date="2026-05-14",
            body=body,
        )

    def _git(self, repo, *args):
        subprocess.run(["git", *args], cwd=repo, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)


if __name__ == "__main__":
    unittest.main()
