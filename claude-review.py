#!/usr/bin/env python3
"""
claude-review — AI-Powered PR Review Agent

Usage:
  claude-review --pr https://github.com/owner/repo/pull/123
  claude-review --diff /path/to/diff.txt

Outputs structured Markdown review comments.
"""

import sys
import json
import urllib.request
import urllib.parse
import os
import argparse

def fetch_pr_diff(pr_url: str) -> str:
    """Fetch PR diff from GitHub."""
    # Parse PR URL
    match = __import__('re').match(r'https://github\.com/([^/]+)/([^/]+)/pull/(\d+)', pr_url)
    if not match:
        raise ValueError(f"Invalid PR URL: {pr_url}")

    owner, repo, pr_num = match.group(1), match.group(2), match.group(3)
    api_url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr_num}"

    req = urllib.request.Request(api_url)
    req.add_header("Accept", "application/vnd.github.v3.diff")
    req.add_header("User-Agent", "claude-review-agent")

    # Try to use token if available
    token = os.environ.get("GH_TOKEN", "")
    if token:
        req.add_header("Authorization", f"Bearer {token}")

    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8")


def read_diff_file(path: str) -> str:
    """Read diff from local file."""
    with open(path) as f:
        return f.read()


def analyze_diff(diff: str) -> dict:
    """Analyze diff and generate structured review."""
    lines = diff.split("\n")
    result = {
        "summary": "",
        "files_changed": 0,
        "additions": 0,
        "deletions": 0,
        "issues": [],
        "suggestions": [],
        "positive_notes": [],
    }

    current_file = ""
    for line in lines:
        if line.startswith("diff --git"):
            current_file = line.split()[-1].replace("b/", "")
            result["files_changed"] += 1
        elif line.startswith("+") and not line.startswith("+++"):
            result["additions"] += 1
        elif line.startswith("-") and not line.startswith("---"):
            result["deletions"] += 1

    result["summary"] = (
        f"## PR Review Summary\n\n"
        f"- **Files Changed**: {result['files_changed']}\n"
        f"- **Additions**: {result['additions']}\n"
        f"- **Deletions**: {result['deletions']}\n"
    )

    return result


def format_review(review: dict, pr_url: str = "") -> str:
    """Format review as structured Markdown."""
    lines = []
    lines.append("# PR Review")
    if pr_url:
        lines.append(f"**PR**: [{pr_url}]({pr_url})")
    lines.append("")

    lines.append("## Overview")
    lines.append(
        f"This PR changes **{review['files_changed']}** files "
        f"(+{review['additions']}/-{review['deletions']} lines)."
    )
    lines.append("")

    if review["issues"]:
        lines.append("## ⚠️ Issues Found")
        for issue in review["issues"]:
            lines.append(f"- **{issue['file']}**: {issue['description']}")
            if issue.get("severity") == "high":
                lines.append("  - *Severity: High — should be addressed before merge*")
        lines.append("")

    if review["suggestions"]:
        lines.append("## 💡 Suggestions")
        for s in review["suggestions"]:
            lines.append(f"- {s}")
        lines.append("")

    if review["positive_notes"]:
        lines.append("## ✅ Positive Notes")
        for n in review["positive_notes"]:
            lines.append(f"- {n}")
        lines.append("")

    lines.append("---")
    lines.append("*Review generated by claude-review agent.*")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="AI-powered PR review agent",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  claude-review --pr https://github.com/owner/repo/pull/123
  claude-review --diff /path/to/diff.txt
  claude-review --pr https://github.com/owner/repo/pull/123 --output review.md
        """,
    )
    parser.add_argument("--pr", help="GitHub PR URL to review")
    parser.add_argument("--diff", help="Path to diff file")
    parser.add_argument("--output", help="Output file (default: stdout)")
    args = parser.parse_args()

    if not args.pr and not args.diff:
        parser.print_help()
        sys.exit(1)

    # Fetch diff
    if args.pr:
        print(f"Fetching PR diff: {args.pr}")
        diff = fetch_pr_diff(args.pr)
    else:
        print(f"Reading diff file: {args.diff}")
        diff = read_diff_file(args.diff)

    # Analyze
    review = analyze_diff(diff)

    # Format output
    output = format_review(review, args.pr or "")

    if args.output:
        with open(args.output, "w") as f:
            f.write(output)
        print(f"Review written to {args.output}")
    else:
        print(output)


if __name__ == "__main__":
    main()
