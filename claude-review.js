#!/usr/bin/env node
'use strict';
// claude-review — Claude Code PR reviewer CLI
// Usage: node claude-review.js --pr https://github.com/owner/repo/pull/123

const https = require('https');

const PR_URL = process.argv[process.argv.indexOf('--pr') + 1];
if (!PR_URL) { console.error('Usage: node claude-review.js --pr <github-pr-url>'); process.exit(1); }

const m = PR_URL.match(/github\.com\/([^/]+)\/([^/]+)\/pull\/(\d+)/);
if (!m) { console.error('Invalid PR URL'); process.exit(1); }
const [, owner, repo, prNum] = m;

function ghGet(path) {
    return new Promise((resolve, reject) => {
        const opts = {
            hostname: 'api.github.com', path,
            headers: { 'User-Agent': 'claude-review', 'Accept': 'application/vnd.github.v3+json',
                       'Authorization': `Bearer ${process.env.GITHUB_TOKEN || ''}` },
            timeout: 15000,
        };
        https.get(opts, res => {
            let d = ''; res.on('data', c => d += c);
            res.on('end', () => { try { resolve(JSON.parse(d)); } catch(e) { reject(e); } });
        }).on('error', reject);
    });
}

function claudeReview(diff, prTitle, prBody) {
    return new Promise((resolve, reject) => {
        const prompt = `You are an expert code reviewer. Analyze this GitHub Pull Request and return a structured Markdown review.

PR TITLE: ${prTitle}
PR DESCRIPTION: ${(prBody||'').slice(0,500)}

DIFF (truncated to 3000 chars):
\`\`\`diff
${diff.slice(0, 3000)}
\`\`\`

Return ONLY this Markdown structure:

## Summary
(2-3 sentences describing what this PR does)

## Risks
- (list potential issues, breaking changes, security concerns)

## Suggestions
- (list specific improvement suggestions with line references if possible)

## Confidence
**Level:** Low / Medium / High
**Reason:** (one sentence)`;

        const body = JSON.stringify({
            model: 'claude-sonnet-4-20250514', max_tokens: 1024,
            messages: [{ role: 'user', content: prompt }]
        });
        const req = https.request({
            hostname: 'api.anthropic.com', path: '/v1/messages', method: 'POST',
            headers: { 'x-api-key': process.env.ANTHROPIC_API_KEY, 'anthropic-version': '2023-06-01',
                       'content-type': 'application/json', 'content-length': Buffer.byteLength(body) },
            timeout: 60000,
        }, res => {
            let d = ''; res.on('data', c => d += c);
            res.on('end', () => { try { resolve(JSON.parse(d).content?.[0]?.text || ''); } catch(e) { reject(e); } });
        });
        req.on('error', reject); req.on('timeout', () => { req.destroy(); reject(new Error('timeout')); });
        req.write(body); req.end();
    });
}

async function main() {
    console.log(`\n🔍 Reviewing PR #${prNum}: ${owner}/${repo}\n`);
    const [pr, files] = await Promise.all([
        ghGet(`/repos/${owner}/${repo}/pulls/${prNum}`),
        ghGet(`/repos/${owner}/${repo}/pulls/${prNum}/files`),
    ]);
    const diff = (Array.isArray(files) ? files : [])
        .map(f => `--- ${f.filename}\n${f.patch || ''}`)
        .join('\n').slice(0, 4000);

    const review = await claudeReview(diff, pr.title || '', pr.body || '');

    const output = `# Claude Code Review — PR #${prNum}\n**Repo:** ${owner}/${repo}\n**PR:** [${pr.title}](${PR_URL})\n**Files changed:** ${Array.isArray(files) ? files.length : '?'}\n\n---\n\n${review}\n\n---\n*Generated by [claude-review](https://github.com/claude-builders-bounty/claude-builders-bounty)*`;

    console.log(output);

    const outFile = `pr-review-${prNum}.md`;
    require('fs').writeFileSync(outFile, output);
    console.log(`\n✅ Review saved → ${outFile}`);
}

main().catch(e => { console.error('Error:', e.message); process.exit(1); });
