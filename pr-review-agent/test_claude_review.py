#!/usr/bin/env python3
"""Tests for PR Review Agent."""

import os
import pytest
from unittest.mock import Mock, patch
import requests

from claude_review import PRReviewer


class TestPRReviewer:
    """Test PRReviewer class."""

    def test_init_with_env_vars(self):
        """Test initialization with environment variables."""
        with patch.dict(os.environ, {"ANTHROPIC_API_KEY": "test-key"}):
            reviewer = PRReviewer()
            assert reviewer.claude_api_key == "test-key"

    def test_init_requires_api_key(self):
        """Test that Anthropic API key is required."""
        with pytest.raises(ValueError, match="ANTHROPIC_API_KEY"):
            PRReviewer(claude_api_key=None)

    def test_init_with_explicit_keys(self):
        """Test initialization with explicit keys."""
        reviewer = PRReviewer(
            github_token="test-gh-token",
            claude_api_key="test-claude-key",
        )
        assert reviewer.github_token == "test-gh-token"
        assert reviewer.claude_api_key == "test-claude-key"

    def test_github_headers_with_token(self):
        """Test GitHub headers with token."""
        reviewer = PRReviewer(github_token="test-token")
        assert "Authorization" in reviewer.github_headers
        assert reviewer.github_headers["Authorization"] == "Bearer test-token"

    def test_github_headers_without_token(self):
        """Test GitHub headers without token."""
        reviewer = PRReviewer(github_token=None, claude_api_key="test-key")
        assert "Authorization" not in reviewer.github_headers

    def test_format_review_structure(self):
        """Test review formatting produces correct structure."""
        reviewer = PRReviewer(claude_api_key="test-key")
        
        pr_data = {
            "title": "Test PR",
            "author": "testuser",
            "additions": 100,
            "deletions": 50,
            "changed_files": 3,
            "url": "https://github.com/test/repo/pull/1",
        }
        
        analysis = "## Summary\nTest summary\n\n## Risks\n- Risk 1\n\n## Improvements\n- Improvement 1\n\n## Confidence\nMedium"
        
        review = reviewer.format_review(analysis, pr_data)
        
        assert "## 🤖 Claude Code PR Review" in review
        assert "Test PR" in review
        assert "@testuser" in review
        assert "+100 -50" in review
        assert "3 files" in review
        assert "## Summary" in review
        assert "## Risks" in review
        assert "## Improvements" in review
        assert "## Confidence" in review
        assert "Generated by Claude Code PR Review Agent" in review

    def test_format_review_escaping(self):
        """Test that special characters in analysis are handled."""
        reviewer = PRReviewer(claude_api_key="test-key")
        
        pr_data = {
            "title": "Test <script>alert('xss')</script>",
            "author": "testuser",
            "additions": 10,
            "deletions": 5,
            "changed_files": 1,
            "url": "https://github.com/test/repo/pull/1",
        }
        
        analysis = "## Summary\nTest with `code` and **bold**"
        
        review = reviewer.format_review(analysis, pr_data)
        
        assert review is not None
        assert len(review) > 0


class TestFetchPRDiff:
    """Test PR diff fetching."""

    @patch('requests.get')
    def test_fetch_pr_diff_success(self, mock_get):
        """Test successful PR diff fetch."""
        # Mock PR API response
        pr_response = Mock()
        pr_response.json.return_value = {
            "title": "Test PR",
            "body": "Test body",
            "user": {"login": "testuser"},
            "additions": 100,
            "deletions": 50,
            "changed_files": 3,
            "diff_url": "https://github.com/test/repo/pull/1.diff",
        }
        
        # Mock diff response
        diff_response = Mock()
        diff_response.text = "diff --git a/file.py b/file.py\n+new line"
        
        mock_get.side_effect = [pr_response, diff_response]
        
        reviewer = PRReviewer(claude_api_key="test-key")
        pr_data = reviewer.fetch_pr_diff("https://github.com/test/repo/pull/1")
        
        assert pr_data["title"] == "Test PR"
        assert pr_data["author"] == "testuser"
        assert pr_data["additions"] == 100
        assert pr_data["diff"] == "diff --git a/file.py b/file.py\n+new line"

    @patch('requests.get')
    def test_fetch_pr_diff_api_error(self, mock_get):
        """Test API error handling."""
        mock_get.return_value.raise_for_status.side_effect = requests.HTTPError("404 Not Found")
        
        reviewer = PRReviewer(claude_api_key="test-key")
        
        with pytest.raises(requests.HTTPError):
            reviewer.fetch_pr_diff("https://github.com/test/repo/pull/1")

    def test_parse_pr_url(self):
        """Test PR URL parsing."""
        # URL format: https://github.com/owner/repo/pull/number
        url = "https://github.com/owner/repo/pull/123"
        parts = url.replace("https://github.com/", "").split("/")
        owner, repo, _, pr_number = parts
        
        assert owner == "owner"
        assert repo == "repo"
        assert pr_number == "123"


