import { PRInfo } from './github';
import { callClaude } from './claude';

export interface ReviewConfig {
  githubToken?: string;
  model?: string;
  maxTokens?: number;
}

function buildReviewPrompt(pr: PRInfo): string {
  return `You are an expert code reviewer. Analyze this Pull Request and provide a structured review.

## Pull Request
- **Title**: ${pr.title}
- **Repository**: ${pr.owner}/${pr.repo}
- **Files changed**: ${pr.files.join(', ')}

## Description
${pr.body || '(No description provided)'}

## Diff
\`\`\`diff
${pr.diff.slice(0, 15000)}
${pr.diff.length > 15000 ? '\n... (truncated)' : ''}
\`\`\`

Please provide your review in the following Markdown format:

## Summary
[2-3 sentence overview of what this PR does and its overall quality]

## Risks
- [List specific, concrete risks. Be honest about severity]
- Each risk should be actionable and tied to the actual code changes

## Suggestions
- [Actionable improvement suggestions]
- Focus on meaningful changes, not style preferences
- Prioritize by importance

## Confidence
- **Overall**: [High/Medium/Low]
- **Rationale**: [Brief explanation of your confidence level]
`;
}

export async function reviewPR(prUrl: string, config: ReviewConfig): Promise<string> {
  const { getPRInfo } = await import('./github');
  const pr = await getPRInfo(prUrl, { token: config.githubToken });

  const prompt = buildReviewPrompt(pr);

  const review = await callClaude(prompt, {
    model: config.model,
    maxTokens: config.maxTokens,
  });

  return `## AI Code Review: ${pr.title}

> **PR**: ${prUrl}
> **Files**: ${pr.files.length} file(s) changed

${review}

---
*Generated by claude-review agent*`;
}
