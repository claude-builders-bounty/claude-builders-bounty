def test_url_validation():
    """Test URL validation logic."""
    pattern = r'^https://github\.com/[^/]+/[^/]+/pull/\d+$'
    
    # Valid URLs
    valid_urls = [
        "https://github.com/owner/repo/pull/123",
        "https://github.com/user-name/repo-name/pull/1",
        "https://github.com/a/b/pull/99999",
    ]
    
    for url in valid_urls:
        assert re.match(pattern, url), f"Valid URL rejected: {url}"
    
    # Invalid URLs
    invalid_urls = [
        "https://github.com/owner/repo/pulls/123",  # plural
        "https://github.com/owner/repo/pull/abc",  # not a number
        "https://github.com/owner/repo",  # missing pull
        "http://github.com/owner/repo/pull/123",  # not https
        "https://gitlab.com/owner/repo/pull/123",  # wrong domain
    ]
    
    for url in invalid_urls:
        assert not re.match(pattern, url), f"Invalid URL accepted: {url}"
    
    print("[PASS] URL validation test passed")


