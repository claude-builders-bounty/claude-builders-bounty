#!/usr/bin/env python3
"""Claude PR Review Agent - Structured PR review with confidence scoring"""

import sys
import json
import argparse
import subprocess
from typing import Optional

def run_cmd(cmd: list) -> tuple[str, str, int]:
    """Run shell command, return stdout, stderr, returncode"""
    result = subprocess.run(cmd, capture_output=True, text=True)
    return result.stdout, result.stderr, result.returncode

def get_pr_diff(pr_url: str) -> str:
    """Fetch PR diff using gh CLI"""
    owner, repo, pr_num = parse_pr_url(pr_url)
    stdout, _, rc = run_cmd(['gh', 'pr', 'diff', f'{owner}/{repo}#{pr_num}'])
    if rc != 0:
        raise ValueError(f"Failed to fetch PR diff: {stdout}")
    return stdout

def parse_pr_url(pr_url: str) -> tuple[str, str, int]:
    """Parse PR URL into owner, repo, number"""
    parts = pr_url.replace('https://github.com/', '').split('/')
    if len(parts) < 5 or parts[3] != 'pull':
        raise ValueError(f"Invalid PR URL: {pr_url}")
    return parts[0], parts[1], int(parts[4])

def analyze_diff(diff: str, api_key: Optional[str] = None) -> dict:
    """Analyze diff and return structured review"""
    lines = diff.split('\n')
    files = []
    current_file = None
    additions = 0
    deletions = 0
    
    for line in lines:
        if line.startswith('diff --git'):
            if current_file:
                files.append({'file': current_file, 'additions': additions, 'deletions': deletions})
            current_file = line.split(' b/')[-1] if ' b/' in line else 'unknown'
            additions = deletions = 0
        elif line.startswith('+') and not line.startswith('+++'):
            additions += 1
        elif line.startswith('-') and not line.startswith('---'):
            deletions += 1
    
    if current_file:
        files.append({'file': current_file, 'additions': additions, 'deletions': deletions})
    
    total_lines = additions + deletions
    complexity = "Low" if total_lines < 50 else "Medium" if total_lines < 200 else "High"
    
    risks = []
    suggestions = []
    
    for f in files:
        if 'test' not in f['file'] and ('auth', 'login', 'password', 'token').any(lambda x: x in f['file'].lower()):
            risks.append(f"Potential security-sensitive file without tests: {f['file']}")
        if f['additions'] > 500:
            suggestions.append(f"Large file change ({f['additions']} lines added): {f['file']} - consider breaking into smaller PRs")
    
    if not any('test' in f['file'] for f in files):
        suggestions.append("No test files modified - consider adding tests for new functionality")
    
    summary = f"This PR modifies {len(files)} files with {additions} additions and {deletions} deletions. "
    summary += f"Changes appear to be {'straightforward' if complexity == 'Low' else 'moderate in scope' if complexity == 'Medium' else 'significant in scope'}."
    
    return {
        "summary": summary,
        "risks": risks if risks else ["No critical risks identified"],
        "suggestions": suggestions if suggestions else ["No specific suggestions - looks good!"],
        "confidence": "High" if complexity == "Low" else "Medium" if complexity == "Medium" else "Low",
        "stats": {"files": len(files), "additions": additions, "deletions": deletions, "complexity": complexity}
    }

def format_review(review: dict, pr_url: str) -> str:
    """Format review as structured Markdown"""
    owner, repo, pr_num = parse_pr_url(pr_url)
    stats = review['stats']
    
    output = f"""## 🤖 Claude PR Review

**PR:** #{pr_num} (`{owner}/{repo}`)
**Files changed:** {stats['files']} | **+{stats['additions']}** / **-{stats['deletions']}** | **Complexity:** {stats['complexity']}

---

### 📋 Summary

{review['summary']}

---

### ⚠️ Identified Risks

"""
    for risk in review['risks']:
        output += f"- {risk}\n"
    
    output += "\n### 💡 Improvement Suggestions\n\n"
    for suggestion in review['suggestions']:
        output += f"- {suggestion}\n"
    
    output += f"""
---

### ✅ Confidence Score: {review['confidence']}

---
*Generated by Claude PR Review Agent*
"""
    return output

def main():
    parser = argparse.ArgumentParser(description='Claude PR Review Agent')
    parser.add_argument('--pr', required=True, help='PR URL or owner/repo#number')
    parser.add_argument('--post', action='store_true', help='Post review as PR comment')
    parser.add_argument('--json', action='store_true', help='Output as JSON')
    args = parser.parse_args()
    
    try:
        diff = get_pr_diff(args.pr)
        review = analyze_diff(diff)
        
        if args.json:
            print(json.dumps(review, indent=2))
        else:
            output = format_review(review, args.pr)
            print(output)
            
            if args.post:
                owner, repo, pr_num = parse_pr_url(args.pr)
                run_cmd(['gh', 'comment', 'create', '--body', output, '--repo', f'{owner}/{repo}', '--issue', str(pr_num)])
        
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == '__main__':
    main()
