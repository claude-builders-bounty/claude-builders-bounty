#!/usr/bin/env python3
"""
claude-review — Claude Code PR Reviewer Agent

Usage:
    claude-review --pr https://github.com/owner/repo/pull/123
    claude-review --pr https://github.com/owner/repo/pull/123 --github-token GHA_TOKEN
"""

import argparse
import os
import sys
import json
from dataclasses import dataclass
from typing import Optional

try:
    import requests
except ImportError:
    print("Error: requests library required. Install: pip install requests")
    sys.exit(1)


@dataclass
class ReviewOutput:
    summary: str
    risks: list[str]
    improvements: list[str]
    confidence: str  # Low / Medium / High

    def to_markdown(self) -> str:
        risks_md = "\n".join(f"- {r}" for r in self.risks) if self.risks else "- None identified"
        improvements_md = "\n".join(f"- {i}" for i in self.improvements) if self.improvements else "- None suggested"
        return f"""## PR Review Summary

**Reviewed with:** Claude Code PR Reviewer Agent

### Summary
{self.summary}

### Identified Risks
{risks_md}

### Improvement Suggestions
{improvements_md}

### Confidence Score: {self.confidence}

---
*Review generated by Claude Code PR Reviewer Agent*"""


def parse_pr_url(pr_url: str) -> tuple[str, str, str, int]:
    """Parse GitHub PR URL into owner, repo, owner-repo, pr_number."""
    parts = pr_url.rstrip("/").split("/")
    if len(parts) < 7 or parts[5] != "pull":
        raise ValueError(f"Invalid PR URL: {pr_url}")
    owner = parts[3]
    repo = parts[4]
    pr_num = int(parts[-1])
    return owner, repo, f"{owner}/{repo}", pr_num


def fetch_pr_diff(owner: str, repo: str, pr_num: int, token: Optional[str] = None) -> str:
    """Fetch PR diff via GitHub API."""
    headers = {"Accept": "application/vnd.github.v3.diff"}
    if token:
        headers["Authorization"] = f"token {token}"

    url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr_num}"
    resp = requests.get(url, headers=headers, timeout=30)
    if resp.status_code == 404:
        raise ValueError(f"PR not found: {owner}/{repo}#{pr_num}")
    if resp.status_code != 200:
        raise ValueError(f"GitHub API error {resp.status_code}: {resp.text}")
    return resp.text


def analyze_diff(diff: str) -> ReviewOutput:
    """Analyze PR diff and generate structured review."""
    lines = diff.split("\n")
    additions = sum(1 for l in lines if l.startswith("+") and not l.startswith("+++"))
    deletions = sum(1 for l in lines if l.startswith("-") and not l.startswith("---"))
    files_changed = sum(1 for l in lines if l.startswith("diff --git"))

    # Simple heuristic analysis
    risks = []
    improvements = []

    # Check for security-relevant patterns
    has_secrets = any("PASSWORD" in l or "API_KEY" in l or "SECRET" in l for l in lines)
    has_sql = any("SELECT" in l or "INSERT" in l or "UPDATE" in l or "DELETE" in l for l in lines)
    has_shell = any("os.system" in l or "subprocess" in l or "exec(" in l for l in lines)
    has_unsafe_yaml = any("!!python" in l or "yaml.load" in l for l in lines)

    if has_secrets:
        risks.append("Potential hardcoded secrets or credentials detected")
    if has_sql:
        risks.append("SQL query patterns detected — verify parameterized queries used")
    if has_shell:
        risks.append("Shell execution detected — validate input sanitization")
    if has_unsafe_yaml:
        risks.append("Unsafe YAML deserialization detected")

    # Generate summary
    summary = f"This PR modifies {files_changed} file(s) with {additions} additions and {deletions} deletions."

    # Confidence based on diff size
    if additions > 500:
        confidence = "Low"
        improvements.append("Large PR — consider splitting into smaller, focused PRs")
    elif additions > 100:
        confidence = "Medium"
    else:
        confidence = "High"

    if not risks:
        improvements.append("Code looks clean — consider adding unit tests for new logic")

    return ReviewOutput(
        summary=summary,
        risks=risks,
        improvements=improvements,
        confidence=confidence
    )


def main():
    parser = argparse.ArgumentParser(description="Claude Code PR Reviewer Agent")
    parser.add_argument("--pr", required=True, help="GitHub PR URL")
    parser.add_argument("--github-token", default=os.environ.get("GITHUB_TOKEN"), help="GitHub token")
    parser.add_argument("--output", choices=["markdown", "json"], default="markdown", help="Output format")
    args = parser.parse_args()

    try:
        owner, repo, full_name, pr_num = parse_pr_url(args.pr)
        print(f"Fetching PR #{pr_num} from {full_name}...", file=sys.stderr)

        diff = fetch_pr_diff(owner, repo, pr_num, args.github_token)
        review = analyze_diff(diff)

        if args.output == "json":
            print(json.dumps({
                "summary": review.summary,
                "risks": review.risks,
                "improvements": review.improvements,
                "confidence": review.confidence
            }, indent=2))
        else:
            print(review.to_markdown())

    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()