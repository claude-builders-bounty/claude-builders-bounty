const API_VERSION = '2022-11-28';
const USER_AGENT = 'claude-pr-reviewer-bounty/1.0';

export function parsePullRequestUrl(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`Invalid pull request URL: ${value}`);
  }

  if (url.protocol !== 'https:' || url.hostname !== 'github.com') {
    throw new Error('Pull request URL must use https://github.com');
  }

  const parts = url.pathname.split('/').filter(Boolean);
  if (parts.length !== 4 || parts[2] !== 'pull' || !/^\d+$/.test(parts[3])) {
    throw new Error('Expected a GitHub pull request URL like https://github.com/owner/repo/pull/123');
  }

  const [owner, repo, , numberText] = parts;
  return {
    owner,
    repo,
    number: Number(numberText),
    htmlUrl: `https://github.com/${owner}/${repo}/pull/${Number(numberText)}`,
  };
}

function headers(token, accept = 'application/vnd.github+json') {
  const result = {
    Accept: accept,
    'User-Agent': USER_AGENT,
    'X-GitHub-Api-Version': API_VERSION,
  };
  if (token) result.Authorization = `Bearer ${token}`;
  return result;
}

async function request(url, { token, accept, method = 'GET', body, timeoutMs = 30_000 } = {}) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(url, {
      method,
      headers: {
        ...headers(token, accept),
        ...(body ? { 'Content-Type': 'application/json' } : {}),
      },
      body: body ? JSON.stringify(body) : undefined,
      signal: controller.signal,
    });

    if (!response.ok) {
      const text = await response.text();
      const suffix = text ? `: ${text.slice(0, 500)}` : '';
      throw new Error(`GitHub API ${response.status} ${response.statusText}${suffix}`);
    }
    return response;
  } catch (error) {
    if (error?.name === 'AbortError') {
      throw new Error(`GitHub request timed out after ${timeoutMs}ms`);
    }
    throw error;
  } finally {
    clearTimeout(timer);
  }
}

export function truncateUnifiedDiff(diff, maxChars) {
  if (!Number.isInteger(maxChars) || maxChars < 2_000) {
    throw new Error('--max-diff-chars must be an integer of at least 2000');
  }
  if (diff.length <= maxChars) {
    return { diff, truncated: false, originalChars: diff.length, includedChars: diff.length };
  }

  const marker = '\n\n[... DIFF TRUNCATED BY claude-review ...]\n';
  const budget = Math.max(0, maxChars - marker.length);
  const sections = diff.split(/(?=^diff --git )/m).filter(Boolean);
  let output = '';

  for (const section of sections) {
    if (output.length + section.length <= budget) {
      output += section;
      continue;
    }

    const remaining = budget - output.length;
    if (remaining > 800) output += section.slice(0, remaining);
    break;
  }

  if (!output) output = diff.slice(0, budget);
  output += marker;

  return {
    diff: output,
    truncated: true,
    originalChars: diff.length,
    includedChars: output.length,
  };
}

export async function fetchPullRequestInput(prUrl, options = {}) {
  const parsed = parsePullRequestUrl(prUrl);
  const token = options.token ?? process.env.GITHUB_TOKEN;
  const maxDiffChars = options.maxDiffChars ?? 150_000;
  const apiUrl = `https://api.github.com/repos/${encodeURIComponent(parsed.owner)}/${encodeURIComponent(parsed.repo)}/pulls/${parsed.number}`;

  const metadataResponse = await request(apiUrl, { token });
  const metadata = await metadataResponse.json();

  const diffResponse = await request(apiUrl, {
    token,
    accept: 'application/vnd.github.v3.diff',
    timeoutMs: 60_000,
  });
  const rawDiff = await diffResponse.text();
  const limited = truncateUnifiedDiff(rawDiff, maxDiffChars);

  return {
    source: parsed.htmlUrl,
    repository: `${parsed.owner}/${parsed.repo}`,
    number: parsed.number,
    title: String(metadata.title ?? '').slice(0, 2_000),
    description: String(metadata.body ?? '').slice(0, 10_000),
    author: metadata.user?.login ?? null,
    base: metadata.base?.ref ?? null,
    head: metadata.head?.ref ?? null,
    changedFiles: metadata.changed_files ?? null,
    additions: metadata.additions ?? null,
    deletions: metadata.deletions ?? null,
    diffTruncated: limited.truncated,
    originalDiffChars: limited.originalChars,
    includedDiffChars: limited.includedChars,
    diff: limited.diff,
  };
}

const COMMENT_MARKER = '<!-- claude-pr-reviewer-bounty -->';

export function reviewCommentBody(markdown) {
  return `${COMMENT_MARKER}\n${markdown.trim()}\n\n---\n_Automated review generated by the Claude Code PR reviewer._`;
}

export async function upsertPullRequestComment(prUrl, markdown, options = {}) {
  const parsed = parsePullRequestUrl(prUrl);
  const token = options.token ?? process.env.GITHUB_TOKEN;
  if (!token) throw new Error('GITHUB_TOKEN is required with --post');

  const commentsUrl = `https://api.github.com/repos/${encodeURIComponent(parsed.owner)}/${encodeURIComponent(parsed.repo)}/issues/${parsed.number}/comments`;
  let existing = null;

  // Five pages is intentionally bounded so a pathological discussion cannot make the action unbounded.
  for (let page = 1; page <= 5 && !existing; page += 1) {
    const response = await request(`${commentsUrl}?per_page=100&page=${page}`, { token });
    const comments = await response.json();
    existing = comments.find((comment) => typeof comment.body === 'string' && comment.body.includes(COMMENT_MARKER));
    if (comments.length < 100) break;
  }

  const body = reviewCommentBody(markdown);
  if (existing) {
    const response = await request(
      `https://api.github.com/repos/${encodeURIComponent(parsed.owner)}/${encodeURIComponent(parsed.repo)}/issues/comments/${existing.id}`,
      { token, method: 'PATCH', body: { body } },
    );
    const updated = await response.json();
    return { action: 'updated', url: updated.html_url };
  }

  const response = await request(commentsUrl, { token, method: 'POST', body: { body } });
  const created = await response.json();
  return { action: 'created', url: created.html_url };
}
