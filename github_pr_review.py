#!/usr/bin/env python3
"""PR Review Agent for Claude Code"""
import json, os, sys, urllib.request, urllib.error
from dataclasses import dataclass, asdict

@dataclass
class ReviewResult:
    summary: str
    risks: list
    improvements: list
    confidence: str
    files_changed: int
    lines_added: int
    lines_removed: int

def fetch_pr_diff(pr_url):
    api_url = pr_url.replace("github.com", "api.github.com/repos").replace("/pull/", "/pulls/") + ".diff"
    token = os.environ.get("GITHUB_TOKEN", "")
    req = urllib.request.Request(api_url)
    if token:
        req.add_header("Authorization", "token " + token)
    req.add_header("Accept", "application/vnd.github.v3.diff")
    try:
        with urllib.request.urlopen(req) as resp:
            return resp.read().decode("utf-8")
    except Exception as e:
        return None

def analyze_diff(diff):
    lines = diff.split("\n")
    files = sum(1 for l in lines if l.startswith("diff --git"))
    added = sum(1 for l in lines if l.startswith("+") and not l.startswith("+++"))
    removed = sum(1 for l in lines if l.startswith("-") and not l.startswith("---"))
    risks, improvements = [], []
    for l in lines:
        s = l.strip()
        if "TODO" in s or "FIXME" in s:
            risks.append("Unresolved TODO/FIXME: " + s[:60])
        if "console.log" in s and l.startswith("+"):
            improvements.append("Remove console.log before merge")
    if not risks:
        risks.append("No critical issues detected")
    if not improvements:
        improvements.append("Code looks clean")
    confidence = "High" if files <= 10 and added <= 500 else "Medium"
    return ReviewResult(summary=str(files) + " file(s), +" + str(added) + "/-" + str(removed), risks=risks[:5], improvements=improvements[:5], confidence=confidence, files_changed=files, lines_added=added, lines_removed=removed)

def format_markdown(r):
    lines = ["# PR Review Report", "", "**Summary:** " + r.summary, "", "**+" + str(r.lines_added) + "/-" + str(r.lines_removed) + "** | **Confidence:** " + r.confidence, "", "## Risks"]
    for risk in r.risks:
        lines.append("- " + risk)
    lines.append("", "## Suggestions")
    for imp in r.improvements:
        lines.append("- " + imp)
    lines.append("", "---", "_Generated by Claude Code PR Review Agent_")
    return "\n".join(lines)

def main():
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--pr", required=True)
    args = parser.parse_args()
    diff = fetch_pr_diff(args.pr)
    if not diff:
        print(json.dumps({"error": "Failed to fetch PR"}))
        return
    review = analyze_diff(diff)
    print(format_markdown(review))

if __name__ == "__main__":
    main()
