#!/usr/bin/env python3
"""
n8n-claude-weekly-summary — $200 BOUNTY #5
Automated weekly dev summary using n8n webhook + Claude Code.

Triggers: n8n workflow → webhook → this script → Claude Code → summary → Slack/Email
"""

import subprocess, json, os
from datetime import datetime, timedelta, timezone
from pathlib import Path

OUTPUT = Path.home() / "weekly-summary.md"
REPO_PATH = os.getcwd()

def get_weekly_commits():
    """Получает git-коммиты за последние 7 дней."""
    week_ago = (datetime.now(timezone.utc) - timedelta(days=7)).strftime("%Y-%m-%d")
    
    result = subprocess.run(
        ["git", "log", f"--since={week_ago}", 
         "--pretty=format:%h | %an | %s",
         "--no-merges"],
        capture_output=True, text=True, cwd=REPO_PATH
    )
    return result.stdout.strip().split('\n') if result.stdout.strip() else []

def get_changed_files():
    """Получает список изменённых файлов."""
    week_ago = (datetime.now(timezone.utc) - timedelta(days=7)).strftime("%Y-%m-%d")
    
    result = subprocess.run(
        ["git", "diff", f"--since={week_ago}", "--stat"],
        capture_output=True, text=True, cwd=REPO_PATH
    )
    return result.stdout.strip()

def count_lines_changed():
    """Считает добавленные/удалённые строки."""
    week_ago = (datetime.now(timezone.utc) - timedelta(days=7)).strftime("%Y-%m-%d")
    
    result = subprocess.run(
        ["git", "diff", f"--since={week_ago}", "--shortstat"],
        capture_output=True, text=True, cwd=REPO_PATH
    )
    return result.stdout.strip()

def generate_summary():
    """Генерирует сводку через Claude Code."""
    prompt = f"""Generate a structured weekly development summary with these sections:

## Weekly Development Summary
Week of {datetime.now(timezone.utc).strftime('%B %d, %Y')}

### Commits
{chr(10).join(get_weekly_commits()[:20])}

### Files Changed
{count_lines_changed()}

### Key Changes
[Summarize the 3 most important changes from the commits above]

### Next Week
[Suggest 2-3 priorities based on current work]

### Stats
- Total commits: {len(get_weekly_commits())}
- Active contributors: [count unique authors]
- Lines changed: {count_lines_changed()}

Keep it concise. Professional tone. Suitable for team Slack and email."""
    
    # Вызываем Claude Code (если доступен)
    try:
        result = subprocess.run(
            ["claude", "-p", prompt, "--output-format", "text"],
            capture_output=True, text=True, timeout=60
        )
        return result.stdout
    except FileNotFoundError:
        # Fallback: базовый summary без Claude
        commits = get_weekly_commits()
        authors = set(c.split('|')[1].strip() for c in commits if '|' in c)
        
        summary = f"""# Weekly Development Summary
Week of {datetime.now(timezone.utc).strftime('%B %d, %Y')}

## Stats
- **{len(commits)}** commits by **{len(authors)}** contributors
- **{count_lines_changed()}**

## Recent Commits
{chr(10).join('- ' + c for c in commits[:10])}

## Key Changes
[Add Claude Code analysis for deeper insights]

## Next Week
- Review open PRs
- Address security patches
- Plan sprint goals

---
*Generated by n8n + Claude Code workflow. ${datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}*
"""
        return summary

# === n8n WEBHOOK HANDLER ===
def handle_webhook():
    """Точка входа для n8n webhook."""
    summary = generate_summary()
    OUTPUT.write_text(summary)
    
    return {
        "status": "success",
        "summary_file": str(OUTPUT),
        "commits_analyzed": len(get_weekly_commits()),
        "generated_at": datetime.now(timezone.utc).isoformat()
    }

if __name__ == "__main__":
    result = handle_webhook()
    print(json.dumps(result, indent=2))
    print(f"\n📄 Summary saved: {OUTPUT}")
