#!/usr/bin/env bash
set -euo pipefail

# changelog.sh — Generate a structured CHANGELOG.md from git history
# Bounty #1 — Claude Builders Bounty
# Usage: bash changelog.sh [repo-path]

REPO_DIR="${1:-.}"
cd "$REPO_DIR"

# Get last tag or use initial range
LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
if [ -z "$LAST_TAG" ]; then
  LOG_RANGE="HEAD"
  TAG_LABEL="initial commit"
else
  LOG_RANGE="${LAST_TAG}..HEAD"
  TAG_LABEL="$LAST_TAG"
fi

# Check for new commits
if ! git log "$LOG_RANGE" --oneline 2>/dev/null | grep -q .; then
  echo "No new commits since $TAG_LABEL."
  exit 0
fi

# Categorize commits
SECTIONS_ADDED=""
SECTIONS_FIXED=""
SECTIONS_CHANGED=""
SECTIONS_REMOVED=""

while IFS='|' read -r HASH SUBJECT; do
  LOWER=$(echo "$SUBJECT" | tr '[:upper:]' '[:lower:]')
  CATEGORY="Changed"
  if echo "$LOWER" | grep -qE '^(feat|add|create|implement|introduce|new)'; then
    CATEGORY="Added"
  elif echo "$LOWER" | grep -qE '^(fix|patch|correct|hotfix|bug|resolve)'; then
    CATEGORY="Fixed"
  elif echo "$LOWER" | grep -qE '^(remove|delete|deprecate|drop|clean|break)'; then
    CATEGORY="Removed"
  fi

  # Format: "- Subject (abc1234)" for markdown link
  SHORT_HASH="${HASH:0:7}"
  ENTRY="- ${SUBJECT} (\`${SHORT_HASH}\`)"
  if [ "$CATEGORY" = "Added" ]; then SECTIONS_ADDED+="${ENTRY}"$'\n'
  elif [ "$CATEGORY" = "Fixed" ]; then SECTIONS_FIXED+="${ENTRY}"$'\n'
  elif [ "$CATEGORY" = "Removed" ]; then SECTIONS_REMOVED+="${ENTRY}"$'\n'
  else SECTIONS_CHANGED+="${ENTRY}"$'\n'
  fi
done < <(git log "$LOG_RANGE" --format="%H|%s" --reverse)

# Generate CHANGELOG.md
OUTPUT="CHANGELOG.md"
{
  echo "# Changelog"
  echo ""
  echo "## [Unreleased]"
  echo ""
  echo "> Generated from commits since **${TAG_LABEL}**"
  echo ""

  [ -n "$SECTIONS_ADDED" ] && echo "### ✨ Added" && echo "" && echo -n "$SECTIONS_ADDED" && echo ""
  [ -n "$SECTIONS_FIXED" ] && echo "### 🐛 Fixed" && echo "" && echo -n "$SECTIONS_FIXED" && echo ""
  [ -n "$SECTIONS_CHANGED" ] && echo "### 🔄 Changed" && echo "" && echo -n "$SECTIONS_CHANGED" && echo ""
  [ -n "$SECTIONS_REMOVED" ] && echo "### 🗑 Removed" && echo "" && echo -n "$SECTIONS_REMOVED" && echo ""

  echo "---"
  echo "_Generated by [changelog.sh](bounties/bounty-001-changelog/changelog.sh)_"
} > "$OUTPUT"

echo "✅ CHANGELOG.md generated ($(grep -c '^- ' "$OUTPUT") entries)"
