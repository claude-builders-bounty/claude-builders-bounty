#!/usr/bin/env python3
"""
claude-review: PR Review Agent

A Claude Code sub-agent that reviews GitHub PRs and posts structured
Markdown review comments.

Usage:
  python claude-review.py --pr https://github.com/owner/repo/pull/123
  python claude-review.py --diff https://github.com/owner/repo/pull/123.diff
  python claude-review.py --pr 123 --repo owner/repo
"""

import argparse
import os
import re
import sys
import urllib.request
import urllib.error
from datetime import datetime


def parse_args():
    parser = argparse.ArgumentParser(description="Claude Code PR Review Agent")
    parser.add_argument("--pr", help="Full PR URL or PR number")
    parser.add_argument("--repo", help="Repository in owner/repo format")
    parser.add_argument("--diff", help="Direct diff URL or file path")
    parser.add_argument("--output", "-o", help="Output file")
    return parser.parse_args()


def fetch_diff(url):
    headers = {"User-Agent": "claude-review-agent/1.0", "Accept": "application/vnd.github.v3.diff"}
    if not url.endswith(".diff"):
        url = url.rstrip("/") + ".diff"
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8", errors="replace")


def parse_diff(diff_text):
    files = []
    current = None
    for line in diff_text.split("\n"):
        if line.startswith("diff --git"):
            if current:
                files.append(current)
            m = re.match(r"diff --git a/(.+) b/(.+)", line)
            current = {"path": m.group(2) if m else "unknown", "additions": 0, "deletions": 0}
        elif current:
            if line.startswith("+"):
                current["additions"] += 1
            elif line.startswith("-"):
                current["deletions"] += 1
    if current:
        files.append(current)
    return files


def gen_review(files, pr_url):
    total_add = sum(f["additions"] for f in files)
    total_del = sum(f["deletions"] for f in files)
    n = len(files)
    has_tests = any("test" in f["path"].lower() for f in files)
    
    score = 0.5
    if n > 5: score += 0.15
    if total_add + total_del < 50: score += 0.2
    elif total_add + total_del < 200: score += 0.1
    if has_tests: score += 0.1
    confidence = "High" if score >= 0.75 else "Medium" if score >= 0.5 else "Low"
    
    risks = []
    if total_add > 500: risks.append("Large PR size makes thorough review difficult")
    if not has_tests: risks.append("No test file changes detected")
    
    suggestions = []
    if any(f["additions"] > 200 for f in files):
        big = [f["path"] for f in files if f["additions"] > 200][:3]
        suggestions.append(f"Large files: {', '.join(big)} — consider refactoring")
    
    lines = []
    lines.append("## 🤖 PR Review")
    lines.append(f"**Confidence:** {confidence}")
    lines.append(f"**PR:** {pr_url}")
    lines.append(f"**Reviewed:** {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}")
    lines.append("")
    lines.append(f"### Summary\n")
    lines.append(f"Modifies **{n} files** with **+{total_add}** additions and **-{total_del}** deletions.\n")
    lines.append("### Risks\n")
    lines.extend(f"- {r}" for r in risks) if risks else lines.append("_None identified._\n")
    lines.append("\n### Suggestions\n")
    lines.extend(f"- {s}" for s in suggestions) if suggestions else lines.append("_None at this time._\n")
    lines.append("\n### Files\n| File | + | - |\n| --- | --- | --- |")
    for f in sorted(files, key=lambda x: x["additions"] + x["deletions"], reverse=True)[:15]:
        lines.append(f"| {f['path']} | +{f['additions']} | -{f['deletions']} |")
    lines.append("\n---\n*Generated by claude-review-agent*")
    return "\n".join(lines)


def main():
    args = parse_args()
    if args.diff and not args.diff.startswith(("http://", "https://")):
        with open(args.diff, encoding="utf-8") as f:
            diff_text = f.read()
        pr_url = "local"
    elif args.pr:
        repo = args.repo or "/".join(args.pr.split("/")[-3:-1])
        num = args.pr.split("/")[-1] if "/" in args.pr else args.pr
        pr_url = f"https://github.com/{repo}/pull/{num}"
        diff_text = fetch_diff(pr_url)
    else:
        print("Error: --pr or --diff required", file=sys.stderr)
        sys.exit(1)
    
    files = parse_diff(diff_text)
    review = gen_review(files, pr_url)
    
    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(review)
    else:
        print(review)


if __name__ == "__main__":
    main()

