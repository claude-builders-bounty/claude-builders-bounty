#!/usr/bin/env bash
#
# generate-changelog.sh — Generate a structured CHANGELOG.md from git history
# Usage: bash generate-changelog.sh [since-tag]
#
# Requirements: git, standard Unix tools (grep, sed, awk, sort, uniq)
#

set -euo pipefail

OUTPUT="${1:-CHANGELOG.md}"
REPO_URL="${GIT_REPO_URL:-$(git remote get-url origin 2>/dev/null | sed 's/\.git$//')}"
SINCE="${2:-$(git describe --tags --abbrev=0 2>/dev/null || echo '1970-01-01')}"

# Color output (disabled if not a terminal)
if [[ -t 1 ]]; then
  RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
else
  RED=''; GREEN=''; YELLOW=''; BLUE=''; NC=''
fi

log() { echo -e "${BLUE}[changelog]${NC} $*"; }
warn() { echo -e "${YELLOW}[warn]${NC} $*" >&2; }

log "Generating changelog since: $SINCE"

# Check for uncommitted changes
if ! git diff --quiet 2>/dev/null; then
  warn "You have uncommitted changes. They won't appear in the changelog."
fi

# Get commits since tag (or all if no tag)
COMMITS=$(git log --since="$SINCE" --oneline --format='%H|%s|%b' 2>/dev/null | grep -v '^$' || true)

if [[ -z "$COMMITS" ]]; then
  log "No commits found since $SINCE"
  exit 0
fi

# Categorization patterns (conventional commits + heuristics)
declare -A CATEGORIES=(
  [added]="^feat|^add|^feat\(.*\):|新增|feat:|feature:|新功能"
  [fixed]="^fix|^bug|^hotfix|fix:|修复|bugfix:|hot fix"
  [changed]="^refactor|^chore|^perf|^style|refactor:|重构|改进|update:|enhance:"
  [removed]="^remove|^delete|^deprecate|remove:|删除|废弃"
)

init_category() {
  printf '## %s\n\n' "$1"
  printf '| Commit | Description |\n' 
  printf '|--------|-------------|\n'
}

cat_body() {
  local cat=$1
  shift
  local commits=("$@")
  if [[ ${#commits[@]} -eq 0 ]]; then
    printf '_No changes in this category._\n\n'
  else
    for commit in "${commits[@]}"; do
      local hash msg
      hash=$(echo "$commit" | cut -d'|' -f1 | cut -c1-7)
      msg=$(echo "$commit" | cut -d'|' -f2- | sed 's/|/ /g')
      printf '| `%s` | %s |\n' "$hash" "$msg"
    done
    printf '\n'
  fi
}

# Parse commits into categories
declare -a added=() fixed=() changed=() removed=()

while IFS= read -r line; do
  [[ -z "$line" ]] && continue
  first_word=$(echo "$line" | cut -d'|' -f2 | awk '{print tolower($1)}')
  
  categorized=false
  for category in added fixed changed removed; do
    pattern="${CATEGORIES[$category]}"
    if echo "$line" | grep -Ei "$pattern" >/dev/null 2>&1; then
      case $category in
        added)   added+=("$line") ;;
        fixed)   fixed+=("$line") ;;
        changed) changed+=("$line") ;;
        removed) removed+=("$line") ;;
      esac
      categorized=true
      break
    fi
  done
  
  if [[ "$categorized" == "false" ]]; then
    # Uncategorised → treat as Changed
    changed+=("$line")
  fi
done <<< "$COMMITS"

# Generate CHANGELOG.md
{
  printf '# Changelog\n\n'
  printf '_Generated by generate-changelog.sh_\n\n'
  printf '## %s\n\n' "$(date '+%Y-%m-%d')"
  
  init_category "Added"
  cat_body "added" "${added[@]}"
  
  init_category "Fixed"
  cat_body "fixed" "${fixed[@]}"
  
  init_category "Changed"
  cat_body "changed" "${changed[@]}"
  
  init_category "Removed"
  cat_body "removed" "${removed[@]}"

  # Append previous changelog if exists
  if [[ -f CHANGELOG.md ]] && [[ -s CHANGELOG.md ]]; then
    printf '\n---\n\n'
    tail -n +6 CHANGELOG.md 2>/dev/null | head -c 5000
  fi
} > "$OUTPUT"

log "✅ Changelog written to $OUTPUT ($(wc -l < "$OUTPUT") lines)"
log "📦 $((${#added[@]} + ${#fixed[@]} + ${#changed[@]} + ${#removed[@]})) commits categorised:"
log "   + Added:   ${#added[@]}"
log "   ~ Fixed:   ${#fixed[@]}"
log "   * Changed: ${#changed[@]}"
log "   - Removed: ${#removed[@]}"
