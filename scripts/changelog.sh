#!/usr/bin/env bash
# CHANGELOG Generator — extracts commits since last tag, auto-categorizes
# Usage: ./scripts/changelog.sh [--since <tag>] [--output CHANGELOG.md]
set -euo pipefail

SINCE=""
OUTPUT="CHANGELOG.md"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --since) SINCE="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    --help|-h)
      echo "Usage: changelog.sh [--since <tag>] [--output <file>]"
      echo ""
      echo "Generates a structured CHANGELOG.md from git history."
      echo "Auto-categorizes commits into: Added, Fixed, Changed, Removed."
      echo ""
      echo "  --since <tag>   Start from this tag (default: most recent tag)"
      echo "  --output <file> Output file (default: CHANGELOG.md)"
      exit 0
      ;;
    *) echo "Unknown arg: $1"; exit 1 ;;
  esac
done

# Determine starting point
if [[ -z "$SINCE" ]]; then
  SINCE=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
fi

if [[ -z "$SINCE" ]]; then
  echo "No git tags found. Generating changelog from first commit..."
  SINCE=$(git rev-list --max-parents=0 HEAD)
fi

echo "📝 Generating changelog since: $SINCE"
echo ""

# Get commits since the tag
COMMITS=$(git log "$SINCE..HEAD" --pretty=format:"%s" --no-merges 2>/dev/null)

if [[ -z "$COMMITS" ]]; then
  echo "No commits found since $SINCE."
  exit 0
fi

# ─── Categorize commits ──────────────────────────────

ADDED=""
FIXED=""
CHANGED=""
REMOVED=""

while IFS= read -r line; do
  [[ -z "$line" ]] && continue

  # Detect conventional commit prefix
  if echo "$line" | grep -qiE '^(feat|add|new|introduce|implement)[(: ]'; then
    ADDED+="- ${line}\n"
  elif echo "$line" | grep -qiE '^(fix|bug|hotfix|patch|resolve|correct)[(: ]'; then
    FIXED+="- ${line}\n"
  elif echo "$line" | grep -qiE '^(remove|drop|delete|deprecate)[(: ]'; then
    REMOVED+="- ${line}\n"
  else
    CHANGED+="- ${line}\n"
  fi
done <<< "$COMMITS"

# ─── Generate CHANGELOG ──────────────────────────────

TODAY=$(date +%Y-%m-%d)
VERSION=$(git describe --tags --abbrev=0 2>/dev/null || echo "unreleased")

{
  echo "# Changelog"
  echo ""
  echo "## [$VERSION] — $TODAY"
  echo ""

  if [[ -n "$ADDED" ]]; then
    echo "### Added"
    echo -e "$ADDED"
  fi

  if [[ -n "$FIXED" ]]; then
    echo "### Fixed"
    echo -e "$FIXED"
  fi

  if [[ -n "$CHANGED" ]]; then
    echo "### Changed"
    echo -e "$CHANGED"
  fi

  if [[ -n "$REMOVED" ]]; then
    echo "### Removed"
    echo -e "$REMOVED"
  fi

  echo ""
  echo "---"
  echo "*Generated by changelog.sh — $(date)*"
} > "$OUTPUT"

COMMIT_COUNT=$(echo "$COMMITS" | wc -l)
echo "✅ $COMMIT_COUNT commits categorized"
echo "   Added:   $(echo -e "$ADDED" | grep -c '^-' || echo 0)"
echo "   Fixed:   $(echo -e "$FIXED" | grep -c '^-' || echo 0)"
echo "   Changed: $(echo -e "$CHANGED" | grep -c '^-' || echo 0)"
echo "   Removed: $(echo -e "$REMOVED" | grep -c '^-' || echo 0)"
echo ""
echo "📄 Output: $OUTPUT"
