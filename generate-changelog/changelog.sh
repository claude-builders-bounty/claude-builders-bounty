#!/usr/bin/env bash
# changelog.sh — generate a structured CHANGELOG.md from git history
# since the last tag. Categorizes commits (conventional-commit aware with
# keyword fallback), skips merges/version-bumps, and prepends a new section
# to an existing CHANGELOG.md (Keep a Changelog style).
#
# Usage: bash changelog.sh [path-to-repo]
# Env:   CHANGELOG_OUTPUT (default: CHANGELOG.md)
set -euo pipefail

OUTPUT="${CHANGELOG_OUTPUT:-CHANGELOG.md}"
REPO="${1:-.}"
cd "$REPO"

if ! git rev-parse --git-dir >/dev/null 2>&1; then
    echo "error: $REPO is not a git repository" >&2
    exit 1
fi

# --- find the range: last tag..HEAD, or full history when no tags exist ---
LAST_TAG="$(git describe --tags --abbrev=0 2>/dev/null || true)"
if [[ -n "$LAST_TAG" ]]; then
    RANGE="${LAST_TAG}..HEAD"
    RANGE_LABEL="since ${LAST_TAG}"
else
    RANGE=""
    RANGE_LABEL="all history (no tags found)"
fi

# --- collect commits (no merges, no version-bump noise) ---
# Fields: hash, subject, author, date — unit-separated for safe parsing.
mapfile -t COMMITS < <(
    git log --no-merges --pretty=format:'%h%x1f%s%x1f%an%x1f%ad' --date=short $RANGE \
    | grep -v -iE '^[^[:space:]]+[[:space:]]*(bump version|release v?[0-9]|version bump)' || true
)

if [[ ${#COMMITS[@]} -eq 0 ]]; then
    echo "no commits ${RANGE_LABEL} — nothing to generate"
    exit 0
fi

# --- categorize ---
declare -a ADDED FIXED CHANGED REMOVED
n_added=0; n_fixed=0; n_changed=0; n_removed=0

classify() {
    # $1 = subject line. Conventional commits win; keyword fallback otherwise.
    local subject="$1"
    local type=""
    local re_conv='^([a-zA-Z]+)(\([^)]*\))?!?:'
    if [[ "$subject" =~ $re_conv ]]; then
        type="$(printf '%s' "${BASH_REMATCH[1]}" | tr '[:upper:]' '[:lower:]')"
    fi
    case "$type" in
        feat|feature|add|added)             echo "added" ;;
        fix|bugfix|hotfix)                  echo "fixed" ;;
        perf|refactor|style|chore|docs|doc|test|tests|build|ci)
                                           echo "changed" ;;
        revert|remove|removed|delete)       echo "removed" ;;
        deprecate|deprecated)               echo "removed" ;;
        *)
            # keyword fallback for non-conventional messages
            local lower
            lower="$(printf '%s' "$subject" | tr '[:upper:]' '[:lower:]')"
            local re_add='(^|[^a-z])(add|added|introduce|new|support)([^a-z]|$)'
            local re_fix='(^|[^a-z])(fix|fixed|bug|patch|correct|resolve)([^a-z]|$)'
            local re_rm='(^|[^a-z])(remove|removed|delete|deleted|drop|revert)([^a-z]|$)'
            if   [[ "$lower" =~ $re_add ]]; then echo "added"
            elif [[ "$lower" =~ $re_fix ]]; then echo "fixed"
            elif [[ "$lower" =~ $re_rm ]]; then echo "removed"
            else echo "changed"
            fi
            ;;
    esac
}

strip_prefix() {
    # remove conventional-commit prefix for display: "feat(x): msg" -> "msg"
    local subject="$1"
    local re_conv='^[a-zA-Z]+(\([^)]*\))?!?:[[:space:]]*(.*)$'
    if [[ "$subject" =~ $re_conv ]]; then
        printf '%s' "${BASH_REMATCH[2]}"
    else
        printf '%s' "$subject"
    fi
}

for line in "${COMMITS[@]}"; do
    IFS=$'\x1f' read -r hash subject author date <<< "$line"
    [[ -z "${subject:-}" ]] && continue
    cat="$(classify "$subject")"
    clean="$(strip_prefix "$subject")"
    entry="- ${clean} (\`${hash}\`, ${author}, ${date})"
    case "$cat" in
        added)   ADDED+=("$entry");   n_added=$((n_added+1)) ;;
        fixed)   FIXED+=("$entry");   n_fixed=$((n_fixed+1)) ;;
        removed) REMOVED+=("$entry"); n_removed=$((n_removed+1)) ;;
        *)       CHANGED+=("$entry"); n_changed=$((n_changed+1)) ;;
    esac
done

# --- render the new section ---
TODAY="$(date +%Y-%m-%d)"
SECTION=""
SECTION+="## Unreleased (${TODAY})"$'\n\n'
SECTION+="<!-- generated by changelog.sh — commits ${RANGE_LABEL} -->"$'\n\n'

emit() {
    local title="$1"; shift
    if [[ $# -gt 0 ]]; then
        SECTION+="### ${title}"$'\n\n'
        for e in "$@"; do SECTION+="${e}"$'\n'; done
        SECTION+=$'\n'
    fi
}
# guard expansion keeps empty arrays out of the call (set -u safe, no empty sections)
emit "Added"   ${ADDED[@]+"${ADDED[@]}"}
emit "Fixed"   ${FIXED[@]+"${FIXED[@]}"}
emit "Changed" ${CHANGED[@]+"${CHANGED[@]}"}
emit "Removed" ${REMOVED[@]+"${REMOVED[@]}"}

if [[ -z "${ADDED[*]:-}${FIXED[*]:-}${CHANGED[*]:-}${REMOVED[*]:-}" ]]; then
    SECTION+="No categorized changes."$'\n\n'
fi

# --- write: prepend to existing CHANGELOG.md (Keep a Changelog) ---
# A re-run must REPLACE the existing "## Unreleased" section (it is a living
# section), not append a second one. Older released sections stay untouched.
strip_unreleased() {
    # print $1 minus its "## Unreleased ..." section (header to next ## or EOF)
    awk '
        /^## Unreleased/ { skip=1; next }
        /^## /           { skip=0 }
        !skip            { print }
    ' "$1"
}

render_fresh() {
    { echo "# Changelog"; echo; printf '%s' "$SECTION"; }
}

if [[ -f "$OUTPUT" ]]; then
    TMP="$(mktemp)"
    if head -1 "$OUTPUT" | grep -q '^# Changelog'; then
        {
            echo "# Changelog"
            echo
            printf '%s' "$SECTION"
            strip_unreleased "$OUTPUT"
        } | awk 'NF{blank=0; print; next} {if(!blank++) print}' > "$TMP"
    else
        { render_fresh; echo; cat "$OUTPUT"; } | awk 'NF{blank=0; print; next} {if(!blank++) print}' > "$TMP"
    fi
    mv "$TMP" "$OUTPUT"
else
    render_fresh > "$OUTPUT"
fi

n_total=${#COMMITS[@]}
echo "wrote ${OUTPUT} — commits ${RANGE_LABEL} (${n_total} commits: ${n_added} added, ${n_fixed} fixed, ${n_changed} changed, ${n_removed} removed)"
