#!/bin/bash
# changelog.sh — Generate a structured CHANGELOG.md from git history
# Usage: ./changelog.sh [--since <tag>] [--output <file>]
# If --since is not provided, auto-detects the last git tag.

set -e

SINCE_TAG=""
OUTPUT_FILE="CHANGELOG.md"
REPO_PATH="${REPO_PATH:-.}"

while [[ $# -gt 0 ]]; do
    case $1 in
        --since)
            SINCE_TAG="$2"
            shift 2
            ;;
        --output)
            OUTPUT_FILE="$2"
            shift 2
            ;;
        *)
            echo "Unknown option: $1"
            exit 1
            ;;
    esac
done

cd "$REPO_PATH"

# Auto-detect last tag if not provided
if [[ -z "$SINCE_TAG" ]]; then
    LAST_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
    if [[ -z "$LAST_TAG" ]]; then
        echo "No tags found. Fetching all commits..."
        SINCE_TAG=$(git rev-list --max-parents=0 HEAD 2>/dev/null | tail -1)
        RANGE="$SINCE_TAG..HEAD"
    else
        RANGE="$LAST_TAG..HEAD"
    fi
else
    RANGE="$SINCE_TAG..HEAD"
fi

# Fetch commits
COMMITS=$(git log $RANGE --pretty=format:"%s|||%b|||%H" 2>/dev/null)

# Categorize
declare -A ADDED FIXED CHANGED REMOVED

while IFS= read -r line; do
    SUBJECT="${line%%|||*}"
    BODY="${line#*|||}"
    BODY="${BODY%%|||*}"
    LOWER_SUBJECT=$(echo "$SUBJECT" | tr '[:upper:]' '[:lower:]')

    # Conventional Commits detection
    if echo "$LOWER_SUBJECT" | grep -qE "^(feat|add|new):"; then
        ADDED+=("$SUBJECT")
    elif echo "$LOWER_SUBJECT" | grep -qE "^(fix|bug|patch):"; then
        FIXED+=("$SUBJECT")
    elif echo "$LOWER_SUBJECT" | grep -qE "^(refactor|chore|docs|style|perf|test):"; then
        CHANGED+=("$SUBJECT")
    elif echo "$LOWER_SUBJECT" | grep -qE "^(remove|delete|deprecate|drop):"; then
        REMOVED+=("$SUBJECT")
    else
        # Heuristic fallback
        if echo "$LOWER_SUBJECT" | grep -qE "(new|add|introduce|create)"; then
            ADDED+=("$SUBJECT")
        elif echo "$LOWER_SUBJECT" | grep -qE "(fix|bug|patch|correct)"; then
            FIXED+=("$SUBJECT")
        elif echo "$LOWER_SUBJECT" | grep -qE "(remove|delete|deprecate|drop)"; then
            REMOVED+=("$SUBJECT")
        else
            CHANGED+=("$SUBJECT")
        fi
    fi
done <<< "$COMMITS"

# Generate CHANGELOG.md
{
    echo "# Changelog"
    echo ""
    echo "All notable changes to this project will be documented in this file."
    echo ""
    echo "## [Unreleased]"
    echo ""

    if [[ ${#ADDED[@]} -gt 0 ]]; then
        echo "### Added"
        for item in "${ADDED[@]}"; do
            echo "- ${item%" | *}"}"
        done
        echo ""
    fi

    if [[ ${#FIXED[@]} -gt 0 ]]; then
        echo "### Fixed"
        for item in "${FIXED[@]}"; do
            echo "- ${item%" | *}"}"
        done
        echo ""
    fi

    if [[ ${#CHANGED[@]} -gt 0 ]]; then
        echo "### Changed"
        for item in "${CHANGED[@]}"; do
            echo "- ${item%" | *}"}"
        done
        echo ""
    fi

    if [[ ${#REMOVED[@]} -gt 0 ]]; then
        echo "### Removed"
        for item in "${REMOVED[@]}"; do
            echo "- ${item%" | *}"}"
        done
        echo ""
    fi

    echo "<!-- Generated by changelog.sh -->"
} > "$OUTPUT_FILE"

echo "✅ CHANGELOG.md written to $OUTPUT_FILE"
echo "   $(( ${#ADDED[@]} + ${#FIXED[@]} + ${#CHANGED[@]} + ${#REMOVED[@]} )) commits processed"
