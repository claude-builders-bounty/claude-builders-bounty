#!/usr/bin/env bash
# Generate a structured CHANGELOG.md from git history since the last tag,
# categorized into Added / Fixed / Changed / Removed (Keep a Changelog style).
set -euo pipefail

MARKER="generated-by: changelog.sh"
OUTPUT="CHANGELOG.md"
SINCE=""
NO_TAG=0
FORCE=0
REPO="."

usage() {
  cat <<'EOF'
Usage: changelog.sh [-o OUTPUT] [--since REF | --no-tag] [-f] [REPO_DIR]
  -o FILE      Output file (default: CHANGELOG.md)
  --since REF  Start the range at REF instead of the newest tag
  --no-tag     Ignore tags and include the full history
  -f           Overwrite OUTPUT even without the generated-by marker
  REPO_DIR     Git repository to read (default: current directory)
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    -o) OUTPUT="$2"; shift 2 ;;
    --since) SINCE="$2"; shift 2 ;;
    --no-tag) NO_TAG=1; shift ;;
    -f|--force) FORCE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) REPO="$1"; shift ;;
  esac
done

git -C "$REPO" rev-parse HEAD >/dev/null 2>&1 || {
  echo "error: $REPO is not a git repository (or has no commits)" >&2
  exit 1
}

# Never clobber a hand-written file: require our marker or an explicit -f.
if [ -e "$OUTPUT" ] && [ "$FORCE" -ne 1 ] && ! grep -q "$MARKER" "$OUTPUT"; then
  echo "error: $OUTPUT exists and was not generated by changelog.sh (use -f to overwrite)" >&2
  exit 1
fi

if [ -z "$SINCE" ] && [ "$NO_TAG" -ne 1 ]; then
  SINCE="$(git -C "$REPO" describe --tags --abbrev=0 2>/dev/null || true)"
fi
if [ -n "$SINCE" ]; then RANGE="$SINCE..HEAD"; else RANGE="HEAD"; fi

# %s = subject, %h = short sha, tab-separated so subjects with spaces survive.
LOG="$(git -C "$REPO" log --no-merges --pretty=%s%x09%h "$RANGE")"

classify() {
  local s="${1,,}" type
  type="${s%%[:!]*}"        # conventional-commit prefix before ":" or "!"
  type="${type%%\(*}"       # drop "(scope)"
  case "$type" in
    fix) echo Fixed; return ;;
    feat) echo Added; return ;;
    revert|revert-[0-9]*|revert*) echo Removed; return ;;
  esac
  # Fallback for free-form subjects: keyword heuristics, most specific first.
  case "$s" in
    *remov*|*deprecat*|*delet*|*drop*|revert*) echo Removed ;;
    *fix*|*bug*|*crash*|*error*|*leak*|*patch*) echo Fixed ;;
    *feat*|*add*|*support*|*introduc*|*implement*|*allow*|*enable*|*new*) echo Added ;;
    *) echo Changed ;;
  esac
}

ADDED="" FIXED="" CHANGED="" REMOVED="" COUNT=0
while IFS=$'\t' read -r subject sha; do
  [ -z "$subject" ] && continue
  COUNT=$((COUNT + 1))
  line="- $subject ($sha)"
  case "$(classify "$subject")" in
    Added)   ADDED="${ADDED}${line}"$'\n' ;;
    Fixed)   FIXED="${FIXED}${line}"$'\n' ;;
    Changed) CHANGED="${CHANGED}${line}"$'\n' ;;
    Removed) REMOVED="${REMOVED}${line}"$'\n' ;;
  esac
done <<< "$LOG"

{
  echo "# Changelog"
  echo
  echo "<!-- $MARKER — regenerate with \`bash generate-changelog/changelog.sh\`; do not edit the sections below by hand -->"
  echo
  echo "## [Unreleased] ($(date -u +%F))"
  echo
  if [ "$COUNT" -eq 0 ]; then
    if [ -n "$SINCE" ]; then echo "_No commits since \`$SINCE\`._"
    else echo "_Repository has no commits yet._"; fi
  else
    if [ -n "$SINCE" ]; then echo "_Commits since \`$SINCE\` ($COUNT)_:"
    else echo "_Full history, no tags found ($COUNT commits):_"; fi
    echo
    section() {
      [ -n "$2" ] || return 0
      echo "### $1"
      echo
      printf '%s' "$2"
      echo
    }
    section Added "$ADDED"
    section Fixed "$FIXED"
    section Changed "$CHANGED"
    section Removed "$REMOVED"
  fi
} > "$OUTPUT"

echo "wrote $OUTPUT ($COUNT commits, since: ${SINCE:-full history})"
