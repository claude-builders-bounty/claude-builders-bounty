#!/usr/bin/env node

import { pathToFileURL } from "node:url";

const VERSION = "0.1.0";

function usage() {
  return `claude-review ${VERSION}

Usage:
  claude-review --pr https://github.com/owner/repo/pull/123 [--output markdown|json]

Environment:
  GITHUB_TOKEN  Optional token for higher GitHub API limits and private repos.
`;
}

function parseArgs(argv) {
  const args = { output: "markdown" };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--help" || arg === "-h") args.help = true;
    else if (arg === "--version") args.version = true;
    else if (arg === "--pr") args.pr = argv[++i];
    else if (arg === "--output") args.output = argv[++i];
    else throw new Error(`Unknown argument: ${arg}`);
  }
  if (!args.help && !args.version && !args.pr) {
    throw new Error("Missing required --pr URL");
  }
  if (!["markdown", "json"].includes(args.output)) {
    throw new Error("--output must be markdown or json");
  }
  return args;
}

export function parsePullRequestUrl(url) {
  const match = String(url).match(/^https:\/\/github\.com\/([^/]+)\/([^/]+)\/pull\/(\d+)(?:[/?#].*)?$/);
  if (!match) {
    throw new Error("PR URL must look like https://github.com/owner/repo/pull/123");
  }
  return { owner: match[1], repo: match[2], pullNumber: Number(match[3]) };
}

async function githubJson(path) {
  const headers = {
    "Accept": "application/vnd.github+json",
    "X-GitHub-Api-Version": "2022-11-28"
  };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const response = await fetch(`https://api.github.com${path}`, { headers });
  if (!response.ok) {
    throw new Error(`GitHub API ${path} failed: ${response.status} ${await response.text()}`);
  }
  return response.json();
}

async function githubText(path) {
  const headers = { "Accept": "application/vnd.github.v3.diff" };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const response = await fetch(`https://api.github.com${path}`, { headers });
  if (!response.ok) {
    throw new Error(`GitHub diff ${path} failed: ${response.status} ${await response.text()}`);
  }
  return response.text();
}

function changedFilesFromDiff(diff) {
  return diff
    .split("\n")
    .filter((line) => line.startsWith("diff --git "))
    .map((line) => line.replace(/^diff --git a\//, "").replace(/ b\/.*/, ""));
}

function diffStats(diff) {
  let additions = 0;
  let deletions = 0;
  for (const line of diff.split("\n")) {
    if (line.startsWith("+++") || line.startsWith("---")) continue;
    if (line.startsWith("+")) additions += 1;
    if (line.startsWith("-")) deletions += 1;
  }
  return { additions, deletions, totalChanged: additions + deletions };
}

function hasAny(files, patterns) {
  return files.some((file) => patterns.some((pattern) => pattern.test(file)));
}

export function analyzePullRequest({ title, body = "", files, diff }) {
  const stats = diffStats(diff);
  const lowerDiff = diff.toLowerCase();
  const lowerBody = body.toLowerCase();
  const risks = [];
  const suggestions = [];

  if (stats.totalChanged > 800) {
    risks.push("Large diff size may hide unrelated behavior changes during review.");
    suggestions.push("Split follow-up cleanup or generated artifacts out of the functional change where possible.");
  }
  if (hasAny(files, [/package-lock\.json$/, /pnpm-lock\.yaml$/, /yarn\.lock$/, /package\.json$/])) {
    risks.push("Dependency or package metadata changed, which can affect install and CI behavior.");
    suggestions.push("Call out why dependency changes are required and verify the lockfile was regenerated by the expected package manager.");
  }
  if (hasAny(files, [/\.github\/workflows\//])) {
    risks.push("Workflow changes can alter CI permissions, triggers, or secret exposure.");
    suggestions.push("Review GitHub Action permissions explicitly and keep default token access least-privileged.");
  }
  if (hasAny(files, [/\.(sql|db|sqlite)$/]) || /\b(migration|migrate|schema)\b/.test(lowerDiff)) {
    risks.push("Database or migration-related changes may be hard to roll back if deployed without a tested path.");
    suggestions.push("Include forward and rollback notes, plus verification against an empty and upgraded database state.");
  }
  if (/\b(api[_-]?key|secret|token|password)\b/.test(lowerDiff) && !/\b(example|placeholder|redacted|process\.env)\b/.test(lowerDiff)) {
    risks.push("Sensitive-looking values or credential names appear in the diff.");
    suggestions.push("Confirm no real secrets are committed and prefer environment variables or secret stores.");
  }
  if (!/\b(test|spec|fixture|sample|mock)\b/.test(files.join(" ")) && !/\b(test|tested|verification|validated)\b/.test(lowerBody)) {
    risks.push("No obvious test or verification artifact is included with the change.");
    suggestions.push("Add a focused test, sample output, or manual verification transcript before merge.");
  }
  if (files.length === 0) {
    risks.push("No changed files were detected from the diff.");
    suggestions.push("Re-run the review with a PR URL that exposes a diff.");
  }
  if (risks.length === 0) risks.push("No high-risk patterns were detected from the diff heuristics.");
  if (suggestions.length === 0) suggestions.push("Keep the PR description tied to acceptance criteria so reviewers can validate it quickly.");

  const confidence = stats.totalChanged === 0 ? "Low" : stats.totalChanged > 1200 ? "Medium" : "High";
  const filePreview = files.slice(0, 6).join(", ") || "no files detected";
  const summary = [
    `This PR, "${title}", changes ${files.length} file${files.length === 1 ? "" : "s"} with ${stats.additions} additions and ${stats.deletions} deletions.`,
    `The touched surface includes ${filePreview}${files.length > 6 ? ", and more" : ""}.`
  ].join(" ");

  return { summary, risks, suggestions, confidence, stats, files };
}

export function renderMarkdown({ prUrl, analysis }) {
  return `## Claude PR Review

**PR:** ${prUrl}

### Summary
${analysis.summary}

### Identified Risks
${analysis.risks.map((risk) => `- ${risk}`).join("\n")}

### Improvement Suggestions
${analysis.suggestions.map((suggestion) => `- ${suggestion}`).join("\n")}

### Confidence Score
${analysis.confidence}
`;
}

async function review(prUrl) {
  const { owner, repo, pullNumber } = parsePullRequestUrl(prUrl);
  const pull = await githubJson(`/repos/${owner}/${repo}/pulls/${pullNumber}`);
  const diff = await githubText(`/repos/${owner}/${repo}/pulls/${pullNumber}`);
  const files = changedFilesFromDiff(diff);
  const analysis = analyzePullRequest({
    title: pull.title,
    body: pull.body || "",
    files,
    diff
  });
  return { prUrl, analysis };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log(usage());
    return;
  }
  if (args.version) {
    console.log(VERSION);
    return;
  }
  const result = await review(args.pr);
  if (args.output === "json") console.log(JSON.stringify(result, null, 2));
  else console.log(renderMarkdown(result));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(`claude-review: ${error.message}`);
    process.exit(1);
  });
}
