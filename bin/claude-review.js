#!/usr/bin/env node

const fs = require("node:fs/promises");
const path = require("node:path");
const { fetchPullRequest } = require("../src/github");
const {
  buildClaudePrompt,
  createHeuristicReview,
  runClaudeReview,
} = require("../src/review");
const { postIssueComment } = require("../src/comment");

function printHelp() {
  console.log(`Usage: claude-review --pr https://github.com/owner/repo/pull/123 [options]

Options:
  --mode auto|claude|heuristic  Review engine. Default: auto
  --out <file>                  Write Markdown output to a file
  --post-comment                Post the review as a GitHub PR comment
  --help                        Show this help

Environment:
  GITHUB_TOKEN                  Optional token for API limits and comments
  CLAUDE_REVIEW_COMMAND         Claude command. Default: claude
  CLAUDE_REVIEW_ARGS            Claude args before prompt. Default: -p
`);
}

function parseArgs(argv) {
  const options = { mode: "auto", postComment: false };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--help" || arg === "-h") {
      options.help = true;
    } else if (arg === "--pr") {
      options.pr = argv[++index];
    } else if (arg === "--mode") {
      options.mode = argv[++index];
    } else if (arg === "--out") {
      options.out = argv[++index];
    } else if (arg === "--post-comment") {
      options.postComment = true;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  if (!["auto", "claude", "heuristic"].includes(options.mode)) {
    throw new Error("--mode must be one of: auto, claude, heuristic");
  }
  return options;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    printHelp();
    return;
  }
  if (!options.pr) {
    throw new Error("Missing required --pr https://github.com/owner/repo/pull/123");
  }

  const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || "";
  const pr = await fetchPullRequest(options.pr, { token });
  const prompt = buildClaudePrompt(pr);

  let markdown;
  let engine = "heuristic";
  if (options.mode !== "heuristic") {
    const claudeResult = runClaudeReview(prompt);
    if (claudeResult.ok) {
      markdown = claudeResult.markdown;
      engine = "claude";
    } else if (options.mode === "claude") {
      throw new Error(claudeResult.error);
    }
  }

  if (!markdown) {
    markdown = createHeuristicReview(pr);
  }

  const footer = `\n\n---\nGenerated by claude-review (${engine} engine).`;
  const output = markdown.trimEnd() + footer + "\n";

  if (options.out) {
    const destination = path.resolve(options.out);
    await fs.mkdir(path.dirname(destination), { recursive: true });
    await fs.writeFile(destination, output, "utf8");
  }

  if (options.postComment) {
    if (!token) {
      throw new Error("--post-comment requires GITHUB_TOKEN or GH_TOKEN");
    }
    await postIssueComment(pr, output, { token });
  }

  process.stdout.write(output);
}

main().catch((error) => {
  console.error(`claude-review: ${error.message}`);
  process.exit(1);
});
