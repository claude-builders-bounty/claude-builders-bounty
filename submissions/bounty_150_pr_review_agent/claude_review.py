#!/usr/bin/env python3
"""
claude-review — A Claude Code sub-agent that reviews GitHub PRs and posts structured comments.

Usage:
    python claude_review.py --pr https://github.com/owner/repo/pull/123
    python claude_review.py --pr https://github.com/owner/repo/pull/123 --post-comment
    python claude_review.py --pr https://github.com/owner/repo/pull/123 --output json

Requirements:
    pip install anthropic requests python-dotenv

Environment variables (or .env file):
    ANTHROPIC_API_KEY  — your Anthropic API key
    GITHUB_TOKEN       — GitHub personal access token (required for private repos or posting comments)
"""

import argparse
import json
import os
import re
import sys
from dataclasses import dataclass, asdict

import anthropic
import requests
from dotenv import load_dotenv

load_dotenv()

# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------

@dataclass
class PRReviewResult:
    pr_url: str
    pr_title: str
    pr_number: int
    repo: str
    summary: str
    risks: list[str]
    suggestions: list[str]
    confidence: str  # Low | Medium | High
    raw_diff_lines: int

    def to_markdown(self) -> str:
        risks_md      = "\n".join(f"- {r}" for r in self.risks)      or "- None identified"
        suggestions_md = "\n".join(f"- {s}" for s in self.suggestions) or "- No suggestions"
        confidence_emoji = {"Low": "🟡", "Medium": "🟠", "High": "🟢"}.get(self.confidence, "⚪")

        return f"""## Claude Code PR Review

**PR:** [{self.pr_title}]({self.pr_url}) (`#{self.pr_number}`)
**Repo:** `{self.repo}`
**Diff size:** {self.raw_diff_lines} lines analyzed

---

### Summary
{self.summary}

---

### Identified Risks
{risks_md}

---

### Improvement Suggestions
{suggestions_md}

---

### Confidence Score
{confidence_emoji} **{self.confidence}**

<sub>Generated by [claude-review](https://github.com/guillaumemcf/claude-review) using `claude-sonnet-4-20250514`</sub>
"""


# ---------------------------------------------------------------------------
# GitHub helpers
# ---------------------------------------------------------------------------

def parse_pr_url(url: str) -> tuple[str, str, int]:
    """Returns (owner, repo, pr_number)."""
    m = re.match(r"https://github\.com/([^/]+)/([^/]+)/pull/(\d+)", url.rstrip("/"))
    if not m:
        raise ValueError(f"Invalid GitHub PR URL: {url!r}")
    return m.group(1), m.group(2), int(m.group(3))


def fetch_pr_metadata(owner: str, repo: str, pr_number: int, token: str | None) -> dict:
    headers = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr_number}"
    resp = requests.get(url, headers=headers, timeout=30)
    resp.raise_for_status()
    return resp.json()


def fetch_pr_diff(owner: str, repo: str, pr_number: int, token: str | None) -> str:
    headers = {"Accept": "application/vnd.github.diff", "X-GitHub-Api-Version": "2022-11-28"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr_number}"
    resp = requests.get(url, headers=headers, timeout=60)
    resp.raise_for_status()
    return resp.text


def post_github_comment(owner: str, repo: str, pr_number: int, body: str, token: str) -> str:
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    url = f"https://api.github.com/repos/{owner}/{repo}/issues/{pr_number}/comments"
    resp = requests.post(url, headers=headers, json={"body": body}, timeout=30)
    resp.raise_for_status()
    return resp.json().get("html_url", "")


# ---------------------------------------------------------------------------
# Claude analysis
# ---------------------------------------------------------------------------

SYSTEM_PROMPT = """You are a senior software engineer conducting a thorough code review.
Your job is to analyze a GitHub pull request diff and return a structured JSON review.

You must return ONLY valid JSON with exactly these keys:
{
  "summary": "<2-3 sentence summary of what this PR does and its overall quality>",
  "risks": ["<risk 1>", "<risk 2>", ...],
  "suggestions": ["<suggestion 1>", "<suggestion 2>", ...],
  "confidence": "<Low|Medium|High>"
}

Confidence scale:
- High:   diff is clean, well-tested, focused change
- Medium: some concerns but nothing critical
- Low:    significant risks, missing tests, or the diff is too large to fully assess

risks: concrete issues (security, correctness, performance, missing error handling)
suggestions: actionable improvements (not stylistic nitpicks)
Do not include markdown formatting inside the JSON strings."""


def truncate_diff(diff: str, max_chars: int = 60_000) -> str:
    """Truncate very large diffs to fit within context limits."""
    if len(diff) <= max_chars:
        return diff
    half = max_chars // 2
    return diff[:half] + "\n\n[... diff truncated for length ...]\n\n" + diff[-half:]


def analyze_pr_with_claude(
    diff: str,
    pr_title: str,
    pr_body: str,
    client: anthropic.Anthropic,
) -> dict:
    truncated = truncate_diff(diff)

    user_message = f"""Pull Request Title: {pr_title}

PR Description:
{pr_body or "(no description provided)"}

--- DIFF START ---
{truncated}
--- DIFF END ---

Review this PR and return structured JSON as instructed."""

    message = client.messages.create(
        model="claude-sonnet-4-20250514",
        max_tokens=1024,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": user_message}],
    )

    text = message.content[0].text.strip()

    # Strip markdown code fences if present
    if text.startswith("```"):
        text = re.sub(r"^```[a-z]*\n?", "", text)
        text = re.sub(r"\n?```$", "", text)

    return json.loads(text)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Claude Code sub-agent: reviews a GitHub PR and produces structured output."
    )
    parser.add_argument("--pr", required=True, help="GitHub PR URL")
    parser.add_argument(
        "--post-comment",
        action="store_true",
        help="Post the review as a comment on the PR (requires GITHUB_TOKEN)",
    )
    parser.add_argument(
        "--output",
        choices=["markdown", "json"],
        default="markdown",
        help="Output format (default: markdown)",
    )
    args = parser.parse_args()

    anthropic_key = os.environ.get("ANTHROPIC_API_KEY")
    github_token  = os.environ.get("GITHUB_TOKEN")

    if not anthropic_key:
        print("ERROR: ANTHROPIC_API_KEY environment variable is not set.", file=sys.stderr)
        sys.exit(1)

    client = anthropic.Anthropic(api_key=anthropic_key)

    print(f"Fetching PR: {args.pr}", file=sys.stderr)
    owner, repo, pr_number = parse_pr_url(args.pr)

    metadata = fetch_pr_metadata(owner, repo, pr_number, github_token)
    pr_title = metadata.get("title", "Untitled PR")
    pr_body  = metadata.get("body", "") or ""

    print(f"Fetching diff for PR #{pr_number}: {pr_title!r}", file=sys.stderr)
    diff = fetch_pr_diff(owner, repo, pr_number, github_token)
    diff_lines = diff.count("\n")

    print(f"Analyzing with Claude ({diff_lines} diff lines)...", file=sys.stderr)
    analysis = analyze_pr_with_claude(diff, pr_title, pr_body, client)

    result = PRReviewResult(
        pr_url=args.pr,
        pr_title=pr_title,
        pr_number=pr_number,
        repo=f"{owner}/{repo}",
        summary=analysis.get("summary", ""),
        risks=analysis.get("risks", []),
        suggestions=analysis.get("suggestions", []),
        confidence=analysis.get("confidence", "Medium"),
        raw_diff_lines=diff_lines,
    )

    if args.output == "json":
        print(json.dumps(asdict(result), indent=2))
    else:
        md = result.to_markdown()
        print(md)

        if args.post_comment:
            if not github_token:
                print("ERROR: --post-comment requires GITHUB_TOKEN.", file=sys.stderr)
                sys.exit(1)
            comment_url = post_github_comment(owner, repo, pr_number, md, github_token)
            print(f"\nComment posted: {comment_url}", file=sys.stderr)


if __name__ == "__main__":
    main()
