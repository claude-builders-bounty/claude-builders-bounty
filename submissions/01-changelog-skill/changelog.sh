#!/bin/bash
# changelog.sh — Generate a structured CHANGELOG.md from git history
set -euo pipefail

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

OUTPUT="${1:-CHANGELOG.md}"
SINCE=""

# Find the last tag for "since" reference
if git describe --tags --abbrev=0 2>/dev/null; then
  SINCE=$(git describe --tags --abbrev=0 2>/dev/null)
  echo -e "${BLUE}Generating changelog since tag: ${SINCE}${NC}"
else
  echo -e "${YELLOW}No tags found. Generating from first commit.${NC}"
  SINCE=$(git rev-list --max-parents=0 HEAD 2>/dev/null)
  if [ -z "$SINCE" ]; then
    echo -e "${RED}No commits found in this repository.${NC}"
    exit 1
  fi
fi

ADDED=()
FIXED=()
CHANGED=()
REMOVED=()

while IFS= read -r line; do
  hash=$(echo "$line" | cut -d' ' -f1)
  msg=$(echo "$line" | cut -d' ' -f2-)
  short_hash="${hash:0:7}"

  # Extract type (first word before : or ()
  type=$(echo "$msg" | sed -n 's/^\([a-zA-Z]*\).*/\1/p')
  type_lower=$(echo "$type" | tr '[:upper:]' '[:lower:]')
  
  # Extract description after "type:" or "type(scope):"
  description=$(echo "$msg" | sed -E 's/^[a-zA-Z]+(\([^)]*\))?:\s*//')
  
  # Fallback: if no colon, use the whole message
  if [ "$description" = "$msg" ]; then
    description="$msg"
  fi

  entry="- ${description} (${short_hash})"

  case "$type_lower" in
    feat|feature)
      ADDED+=("$entry")
      ;;
    fix|bugfix|hotfix|bug)
      FIXED+=("$entry")
      ;;
    breaking|break|major)
      CHANGED+=("$entry [BREAKING]")
      ;;
    remove|deprecate|revert|delete|drop)
      REMOVED+=("$entry")
      ;;
    chore|refactor|docs|style|perf|build|ci|test|update)
      CHANGED+=("$entry")
      ;;
    add|create|implement|new|support|introduce|enable)
      ADDED+=("$entry")
      ;;
    *)
      # Uncategorized: infer from first word of description
      first_word=$(echo "$description" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z].*//')
      case "$first_word" in
        add|create|implement|new|support|introduce|enable|allow)
          ADDED+=("$entry") ;;
        fix|correct|resolve|patch|prevent|handle|ensure)
          FIXED+=("$entry") ;;
        remove|delete|drop|deprecat|revert|cleanup)
          REMOVED+=("$entry") ;;
        *)
          CHANGED+=("$entry") ;;
      esac
      ;;
  esac
done < <(git log "${SINCE}..HEAD" --format="%H %s" 2>/dev/null || true)

{
  echo "# Changelog"
  echo ""
  echo "## [Unreleased]"
  echo ""

  if [ ${#ADDED[@]} -gt 0 ]; then
    echo "### Added"
    echo ""
    for entry in "${ADDED[@]}"; do echo "$entry"; done
    echo ""
  fi

  if [ ${#FIXED[@]} -gt 0 ]; then
    echo "### Fixed"
    echo ""
    for entry in "${FIXED[@]}"; do echo "$entry"; done
    echo ""
  fi

  if [ ${#CHANGED[@]} -gt 0 ]; then
    echo "### Changed"
    echo ""
    for entry in "${CHANGED[@]}"; do echo "$entry"; done
    echo ""
  fi

  if [ ${#REMOVED[@]} -gt 0 ]; then
    echo "### Removed"
    echo ""
    for entry in "${REMOVED[@]}"; do echo "$entry"; done
    echo ""
  fi

  total=$(( ${#ADDED[@]} + ${#FIXED[@]} + ${#CHANGED[@]} + ${#REMOVED[@]} ))
  echo "---"
  echo "_Generated by changelog.sh - ${total} commits since ${SINCE}_"
} > "$OUTPUT"

echo -e "${GREEN}Changelog generated: ${OUTPUT}${NC}"
echo -e "${BLUE}${#ADDED[@]} added | ${#FIXED[@]} fixed | ${#CHANGED[@]} changed | ${#REMOVED[@]} removed${NC}"
