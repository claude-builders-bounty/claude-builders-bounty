// =========================================================================
// 🎨 FORMAT MULTI-CHANNEL DELIVERY PAYLOADS
// =========================================================================

const prev = $('Aggregate Activity Digest').first().json;
const claudeResp = $input.first()?.json || {};

// Extract generated text from Claude Messages API response
let summaryText = '';
if (claudeResp.content && Array.isArray(claudeResp.content)) {
  summaryText = claudeResp.content.map(b => b.text || '').join('\n').trim();
} else if (typeof claudeResp === 'string') {
  summaryText = claudeResp;
} else if (claudeResp.error) {
  summaryText = `⚠️ Claude API Notice: ${claudeResp.error.message || JSON.stringify(claudeResp.error)}`;
}

if (!summaryText) {
  summaryText = `### Weekly Dev Summary for ${prev.repoFullName}\n\n**Activity Highlights (${prev.sinceFormatted} - ${prev.untilFormatted}):**\n- Merged PRs: ${prev.stats.totalMergedPRs}\n- Closed Issues: ${prev.stats.totalClosedIssues}\n- Commits: ${prev.stats.totalCommits}\n\n*(Claude API Key was not provided or returned empty content)*`;
}

const title = prev.language === 'FR'
  ? `📦 Synthèse Hebdomadaire Dev — ${prev.repoFullName}`
  : `📦 Weekly Dev Summary — ${prev.repoFullName}`;

const subtitle = `📅 ${prev.sinceFormatted} → ${prev.untilFormatted} | 🔀 ${prev.stats.totalMergedPRs} PRs | 🎯 ${prev.stats.totalClosedIssues} Issues | 💻 ${prev.stats.totalCommits} Commits`;

// 1. Build Discord Embed Payload (with character limits safety)
const discordDescription = summaryText.length > 3900
  ? summaryText.substring(0, 3900) + '...\n\n*(Truncated due to Discord 4096-character limit)*'
  : summaryText;

const discordPayload = {
  embeds: [
    {
      title: title,
      description: discordDescription,
      color: 0x6366F1, // Indigo / Claude brand accent
      fields: [
        { name: 'Merged PRs', value: String(prev.stats.totalMergedPRs), inline: true },
        { name: 'Closed Issues', value: String(prev.stats.totalClosedIssues), inline: true },
        { name: 'Commits', value: String(prev.stats.totalCommits), inline: true }
      ],
      footer: {
        text: `Generated by Claude (${prev.claudeModel}) via n8n`
      },
      timestamp: new Date().toISOString()
    }
  ]
};

// 2. Build Slack Block Kit Payload
const slackPayload = {
  blocks: [
    {
      type: "header",
      text: {
        type: "plain_text",
        text: title,
        emoji: true
      }
    },
    {
      type: "context",
      elements: [
        {
          type: "mrkdwn",
          text: subtitle
        }
      ]
    },
    {
      type: "divider"
    },
    {
      type: "section",
      text: {
        type: "mrkdwn",
        text: summaryText.length > 2900 ? summaryText.substring(0, 2900) + '...' : summaryText
      }
    },
    {
      type: "divider"
    },
    {
      type: "context",
      elements: [
        {
          type: "mrkdwn",
          text: `*Generated by Claude (${prev.claudeModel}) via n8n* | Model: \`${prev.claudeModel}\``
        }
      ]
    }
  ]
};

// Determine channel activation
const ch = prev.deliveryChannel;
const discordActive = (ch === 'discord' || ch === 'both' || ch === 'all') && Boolean(prev.discordWebhookUrl);
const slackActive = (ch === 'slack' || ch === 'both' || ch === 'all') && Boolean(prev.slackWebhookUrl);

return [{
  json: {
    ...prev,
    title,
    subtitle,
    summaryMarkdown: summaryText,
    discordPayload,
    slackPayload,
    discordActive,
    slackActive
  }
}];
