#!/usr/bin/env python3
"""
claude-review — AI-powered PR reviewer using Claude API.

Usage:
    python claude-review.py https://github.com/owner/repo/pull/123
    python claude-review.py owner/repo 123
    python claude-review.py --diff file.diff

Outputs structured Markdown review with:
- Summary (2-3 sentences)
- Risks identified
- Improvement suggestions
- Confidence score (Low/Medium/High)

Requires: ANTHROPIC_API_KEY environment variable
          pip install anthropic
"""

import sys
import os
import re
import json
import subprocess
import argparse
from pathlib import Path

try:
    from anthropic import Anthropic
except ImportError:
    print("Error: pip install anthropic")
    sys.exit(1)


def parse_pr_url(url_or_args):
    """Parse PR URL or owner/repo + number into components."""
    # Full URL: https://github.com/owner/repo/pull/123
    m = re.match(r"https?://github\.com/([^/]+)/([^/]+)/pull/(\d+)", url_or_args)
    if m:
        return m.group(1), m.group(2), int(m.group(3))
    # Short: owner/repo
    m = re.match(r"([^/]+)/([^/]+)", url_or_args)
    if m:
        return m.group(1), m.group(2), None
    return None, None, None


def fetch_pr_data(owner, repo, pr_number):
    """Fetch PR metadata and diff using gh CLI."""
    try:
        # Get PR info
        info_cmd = f"gh pr view {pr_number} --repo {owner}/{repo} --json title,body,files,additions,deletions,changedFiles,author,baseRefName,headRefName"
        info = json.loads(subprocess.check_output(info_cmd, shell=True, text=True))

        # Get diff
        diff_cmd = f"gh pr diff {pr_number} --repo {owner}/{repo}"
        diff = subprocess.check_output(diff_cmd, shell=True, text=True)

        return info, diff
    except subprocess.CalledProcessError as e:
        print(f"Error fetching PR: {e}")
        print("Make sure 'gh' CLI is installed and authenticated: gh auth login")
        sys.exit(1)


def review_pr(pr_info, diff, model="claude-sonnet-4-20250514"):
    """Send PR diff to Claude for review."""
    client = Anthropic()

    # Truncate diff if too long (keep first 15000 chars)
    if len(diff) > 15000:
        diff = diff[:15000] + "\n\n... [diff truncated — showing first 15000 chars] ..."

    system_prompt = """You are an expert code reviewer. You review pull requests with a focus on:
- Code correctness and potential bugs
- Security vulnerabilities (injection, XSS, secrets, auth issues)
- Performance implications
- Code style and maintainability
- Test coverage gaps

Your output MUST follow this exact Markdown structure:

## Summary
[2-3 sentences describing what this PR does and its overall quality]

## Risks
[Bulleted list of identified risks. If none, say "No significant risks identified."]

## Suggestions
[Bulleted list of improvement suggestions with specific file:line references when possible]

## Confidence
[One of: **Low** / **Medium** / **High** with a brief justification]

Be constructive and specific. Reference exact file names and line numbers from the diff."""

    title = pr_info.get("title", "Unknown")
    body = (pr_info.get("body") or "No description provided.")[:2000]
    author = pr_info.get("author", {}).get("login", "unknown")
    base = pr_info.get("baseRefName", "main")
    head = pr_info.get("headRefName", "unknown")
    additions = pr_info.get("additions", 0)
    deletions = pr_info.get("deletions", 0)
    files_changed = pr_info.get("changedFiles", 0)
    files = pr_info.get("files", [])
    file_list = "\n".join(f"  - {f.get('path', '?')} (+{f.get('additions', 0)}, -{f.get('deletions', 0)})" for f in files[:30])

    user_prompt = f"""Review this pull request:

**Title:** {title}
**Author:** {author}
**Branch:** {head} → {base}
**Stats:** {files_changed} files changed, +{additions} additions, -{deletions} deletions

**Files changed:**
{file_list}

**PR Description:**
{body}

**Diff:**
```diff
{diff}
```

Provide your review in the structured Markdown format specified."""

    response = client.messages.create(
        model=model,
        max_tokens=4096,
        system=system_prompt,
        messages=[{"role": "user", "content": user_prompt}],
    )

    return response.content[0].text


def format_output(review_text, pr_info, pr_number, owner, repo):
    """Format the final review output."""
    title = pr_info.get("title", "Unknown")
    author = pr_info.get("author", {}).get("login", "unknown")
    url = f"https://github.com/{owner}/{repo}/pull/{pr_number}"

    output = f"""# PR Review: {title}

> **PR:** [{owner}/{repo}#{pr_number}]({url})
> **Author:** @{author}
> **Reviewed by:** claude-review (AI-powered)

---

{review_text}

---

_Generated by [claude-review](https://github.com/xamdkx/claude-builders-bounty) using Claude Sonnet._
"""
    return output


def main():
    parser = argparse.ArgumentParser(description="AI-powered PR reviewer using Claude")
    parser.add_argument("pr_url", nargs="?", help="GitHub PR URL (https://github.com/owner/repo/pull/123)")
    parser.add_argument("pr_number", nargs="?", type=int, help="PR number (when using owner/repo format)")
    parser.add_argument("--diff", help="Path to a diff file (instead of fetching from GitHub)")
    parser.add_argument("--model", default="claude-sonnet-4-20250514", help="Claude model to use")
    parser.add_argument("--output", "-o", help="Save review to file")
    parser.add_argument("--post", action="store_true", help="Post review as a PR comment on GitHub")
    args = parser.parse_args()

    if not os.environ.get("ANTHROPIC_API_KEY"):
        print("Error: Set ANTHROPIC_API_KEY environment variable")
        print("  export ANTHROPIC_API_KEY=sk-ant-...")
        sys.exit(1)

    # Handle diff file mode
    if args.diff:
        diff = Path(args.diff).read_text(encoding="utf-8")
        pr_info = {"title": f"Review of {args.diff}", "body": "", "author": {"login": "local"},
                   "additions": 0, "deletions": 0, "changedFiles": 0, "files": []}
        review = review_pr(pr_info, diff, args.model)
        print(review)
        return

    # Parse PR URL
    if not args.pr_url:
        parser.print_help()
        sys.exit(1)

    owner, repo, pr_number = parse_pr_url(args.pr_url)
    if args.pr_number:
        pr_number = args.pr_number

    if not owner or not repo or not pr_number:
        print(f"Could not parse PR URL: {args.pr_url}")
        print("Expected format: https://github.com/owner/repo/pull/123 or owner/repo 123")
        sys.exit(1)

    print(f"Fetching PR #{pr_number} from {owner}/{repo}...")
    pr_info, diff = fetch_pr_data(owner, repo, pr_number)

    print(f"Reviewing ({pr_info.get('changedFiles', '?')} files, +{pr_info.get('additions', '?')}/-{pr_info.get('deletions', '?')})...")
    review = review_pr(pr_info, diff, args.model)

    output = format_output(review, pr_info, pr_number, owner, repo)

    # Output
    print("\n" + output)

    # Save to file
    if args.output:
        Path(args.output).write_text(output, encoding="utf-8")
        print(f"\nSaved to {args.output}")

    # Post as PR comment
    if args.post:
        try:
            comment_cmd = f'gh pr comment {pr_number} --repo {owner}/{repo} --body "{review}"'
            subprocess.run(comment_cmd, shell=True, check=True)
            print(f"\nPosted review as comment on PR #{pr_number}")
        except subprocess.CalledProcessError:
            print("\nFailed to post comment. Make sure gh CLI has permissions.")


if __name__ == "__main__":
    main()
