#!/usr/bin/env bash
# changelog.sh — Structured CHANGELOG generator from git history
# Usage: bash changelog.sh [since_tag] [output_file]
# Default: since last git tag → CHANGELOG.md

set -eo pipefail

OUTPUT="${2:-CHANGELOG.md}"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$(git rev-parse --show-toplevel 2>/dev/null || echo "$SCRIPT_DIR")"

SINCE_TAG="${1:-}"
if [ -z "$SINCE_TAG" ]; then
  SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo '')
fi

echo "# Changelog" > "$OUTPUT"
echo "" >> "$OUTPUT"

LATEST_TAG=$(git tag --sort=-creatordate 2>/dev/null | head -1)
if [ -n "$LATEST_TAG" ]; then
  echo "## $LATEST_TAG ($(date +%Y-%m-%d))" >> "$OUTPUT"
else
  echo "## Unreleased ($(date +%Y-%m-%d))" >> "$OUTPUT"
fi
echo "" >> "$OUTPUT"

# Fetch commits
if [ -n "$SINCE_TAG" ]; then
  echo "> Generated from commits since \`$SINCE_TAG\`" >> "$OUTPUT"
  COMMITS=$(git log "$SINCE_TAG"..HEAD --pretty=format:"%s" 2>/dev/null)
else
  echo "> Generated from all commits" >> "$OUTPUT"
  COMMITS=$(git log --pretty=format:"%s")
fi
[ -z "$COMMITS" ] && COMMITS=""
echo "" >> "$OUTPUT"

# Categorization
ADDED=""
FIXED=""
CHANGED=""
REMOVED=""
OTHER=""
ac=0; fc=0; cc=0; rc=0; oc=0

while IFS= read -r line; do
  [ -z "$line" ] && continue
  msg_lower=$(echo "$line" | tr '[:upper:]' '[:lower:]')
  
  # Conventional commit: type: message
  if echo "$msg_lower" | grep -qE "^(add|feat|new|create|implement|introduce)"; then
    ADDED="$ADDED- $(echo "$line" | sed -E 's/^[a-z]+(\([^)]*\))?:\s*//')\n"
    ac=$((ac + 1))
  elif echo "$msg_lower" | grep -qE "^(fix|bug|resolve|patch|hotfix|repair)"; then
    FIXED="$FIXED- $(echo "$line" | sed -E 's/^[a-z]+(\([^)]*\))?:\s*//')\n"
    fc=$((fc + 1))
  elif echo "$msg_lower" | grep -qE "^(change|update|modify|refactor|improve|enhance|tweak|adjust|upgrade)"; then
    CHANGED="$CHANGED- $(echo "$line" | sed -E 's/^[a-z]+(\([^)]*\))?:\s*//')\n"
    cc=$((cc + 1))
  elif echo "$msg_lower" | grep -qE "^(remove|delete|drop|deprecate|retire)"; then
    REMOVED="$REMOVED- $(echo "$line" | sed -E 's/^[a-z]+(\([^)]*\))?:\s*//')\n"
    rc=$((rc + 1))
  else
    OTHER="$OTHER- $line\n"
    oc=$((oc + 1))
  fi
done <<< "$COMMITS"

# Write sections
if [ "$ac" -gt 0 ]; then
  echo "### Added" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
  printf "%b" "$ADDED" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
fi

if [ "$fc" -gt 0 ]; then
  echo "### Fixed" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
  printf "%b" "$FIXED" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
fi

if [ "$cc" -gt 0 ]; then
  echo "### Changed" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
  printf "%b" "$CHANGED" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
fi

if [ "$rc" -gt 0 ]; then
  echo "### Removed" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
  printf "%b" "$REMOVED" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
fi

if [ "$oc" -gt 0 ]; then
  echo "### Other" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
  printf "%b" "$OTHER" >> "$OUTPUT"
  echo "" >> "$OUTPUT"
fi

echo "---" >> "$OUTPUT"
echo "" >> "$OUTPUT"
echo "*Generated by [changelog.sh](https://github.com/claude-builders-bounty/claude-builders-bounty) on $(date -u +"%Y-%m-%dT%H:%M:%SZ")*" >> "$OUTPUT"

TOTAL=$((ac + fc + cc + rc + oc))
echo "✅ CHANGELOG written to $OUTPUT"
echo "   $TOTAL commits categorized"
echo "   Added: $ac | Fixed: $fc | Changed: $cc | Removed: $rc | Other: $oc"
