#!/usr/bin/env bash
# =============================================================================
# generate-changelog.sh
# Claude Code Skill: Generate structured CHANGELOG.md from git history
# Bounty: #1 - $50
# =============================================================================
set -euo pipefail

# ── Config ──────────────────────────────────────────────────────────────────────
OUTPUT_FILE="${1:-CHANGELOG.md}"
LAST_TAG="${2:-$(git describe --tags --abbrev=0 2>/dev/null || echo "")}"

# ── Help ────────────────────────────────────────────────────────────────────────
if [[ "${1:-}" == "--help" ]] || [[ "${1:-}" == "-h" ]]; then
  cat <<'HELP'
Usage: ./generate-changelog.sh [output_file] [tag]

Generate a structured CHANGELOG.md from git history.

Arguments:
  output_file   Output file path (default: CHANGELOG.md)
  tag           Git tag to start from (default: latest tag)

Output sections:
  🚀 Added       New features
  🐛 Fixed       Bug fixes
  🔧 Changed     Modifications and refactors
  🗑️ Removed     Deprecations and deletions

Examples:
  ./generate-changelog.sh                     # Generate from latest tag
  ./generate-changelog.md CHANGELOG.md v1.0.0  # From specific tag
HELP
  exit 0
fi

# ── Generate Changelog ──────────────────────────────────────────────────────────
echo "📝 Generating changelog..."
echo "   Output: $OUTPUT_FILE"
echo "   From:   ${LAST_TAG:-beginning of history}"
echo ""

# Detect if we're in a git repo
if ! git rev-parse --git-dir > /dev/null 2>&1; then
  echo "❌ Error: Not in a git repository"
  exit 1
fi

# Build the range argument
RANGE=""
if [[ -n "$LAST_TAG" ]]; then
  RANGE="${LAST_TAG}..HEAD"
fi

# Categorize commits
ADDED=$(git log "$RANGE" --grep="^feat" --pretty=format:"- %s (%h)" --no-merges 2>/dev/null || echo "")
FIXED=$(git log "$RANGE" --grep="^fix" --pretty=format:"- %s (%h)" --no-merges 2>/dev/null || echo "")
CHANGED=$(git log "$RANGE" --grep="^(refactor|perf|style|chore|ci|build|deps)" --pretty=format:"- %s (%h)" --no-merges -P 2>/dev/null || echo "")
REMOVED=$(git log "$RANGE" --grep="^remove" --pretty=format:"- %s (%h)" --no-merges 2>/dev/null || echo "")
DOCS=$(git log "$RANGE" --grep="^docs" --pretty=format:"- %s (%h)" --no-merges 2>/dev/null || echo "")
TESTS=$(git log "$RANGE" --grep="^test" --pretty=format:"- %s (%h)" --no-merges 2>/dev/null || echo "")

# Get version info
VERSION="${LAST_TAG:-$(git rev-parse --short HEAD)}"
DATE=$(date +%Y-%m-%d)
PROJECT=$(basename "$(git rev-parse --show-toplevel)" 2>/dev/null || echo "project")

# ── Write CHANGELOG.md ──────────────────────────────────────────────────────────
cat > "$OUTPUT_FILE" <<CHANGELOG
# Changelog

## [${VERSION}] - ${DATE}

### 🚀 Added
${ADDED:-_No new features in this release._}

### 🐛 Fixed
${FIXED:-_No bug fixes in this release._}

### 🔧 Changed
${CHANGED:-_No changes in this release._}
${DOCS:+
### 📚 Documentation
${DOCS}}
${TESTS:+
### 🧪 Testing
${TESTS}}

### 🗑️ Removed
${REMOVED:-_No removals in this release._}

---

*Generated by [changelog-skill](https://github.com/claude-builders-bounty/claude-builders-bounty/issues/1)*
CHANGELOG

echo "✅ Changelog written to $OUTPUT_FILE"
echo ""
echo "📊 Stats:"
echo "   Added:    $(echo "$ADDED" | grep -c . || true)"
echo "   Fixed:    $(echo "$FIXED" | grep -c . || true)"
echo "   Changed:  $(echo "$CHANGED" | grep -c . || true)"
echo "   Removed:  $(echo "$REMOVED" | grep -c . || true)"
