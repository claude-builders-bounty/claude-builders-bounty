#!/usr/bin/env bash
set -euo pipefail

# ── CHANGELOG Generator ─────────────────────────────────────────────
# Generates CHANGELOG.md from git history since the last tag.
# Usage: bash changelog.sh [--output FILE] [--tag TAG]
# ─────────────────────────────────────────────────────────────────────

OUTPUT="${OUTPUT:-CHANGELOG.md}"
SINCE_TAG="${SINCE_TAG:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --output) OUTPUT="$2"; shift 2 ;;
    --tag)    SINCE_TAG="$2"; shift 2 ;;
    -h|--help)
      echo "Usage: $0 [--output FILE] [--tag TAG]"
      echo "  --output FILE   Output file (default: CHANGELOG.md)"
      echo "  --tag TAG       Base tag to compare from (default: latest tag)"
      exit 0 ;;
    *) shift ;;
  esac
done

# ── Determine base tag ──────────────────────────────────────────────
if [[ -z "$SINCE_TAG" ]]; then
  SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || echo "")
fi

if [[ -z "$SINCE_TAG" ]]; then
  echo "⚠️  No git tags found. Generating from all commits."
  RANGE=""
else
  echo "📌 Base tag: $SINCE_TAG"
  RANGE="$SINCE_TAG..HEAD"
fi

# ── Fetch commits ───────────────────────────────────────────────────
COMMITS=$(git log "$RANGE" --no-merges --pretty=format:"%s" 2>/dev/null || git log --no-merges --pretty=format:"%s")

if [[ -z "$COMMITS" ]]; then
  echo "⚠️  No commits found since $SINCE_TAG."
  exit 0
fi

# ── Categorize ──────────────────────────────────────────────────────
declare -a ADDED=()
declare -a FIXED=()
declare -a CHANGED=()
declare -a REMOVED=()

while IFS= read -r line; do
  [[ -z "$line" ]] && continue

  # Strip conventional commit prefix if present
  msg="${line#*: }"
  [[ "$msg" == "$line" ]] && msg="$line"

  if   echo "$line" | grep -qiE '^(feat|add|new|introduce|create)';   then ADDED+=("$msg")
  elif echo "$line" | grep -qiE '^(fix|bug|resolve|patch|hotfix)';     then FIXED+=("$msg")
  elif echo "$line" | grep -qiE '^(remove|drop|delete|deprecate)';     then REMOVED+=("$msg")
  else CHANGED+=("$msg")
  fi
done <<< "$COMMITS"

# ── Generate output ─────────────────────────────────────────────────
VERSION="${SINCE_TAG:-HEAD}"
TODAY=$(date +%Y-%m-%d)

{
  echo "# Changelog"
  echo ""
  echo "## [$VERSION → HEAD] — $TODAY"
  echo ""

  section() {
    local title="$1"
    shift
    local -a items=("$@")
    [[ ${#items[@]} -eq 0 ]] && return
    echo "### $title"
    echo ""
    for item in "${items[@]}"; do
      echo "- $item"
    done
    echo ""
  }

  section "Added"   "${ADDED[@]}"
  section "Fixed"   "${FIXED[@]}"
  section "Changed" "${CHANGED[@]}"
  section "Removed" "${REMOVED[@]}"

  echo "---"
  echo "Generated by changelog.sh • $(date)"
} > "$OUTPUT"

# ── Summary ─────────────────────────────────────────────────────────
echo ""
echo "✅ CHANGELOG written to $OUTPUT"
echo "   Added:   ${#ADDED[@]}"
echo "   Fixed:   ${#FIXED[@]}"
echo "   Changed: ${#CHANGED[@]}"
echo "   Removed: ${#REMOVED[@]}"
