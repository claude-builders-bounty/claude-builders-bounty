#!/usr/bin/env bash
set -euo pipefail

# changelog.sh — Generate structured CHANGELOG.md from git history

OUTPUT="${1:-CHANGELOG.md}"
REPO_DIR="${2:-.}"

cd "$REPO_DIR"

if ! git rev-parse --git-dir > /dev/null 2>&1; then
  echo "Error: not a git repository"
  exit 1
fi

LAST_TAG=$(git tag --sort=-version:refname 2>/dev/null | head -1 || true)

if [[ -z "$LAST_TAG" ]]; then
  SCOPE="HEAD"
  SINCE_MSG="initial commit"
  COMMITS=$(git log --oneline HEAD 2>/dev/null)
else
  SCOPE="$LAST_TAG..HEAD"
  SINCE_MSG="$LAST_TAG"
  COMMITS=$(git log --oneline "$SCOPE" 2>/dev/null)
fi

if [[ -z "$COMMITS" ]]; then
  echo "No new commits since $SINCE_MSG"
  exit 0
fi

VERSION=""
if [[ -n "$LAST_TAG" ]]; then
  VERSION="$LAST_TAG"
else
  VERSION="0.1.0"
fi

DATE=$(date '+%Y-%m-%d')

ADDED=()
FIXED=()
CHANGED=()
REMOVED=()

while IFS= read -r line; do
  SHA=$(echo "$line" | awk '{print $1}')
  MSG=$(echo "$line" | cut -d' ' -f2-)

  CAT=$(echo "$MSG" | awk -F'[(:]' '{print $1}' | tr -d ' ')

  case "$CAT" in
    feat|feature|add|new|implement)
      BODY=$(echo "$MSG" | sed -E 's/^[^:]*: *//')
      ADDED+=("$BODY") ;;
    fix|bugfix|bug|hotfix|correct)
      BODY=$(echo "$MSG" | sed -E 's/^[^:]*: *//')
      FIXED+=("$BODY") ;;
    change|update|refactor|perf|improve)
      BODY=$(echo "$MSG" | sed -E 's/^[^:]*: *//')
      CHANGED+=("$BODY") ;;
    remove|deprecate|delete|drop)
      BODY=$(echo "$MSG" | sed -E 's/^[^:]*: *//')
      REMOVED+=("$BODY") ;;
    *)
      BODY=$(echo "$MSG" | sed -E 's/^[^:]*: *//')
      case "$MSG" in
        [Ff]ix*|[Hh]otfix*) FIXED+=("$BODY") ;;
        [Rr]emove*|[Dd]eprecat*) REMOVED+=("$BODY") ;;
        [Uu]pdate*|[Rr]efactor*|[Cc]hange*) CHANGED+=("$BODY") ;;
        *) ADDED+=("$MSG") ;;
      esac ;;
  esac
done <<< "$COMMITS"

{
  echo "# Changelog"
  echo ""
  echo "## [$VERSION] - $DATE"
  echo ""

  if [[ ${#ADDED[@]} -gt 0 ]]; then
    echo "### Added"
    for item in "${ADDED[@]}"; do
      echo "- $item"
    done
    echo ""
  fi

  if [[ ${#FIXED[@]} -gt 0 ]]; then
    echo "### Fixed"
    for item in "${FIXED[@]}"; do
      echo "- $item"
    done
    echo ""
  fi

  if [[ ${#CHANGED[@]} -gt 0 ]]; then
    echo "### Changed"
    for item in "${CHANGED[@]}"; do
      echo "- $item"
    done
    echo ""
  fi

  if [[ ${#REMOVED[@]} -gt 0 ]]; then
    echo "### Removed"
    for item in "${REMOVED[@]}"; do
      echo "- $item"
    done
    echo ""
  fi

  echo "---"
  echo "*Generated by changelog.sh on $DATE*"
} > "$OUTPUT"

echo "✅ CHANGELOG.md generated ($(echo "$COMMITS" | wc -l) commits since $SINCE_MSG)"
