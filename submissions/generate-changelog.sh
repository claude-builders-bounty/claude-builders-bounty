#!/usr/bin/env bash
# generate-changelog.sh — Generate CHANGELOG.md from git history
# Usage: bash generate-changelog.sh [--tag TAG] [--repo PATH]
set -euo pipefail

REPO="${2:-.}"
SINCE_TAG=""

# Parse args
while [[ $# -gt 0 ]]; do
  case "$1" in
    --tag) SINCE_TAG="$2"; shift 2 ;;
    --repo) REPO="$2"; shift 2 ;;
    *) echo "Usage: $0 [--tag TAG] [--repo PATH]"; exit 1 ;;
  esac
done

cd "$REPO"

# Determine the last tag for "since" reference
if [[ -z "$SINCE_TAG" ]]; then
  SINCE_TAG=$(git describe --tags --abbrev=0 2>/dev/null || git rev-list --max-parents=0 HEAD)
fi

echo "# Changelog"
echo ""
echo "## [Unreleased] — $(date +%Y-%m-%d)"
echo ""

# Categorize commits
categories() {
  local label="$1" pattern="$2"
  local commits
  commits=$(git log "$SINCE_TAG..HEAD" --oneline --grep="$pattern" 2>/dev/null)
  if [[ -n "$commits" ]]; then
    echo "### $label"
    echo "$commits" | sed 's/^/- /' | sed 's/^-[[:space:]]*\([a-f0-9]\{7,\}\)[[:space:]]*/- \1 /'
    echo ""
  fi
}

categories "Added" "^feat\|^feature\|^add\|^implement"
categories "Fixed" "^fix\|^bugfix\|^hotfix\|^patch"
categories "Changed" "^refactor\|^update\|^improve\|^change\|^chore"
categories "Removed" "^remove\|^delete\|^deprecate\|^drop"
categories "Documentation" "^docs\|^doc\|^readme"
categories "Security" "^security\|^vuln\|^cve"

# Remaining uncategorized commits
local remaining
remaining=$(git log "$SINCE_TAG..HEAD" --oneline --not \
  --grep="^feat\|^fix\|^refactor\|^docs\|^chore\|^remove\|^security\|^add\|^test" 2>/dev/null)
if [[ -n "$remaining" ]]; then
  echo "### Other"
  echo "$remaining" | sed 's/^/- /' | sed 's/^-[[:space:]]*\([a-f0-9]\{7,\}\)[[:space:]]*/- \1 /'
  echo ""
fi

echo "---"
echo "_Generated by generate-changelog.sh from ${SINCE_TAG} to HEAD_"
