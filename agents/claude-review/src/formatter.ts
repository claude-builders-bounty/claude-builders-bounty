import { ReviewResult } from './reviewer';
import { PRInfo } from './github';

export function formatReviewAsMarkdown(prInfo: PRInfo, review: ReviewResult): string {
  const now = new Date().toISOString();
  const filesList = prInfo.files.map(f => 
    `| \`${f.filename}\` | ${f.status} | +${f.additions}/-${f.deletions} |`
  ).join('\n');

  const risksList = review.risks.map(r => `- ${r}`).join('\n');
  const suggestionsList = review.suggestions.map(s => `- ${s}`).join('\n');

  const confidenceEmoji = {
    'Low': '⚠️',
    'Medium': '📊',
    'High': '✅'
  }[review.confidence];

  return `## 🤖 Claude Code Review

> **PR**: [#${prInfo.number}](https://github.com/${prInfo.owner}/${prInfo.repo}/pull/${prInfo.number}) - ${prInfo.title}
> **Author**: @${prInfo.author}
> **Branch**: \`${prInfo.headBranch}\` → \`${prInfo.baseBranch}\`
> **Reviewed**: ${now}

---

### 📋 Summary

${review.summary}

---

### ⚠️ Identified Risks

${risksList}

---

### 💡 Improvement Suggestions

${suggestionsList}

---

### ${confidenceEmoji} Confidence: ${review.confidence}

---

<details>
<summary>📁 Files Changed (${prInfo.files.length})</summary>

| File | Status | Changes |
|------|--------|---------|
${filesList}

</details>

---

*This review was generated by [claude-review](https://github.com/claude-builders-bounty/claude-review) - an AI-powered PR review tool powered by Claude.*
`;
}

export function formatReviewAsComment(prInfo: PRInfo, review: ReviewResult): string {
  // Shorter format suitable for GitHub PR comment
  const risksList = review.risks.map(r => `- ${r}`).join('\n');
  const suggestionsList = review.suggestions.map(s => `- ${s}`).join('\n');

  const confidenceEmoji = {
    'Low': '⚠️',
    'Medium': '📊',
    'High': '✅'
  }[review.confidence];

  return `## 🤖 Claude Code Review

### 📋 Summary
${review.summary}

### ⚠️ Risks
${risksList}

### 💡 Suggestions
${suggestionsList}

### ${confidenceEmoji} Confidence: **${review.confidence}**

---
*Powered by [claude-review](https://github.com/claude-builders-bounty/claude-review)*`;
}

export function printReviewToConsole(prInfo: PRInfo, review: ReviewResult): void {
  console.log('\n' + '='.repeat(60));
  console.log('🤖 CLAUDE CODE REVIEW');
  console.log('='.repeat(60));
  console.log(`\nPR #${prInfo.number}: ${prInfo.title}`);
  console.log(`Author: @${prInfo.author}`);
  console.log(`Branch: ${prInfo.headBranch} → ${prInfo.baseBranch}`);
  console.log(`Files: ${prInfo.files.length} changed`);
  
  console.log('\n' + '-'.repeat(60));
  console.log('📋 SUMMARY');
  console.log('-'.repeat(60));
  console.log(review.summary);

  console.log('\n' + '-'.repeat(60));
  console.log('⚠️  RISKS');
  console.log('-'.repeat(60));
  review.risks.forEach(r => console.log(`  • ${r}`));

  console.log('\n' + '-'.repeat(60));
  console.log('💡 SUGGESTIONS');
  console.log('-'.repeat(60));
  review.suggestions.forEach(s => console.log(`  • ${s}`));

  console.log('\n' + '-'.repeat(60));
  console.log(`${review.confidence === 'High' ? '✅' : review.confidence === 'Low' ? '⚠️' : '📊'} CONFIDENCE: ${review.confidence}`);
  console.log('='.repeat(60) + '\n');
}
