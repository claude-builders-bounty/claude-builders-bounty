#!/bin/bash
# =============================================================================
# claude-review — Claude Code sub-agent for PR review
# 
# Usage:
#   bash claude-review.sh --pr https://github.com/owner/repo/pull/123
#   bash claude-review.sh --pr https://github.com/owner/repo/pull/123 --claude
#
# Requires: python3, curl or GitHub token ($GITHUB_TOKEN)
# Optional: claude (Claude Code CLI) for AI-powered review
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLAUDE_MODE=""
PR_URL=""

while [ $# -gt 0 ]; do
  case "$1" in
    --pr) PR_URL="$2"; shift 2 ;;
    --claude) CLAUDE_MODE="--claude"; shift ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

if [ -z "$PR_URL" ]; then
  echo "Usage: bash claude-review.sh --pr <PR_URL> [--claude]"
  exit 1
fi

python3 "$SCRIPT_DIR/review.py" --pr "$PR_URL" $CLAUDE_MODE
echo ""
echo "---"
echo "_Review generated by claude-review — https://github.com/claude-builders-bounty_"
echo ""
echo "### How to post this review"
echo ""
echo "1. Copy the output above"
echo "2. Go to $PR_URL"
echo "3. Paste as a PR comment"
echo ""
echo "Or use the GitHub Action (see .github/workflows/pr-review.yml) for automation."
echo ""
echo "### Integration with Claude Code"
echo ""
echo "Add to CLAUDE.md:"
echo ""
echo '```'
echo "/pr-review --pr <URL>"
echo '```'
echo ""
echo "This runs the review sub-agent directly from Claude Code."
echo ""
echo "### Sample"
echo ""
echo '```bash'
echo 'bash claude-review.sh --pr https://github.com/claude-builders-bounty/claude-builders-bounty/pull/2755'
echo '```'
echo ""
echo "Outputs a full structured review."
echo ""
echo "### Requirements"
echo ""
echo "- Python 3.6+"
echo "- GitHub token (set GITHUB_TOKEN env var for higher rate limits)"
echo "- (Optional) Claude Code CLI for AI review: \`brew install claude-code\`"
echo ""
echo "_This is a Claude Builders Bounty submission — #4_"
