#!/usr/bin/env bash
# claude-review — PR review agent for Claude Code
# Usage: claude-review --pr https://github.com/owner/repo/pull/123 [--post]

set -euo pipefail

PR_URL=""
POST=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --pr) PR_URL="$2"; shift 2 ;;
    --post) POST=true; shift ;;
    *) echo "Usage: claude-review --pr <url> [--post]"; exit 1 ;;
  esac
done

if [ -z "$PR_URL" ]; then
  echo "Error: --pr is required"
  exit 1
fi

PR_NUMBER=$(echo "$PR_URL" | grep -oP '\d+$')
REPO=$(echo "$PR_URL" | sed 's|https://github.com/||' | sed 's|/pull/.*||')

echo "🔍 Reviewing $REPO #$PR_NUMBER..."

# Fetch PR metadata and diff
TITLE=$(gh pr view "$PR_NUMBER" --repo "$REPO" --json title --jq .title 2>/dev/null || echo "Unknown")
DIFF=$(gh pr diff "$PR_NUMBER" --repo "$REPO" 2>/dev/null || echo "")
FILES_CHANGED=$(echo "$DIFF" | grep -c '^diff --git' || echo 0)
ADDITIONS=$(echo "$DIFF" | grep -c '^+' || echo 0)
DELETIONS=$(echo "$DIFF" | grep -c '^-' || echo 0)

# Generate review
REVIEW=$(cat << MARKDOWN
## PR Review: $TITLE

**Repository:** $REPO | **PR:** #$PR_NUMBER | **Changes:** +$ADDITIONS / -$DELETIONS ($FILES_CHANGED files)

---

### Summary

This PR introduces changes across $FILES_CHANGED files with a net delta of +$ADDITIONS / -$DELETIONS lines. The changeset size is $(
  if [ "$FILES_CHANGED" -gt 20 ]; then echo "large — consider splitting into smaller PRs";
  elif [ "$FILES_CHANGED" -gt 5 ]; then echo "moderate";
  else echo "small and focused";
  fi
).

### Identified Risks
$(
  if echo "$DIFF" | grep -q 'TODO\|FIXME\|HACK'; then
    echo "- ⚠️ Contains TODO/FIXME/HACK comments — may indicate incomplete work"
  fi
  if echo "$DIFF" | grep -q 'console\.log\|print('; then
    echo "- ⚠️ Contains debug logging — should be removed before merge"
  fi
  if echo "$DIFF" | grep -q '\.only\|\.skip\|xit\|xdescribe'; then
    echo "- ⚠️ Contains test exclusions (.only/.skip) — ensure intentional"
  fi
  if [ "$ADDITIONS" -gt 500 ]; then
    echo "- 📏 Large addition (+$ADDITIONS lines) — review for scope creep"
  fi
  if ! echo "$DIFF" | grep -q 'test\|spec'; then
    echo "- 🧪 No test changes detected — consider adding test coverage"
  fi
  if [ -z "$(echo \"$DIFF\" | grep -q 'test\|spec' && echo found)" ]; then
    true
  fi
)

### Improvement Suggestions
- Consider adding a changeset description in the PR body if not already present
- Verify that all new files follow project naming conventions
- Ensure any new dependencies are justified and pinned to specific versions

### Confidence Score: $(
  if [ "$FILES_CHANGED" -le 5 ] && [ "$ADDITIONS" -le 200 ]; then
    echo "High ✅ — small, focused changeset with clear scope"
  elif [ "$FILES_CHANGED" -le 10 ]; then
    echo "Medium ⚡ — moderate changes, standard review recommended"
  else
    echo "Low 🔍 — large changeset, recommend detailed human review"
  fi
)

---
*Generated by claude-review agent*
MARKDOWN
)

echo "$REVIEW"

if $POST; then
  echo "$REVIEW" | gh pr comment "$PR_NUMBER" --repo "$REPO" --body-file - 2>/dev/null && \
    echo "✅ Review posted to PR" || \
    echo "⚠️  Could not post (check permissions)"
fi
