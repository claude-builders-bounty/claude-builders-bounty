#!/usr/bin/env bash
set -euo pipefail

# ──────────────────────────────────────────────────────────
# claude-review — Fetch a PR and produce a structured review
# Usage: claude-review --pr <pr-url-or-number>
# ──────────────────────────────────────────────────────────

PR=""
VERBOSE=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --pr|-p)
      PR="$2"
      shift 2
      ;;
    --verbose|-v)
      VERBOSE=true
      shift
      ;;
    *)
      echo "Usage: claude-review --pr <pr-url-or-number>"
      exit 1
      ;;
  esac
done

if [[ -z "$PR" ]]; then
  echo "Error: --pr is required"
  echo "Usage: claude-review --pr https://github.com/owner/repo/pull/123"
  exit 1
fi

# ── Parse PR argument ─────────────────────────────────────
# Accept either a full URL or a number (uses GITHUB_REPOSITORY env)

if [[ "$PR" =~ ^https://github\.com/([^/]+)/([^/]+)/pull/([0-9]+) ]]; then
  OWNER="${BASH_REMATCH[1]}"
  REPO="${BASH_REMATCH[2]}"
  PR_NUM="${BASH_REMATCH[3]}"
elif [[ "$PR" =~ ^[0-9]+$ ]]; then
  if [[ -z "${GITHUB_REPOSITORY:-}" ]]; then
    echo "Error: GITHUB_REPOSITORY not set. Use full URL or set GITHUB_REPOSITORY=owner/repo"
    exit 1
  fi
  OWNER="${GITHUB_REPOSITORY%/*}"
  REPO="${GITHUB_REPOSITORY#*/}"
  PR_NUM="$PR"
else
  echo "Error: Invalid PR format. Use: https://github.com/owner/repo/pull/123 or just 123 (with GITHUB_REPOSITORY set)"
  exit 1
fi

PR_REF="${OWNER}/${REPO}#${PR_NUM}"

# ── Fetch PR metadata ─────────────────────────────────────
if $VERBOSE; then echo "Fetching PR ${PR_REF}..." >&2; fi

PR_JSON=$(gh pr view "${PR_NUM}" --repo "${OWNER}/${REPO}" --json title,author,body,state,baseRefName,headRefName,additions,deletions,files,createdAt,updatedAt 2>/dev/null || {
  echo "Error: Could not fetch PR ${PR_REF}" >&2
  exit 1
})

TITLE=$(echo "$PR_JSON" | jq -r '.title')
AUTHOR=$(echo "$PR_JSON" | jq -r '.author.login // "unknown"')
STATE=$(echo "$PR_JSON" | jq -r '.state')
BASE_BRANCH=$(echo "$PR_JSON" | jq -r '.baseRefName')
HEAD_BRANCH=$(echo "$PR_JSON" | jq -r '.headRefName')
ADDITIONS=$(echo "$PR_JSON" | jq -r '.additions')
DELETIONS=$(echo "$PR_JSON" | jq -r '.deletions')
BODY=$(echo "$PR_JSON" | jq -r '.body // "No description provided."')
FILES_CHANGED=$(echo "$PR_JSON" | jq -r '.files | length')

if $VERBOSE; then echo "Title: ${TITLE}" >&2; fi

# ── Fetch PR diff ─────────────────────────────────────────
DIFF=$(gh pr diff "${PR_NUM}" --repo "${OWNER}/${REPO}" 2>/dev/null || true)
DIFF_LEN=$(echo "$DIFF" | wc -l | tr -d ' ')

# ── File analysis ─────────────────────────────────────────
FILE_TYPES=$(echo "$PR_JSON" | jq -r '.files[]?.path' | sed 's/.*\.//' | sort | uniq -c | sort -rn | head -5 || true)

# ── Generate structured review ───────────────────────────
# The diff is passed to Claude Code in the agent context
# This script fetches and formats the data; Claude does the analysis
print_review() {
  echo "## Review: ${PR_REF}"
  echo ""
  echo "**Title:** ${TITLE}"
  echo "**Author:** @${AUTHOR}  **State:** ${STATE}"
  echo "**Branch:** \`${HEAD_BRANCH}\` → \`${BASE_BRANCH}\`"
  echo "**Stats:** +${ADDITIONS}/-${DELETIONS} across ${FILES_CHANGED} files"
  echo ""

  if [[ -n "$FILE_TYPES" ]]; then
    echo "**File types:**"
    echo '```'
    echo "$FILE_TYPES"
    echo '```'
    echo ""
  fi

  echo "---"
  echo ""
  echo "### PR Description"
  echo ""
  echo "${BODY}"
  echo ""
  echo "---"
  echo ""
  echo "### Diff (${DIFF_LEN} lines)"
  echo ""
  echo '```diff'
  echo "$DIFF"
  echo '```'
  echo ""
  echo "---"
  echo ""
  echo "### Analysis Checklist"
  echo ""
  echo "Review each file below and note:"
  echo ""
  while IFS= read -r file_info; do
    FILE_PATH=$(echo "$file_info" | jq -r '.path')
    FILE_STATUS=$(echo "$file_info" | jq -r '.status')
    FILE_ADD=$(echo "$file_info" | jq -r '.additions')
    FILE_DEL=$(echo "$file_info" | jq -r '.deletions')
    echo "- **\`${FILE_PATH}\`** (${FILE_STATUS}, +${FILE_ADD}/-${FILE_DEL})"
  done < <(echo "$PR_JSON" | jq -c '.files[]')
  echo ""
  echo "---"
  echo ""
  echo "### Summary"
  echo "_Claude Code will analyze the diff above and summarize the changes._"
  echo ""
  echo "### Identified Risks"
  echo "_Claude Code will identify potential issues._"
  echo ""
  echo "### Improvement Suggestions"
  echo "_Claude Code will suggest improvements._"
  echo ""
  echo "### Confidence Score"
  echo "_Claude Code will assign High / Medium / Low._"
  echo ""
  echo "---"
  echo ""
  echo "> Generated by claude-review"
}

print_review
