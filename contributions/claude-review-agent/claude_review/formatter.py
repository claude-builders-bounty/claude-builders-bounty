"""Output formatting for review results."""

from .github_client import PRData
from .reviewer import ReviewResult


def format_markdown(pr: PRData, result: ReviewResult) -> str:
    """Format review result as structured Markdown."""
    risks_md = "\n".join(f"- {r}" for r in result.risks)
    suggestions_md = "\n".join(f"- {s}" for s in result.suggestions)

    return f"""# 🔍 PR Review: #{pr.number}

> **{pr.title}** by @{pr.author}
> {pr.url}

---

## 📋 Summary

{result.summary}

## ⚠️ Identified Risks

{risks_md}

## 💡 Improvement Suggestions

{suggestions_md}

## 🎯 Confidence Score: **{result.confidence}**

---

<details>
<summary>📊 PR Stats</summary>

| Metric | Value |
|--------|-------|
| Files Changed | {pr.files_changed} |
| Additions | +{pr.additions} |
| Deletions | -{pr.deletions} |
| Branch | `{pr.head_branch}` → `{pr.base_branch}` |

</details>

---
*Generated by [claude-review](https://github.com/intagold561/claude-review-agent) v1.0.0*
"""


def format_github_comment(pr: PRData, result: ReviewResult) -> str:
    """Format as a GitHub PR comment (more compact)."""
    risks_md = "\n".join(f"- {r}" for r in result.risks)
    suggestions_md = "\n".join(f"- {s}" for s in result.suggestions)

    return f"""## 🤖 Claude Review

**Summary:** {result.summary}

**Risks:**
{risks_md}

**Suggestions:**
{suggestions_md}

**Confidence:** {result.confidence}

---
*Automated review by claude-review v1.0.0*
"""
